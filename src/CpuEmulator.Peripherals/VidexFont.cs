namespace CpuEmulator.Peripherals;

/// <summary>A SYNTHETIC but genuinely LEGIBLE Videx Videoterm character ROM (256 glyphs x 8 rows = 2048
/// bytes) — the asset-free default the web Videx render streams when no VALID real Videx character ROM is
/// present. Each glyph is byte [code*8 + row]; bit 6 is the LEFTMOST of the 7-px Videx cell (the
/// <see cref="VidexVideoterm"/> render convention). The glyphs are real ASCII letterforms ported from the
/// public-domain <c>font8x8_basic</c> set (Daniel Hepper / Marcel Sondaar), so the streamed 80x24 frame
/// reads as a true CP/M-3 terminal in the browser — the <c>CP/M Version 3.0 ... BIOS R6/89</c> sign-on +
/// the <c>A&gt;</c> prompt are human-legible, and blank cells (space / non-printable) are all-black.
///
/// History: the prior synthetic font drew a code-dependent BOX-OUTLINE pattern per printable code — enough
/// "distinct ink" to satisfy an OCR-against-itself gate, but a STIPPLE field to a human eye, never a
/// readable console. This set replaces those box outlines with the real letterforms so the live web render
/// is cleanly legible. (The exact-fidelity option is the real Videx character ROM, injected via
/// <see cref="VidexVideoterm"/>'s ctor — but only when the cached file is a VALID font; a firmware-ROM dump
/// mis-placed at the char-ROM path is rejected and this legible default wins.)
///
/// The space ($20) is blank; every printable ASCII code $21-$7E carries its real glyph; non-printables and
/// codes outside $20-$7E are blank (the inverse of "inked") — the high bit is masked at render time so the
/// firmware's $A0-padded cells render as black spaces.</summary>
public static class VidexFont
{
    /// <summary>The 7-pixel-wide Videx character cell (bit 6..0 of each glyph row).</summary>
    public const int CellWidth = 7;

    /// <summary>The 8 active glyph rows the 2 KiB char ROM stores (the CRTC's 9-line cell, R9=$08, adds
    /// one blank descender line at render time — see VidexVideoterm.RenderInto).</summary>
    public const int GlyphRows = 8;

    // NOTE: Fallback is initialized AFTER Font8x8 below (static field initializers run in declaration order,
    // and Build() reads Font8x8) — see the field at the bottom of this type.

    /// <summary>Validate that a candidate 2 KiB char ROM is structurally a real FONT (not a firmware-ROM or
    /// garbage dump mis-placed at the char-ROM cache path — the exact failure that put a stipple field on the
    /// browser). A genuine character ROM ALWAYS has an all-zero space glyph ($20) and a clearly non-blank,
    /// distinct set of letter glyphs. The check: (1) the $20 space cell is fully blank, (2) the core
    /// uppercase letters A-Z carry real ink, and (3) those letters are not all the same bitmap. Returns false
    /// for the wrong length, a non-blank space, or a degenerate/blank letter band — in which case the caller
    /// uses the legible synthetic <see cref="Fallback"/> instead.</summary>
    public static bool LooksLikeFont(byte[]? rom)
    {
        if (rom is null || rom.Length != 256 * GlyphRows) return false;

        // (1) The space glyph ($20) must be entirely blank — a real font never inks the space, and a
        //     firmware/garbage dump almost never lands all-zero here (the observed bogus char ROM had
        //     0x00 0x00 0x01 0x20 0x5E 0x00 0xFE 0x90 at the space slot).
        for (int r = 0; r < GlyphRows; r++)
            if (rom[0x20 * GlyphRows + r] != 0) return false;

        // (2)+(3) The uppercase letters A-Z must each carry ink AND not collapse to one shared bitmap (a
        //         degenerate "font" that would tile one glyph). Hash each letter's 8 rows; require every
        //         letter inked and at least a dozen DISTINCT letter bitmaps across A-Z.
        var distinct = new HashSet<ulong>();
        for (int code = 0x41; code <= 0x5A; code++)
        {
            ulong bits = 0;
            int ink = 0;
            for (int r = 0; r < GlyphRows; r++)
            {
                byte row = rom[code * GlyphRows + r];
                bits = (bits << 8) | row;
                ink += System.Numerics.BitOperations.PopCount((uint)row);
            }
            if (ink == 0) return false;   // a real letter is never blank
            distinct.Add(bits);
        }
        return distinct.Count >= 12;      // A-Z must be visibly distinct letterforms, not one tiled shape
    }

    private static byte[] Build()
    {
        var rom = new byte[256 * GlyphRows];
        // Port font8x8_basic (ASCII $20-$7E) into the Videx cell. font8x8 stores each glyph as 8 rows with
        // bit 0 = LEFTMOST column; the Videx cell is 7-px with bit 6 = LEFTMOST (VidexVideoterm.RenderInto's
        // `0x40 >> gx` walk). Re-pack each row's low 7 columns: font8x8 bit b (0..6) -> Videx bit (6-b).
        // (font8x8's bit-7 column, used by a couple of glyphs like '_'/'*', is outside the 7-px Videx cell
        // and is clipped — exactly as a real 7-px Videx character cell would clip it.)
        for (int code = 0x20; code <= 0x7E; code++)
        {
            byte[] glyph = Font8x8[code - 0x20];
            for (int row = 0; row < GlyphRows; row++)
            {
                byte src = glyph[row];   // bit 0 = leftmost
                byte dst = 0;
                for (int col = 0; col < CellWidth; col++)   // columns 0..6 (the 7-px Videx cell)
                    if ((src & (1 << col)) != 0)
                        dst |= (byte)(0x40 >> col);          // Videx bit 6 = leftmost
                rom[code * GlyphRows + row] = dst;
            }
        }
        return rom;   // $20 (space) and all non-printables stay blank (all-zero) — the inverse of "inked".
    }

