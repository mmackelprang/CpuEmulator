using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis.CSharp;

namespace CpuEmulator.Generators;

internal static class CpuEmitter
{
    public static string Emit(SpecModel model)
    {
        bool hasPortOp = model.Instructions.Any(i => i.Class == InstructionClass.Port);
        bool hasHaltOp = model.Instructions.Any(
            i => i.Ops.Length > 0 && i.Ops[0].Kind == "Halt");

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("// Generated by CpuEmulator.Generators from the CPU specification.");
        sb.AppendLine("// The hand-written partial MUST provide: a constructor, Reset(),");
        sb.AppendLine("// SetIrqLine(bool), SetNmiLine(bool), byte ReadBus(uint address)");
        sb.AppendLine("// (which increments _cycles), WriteBus(uint, byte) (which increments _cycles),");
        sb.AppendLine("// HandleUndefinedOpcode(byte opcode), and");
        sb.AppendLine("// private partial bool TryServiceInterrupt() (return false when no interrupt is pending).");
        sb.AppendLine("// public partial bool InterruptPending (true when the next Step will service an interrupt).");
        if (hasPortOp)
        {
            // M3.2 (Ground truth A.4): a Port-class instruction (PortIn/PortOut) targets the Io bus.
            sb.AppendLine("// This CPU declares a Port-class instruction (IN/OUT), so the partial MUST also provide:");
            sb.AppendLine("//   byte ReadIo(uint port)  (the Io-bus read; charges the I/O cycle), and");
            sb.AppendLine("//   void WriteIo(uint port, byte value)  (the Io-bus write; charges the I/O cycle).");
            sb.AppendLine("// These are the Io analogues of ReadBus/WriteBus; the generated port bodies call them,");
            sb.AppendLine("// so a port op hits the Io space, NEVER the program/data space.");
        }
        if (hasHaltOp)
        {
            // M3.2 (Ground truth B): a CPU using Halt() owns a halted latch the generated Step consults.
            sb.AppendLine("// This CPU uses Halt() (HALT/STOP), so the partial MUST also provide:");
            sb.AppendLine("//   public partial bool Halted  (true while the halted latch is set),");
            sb.AppendLine("//   void IdleCycle()  (advances _cycles by one — the 'NOP while halted'), and");
            sb.AppendLine("//   a Halt() micro-op body that SETS the latch.");
            sb.AppendLine("// The latch MUST clear when an interrupt is serviced (in TryServiceInterrupt — the wake).");
        }
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine($"namespace {model.Namespace};");
        sb.AppendLine();
        sb.AppendLine($"public sealed partial class {model.CpuName} : CpuEmulator.Core.ICpuCore, CpuEmulator.Core.IMonitorSupport");
        sb.AppendLine("{");
        sb.AppendLine($"    public string Architecture => {SymbolDisplay.FormatLiteral(model.Architecture, quote: true)};");
        sb.AppendLine();
        sb.AppendLine("    private long _cycles;");
        sb.AppendLine("    public long CycleCount => _cycles;");
        var flags = FlagBitMap.From(model.Flags.Length > 0 ? model.Flags.Values : null);
        EmitBody(sb, model, flags);
        sb.AppendLine("}");
        return sb.ToString();
    }

    /// <summary>M4.1 (ADR 0003 Decision 1): the register backing-field C# type as a function of width.
    /// 8 → byte, 16 → ushort, 32 → uint. The 8/16 arms are UNCHANGED from the prior two-case ternary, so
    /// every 6502/Z80 register (all 8/16-bit) emits byte-identically (RegeneratedSpecTests guards it). The
    /// uint arm is the only new output and is reached ONLY by a register declaring Bits == 32 — a
    /// construct the 6502/Z80 specs never use. The parser caps Bits at {8,16,32}, so no other width
    /// reaches here.</summary>
    private static string FieldType(int bits) => bits <= 8 ? "byte" : bits <= 16 ? "ushort" : "uint";

    private static void EmitBody(StringBuilder sb, SpecModel model, FlagBitMap flags)
    {
        sb.AppendLine();
        foreach (var register in model.Registers)
        {
            if (register.HighHalf is { } high && register.LowHalf is { } low)
                // M3.4a (Ground truth A.3): a pair VIEW — NO backing field, a computed property over
                // the two 8-bit halves. Bidirectional: write a half then read the pair reflects it,
                // and vice versa, because the halves are the only storage.
                sb.AppendLine(
                    $"    public ushort {register.Name} {{ get => (ushort)(({high} << 8) | {low}); " +
                    $"set {{ {high} = (byte)(value >> 8); {low} = (byte)value; }} }}");
            else
                sb.AppendLine($"    public {FieldType(register.Bits)} {register.Name};");
        }

        string nameList = string.Join(", ", model.Registers.Select(r => $"\"{r.Name}\""));
        sb.AppendLine();
        sb.AppendLine($"    private static readonly string[] s_registerNames = [{nameList}];");
        sb.AppendLine("    public System.Collections.Generic.IReadOnlyList<string> RegisterNames => s_registerNames;");

        sb.AppendLine();
        sb.AppendLine("    public ulong GetRegister(string name) => name switch");
        sb.AppendLine("    {");
        foreach (var register in model.Registers)
            sb.AppendLine($"        \"{register.Name}\" => {register.Name},");
        sb.AppendLine("        _ => throw new System.ArgumentException($\"Unknown register '{name}'.\", nameof(name)),");
        sb.AppendLine("    };");

        sb.AppendLine();
        sb.AppendLine("    public void SetRegister(string name, ulong value)");
        sb.AppendLine("    {");
        sb.AppendLine("        switch (name)");
        sb.AppendLine("        {");
        foreach (var register in model.Registers)
        {
            string cast = FieldType(register.Bits);
            sb.AppendLine($"            case \"{register.Name}\": {register.Name} = unchecked(({cast})value); break;");
        }
        sb.AppendLine("            default: throw new System.ArgumentException($\"Unknown register '{name}'.\", nameof(name));");
        sb.AppendLine("        }");
        sb.AppendLine("    }");

        EmitExecution(sb, model, flags);
        EmitDisassembler(sb, model);
        EmitMonitorSupport(sb, model);
        EmitJitDescriptors(sb, model, flags);
        EmitJitTarget(sb, model);
        EmitDecodeWalk(sb, model);
    }

    /// <summary>The generated per-CPU JIT seam (J1) — the data-driven replacement for the 6502's baked
    /// FA/FP/FPC/MStep handles. Resolves the status/PC/accumulator fields by the SPEC's role-named
    /// registers, so the generic BlockCompiler&lt;TCpu&gt; never names a concrete CPU type. AOT-clean
    /// (reflection handles + delegate wraps, no Reflection.Emit). One per CPU, on the generated partial.</summary>
    private static void EmitJitTarget(StringBuilder sb, SpecModel model)
    {
        // Resolve the role-named registers from the spec (NOT hardcoded): the Status-role reg, the
        // ProgramCounter-role reg, and the accumulator (the first 8-bit general reg by convention — "A"
        // on both the 6502 and Z80; falls back to the status reg if a future CPU lacks an "A").
        // GUARD: the generic JIT requires BOTH a Status and a ProgramCounter register (the baked
        // _fp/_fpc handles). A minimal synthetic spec (decode/flag/port fixtures) may declare neither
        // — those CPUs are never driven through the generic JIT, so skip the JitTarget emission for
        // them (no StatusField/ProgramCounterField to resolve). The 6502 + Z80 + any real CPU declare
        // both, so they always get a JitTarget.
        var statusRegister = model.Registers.FirstOrDefault(r => r.Role == "Status");
        var pcRegisterModel = model.Registers.FirstOrDefault(r => r.Role == "ProgramCounter");
        if (statusRegister is null || pcRegisterModel is null)
            return;
        string status = statusRegister.Name;
        string pc = pcRegisterModel.Name;
        string acc = model.Registers.Any(r => r.Name == "A") ? "A" : status;
        string cpuType = model.CpuName;

        sb.AppendLine();
        sb.AppendLine("    /// <summary>The generated per-CPU JIT seam (J1) — the data-driven replacement for the");
        sb.AppendLine("    /// 6502's baked FA/FP/FPC/MStep handles. Resolves the status/PC/accumulator fields by the");
        sb.AppendLine("    /// SPEC's role-named registers, so the generic BlockCompiler&lt;TCpu&gt; never names a");
        sb.AppendLine("    /// concrete CPU type. AOT-clean (reflection handles + delegate wraps, no Reflection.Emit).</summary>");
        sb.AppendLine("    public static readonly CpuEmulator.Core.Jit.IJitTarget JitTarget = new GeneratedJitTarget();");
        sb.AppendLine();
        sb.AppendLine("    private sealed class GeneratedJitTarget : CpuEmulator.Core.Jit.IJitTarget");
        sb.AppendLine("    {");
        sb.AppendLine($"        public System.Type CpuType => typeof({cpuType});");
        sb.AppendLine($"        public System.Reflection.FieldInfo StatusField => typeof({cpuType}).GetField(\"{status}\")!;");
        sb.AppendLine($"        public System.Reflection.FieldInfo ProgramCounterField => typeof({cpuType}).GetField(\"{pc}\")!;");
        sb.AppendLine($"        public System.Reflection.FieldInfo AccumulatorField => typeof({cpuType}).GetField(\"{acc}\")!;");
        sb.AppendLine($"        public System.Reflection.MethodInfo StepMethod => typeof({cpuType}).GetMethod(\"Step\")!;");
        sb.AppendLine($"        public System.Reflection.MethodInfo AdvanceCyclesMethod => typeof({cpuType}).GetMethod(\"AdvanceCycles\", System.Reflection.BindingFlags.NonPublic | System.Reflection.BindingFlags.Instance)!;");
        sb.AppendLine($"        public System.Reflection.MethodInfo CycleCountGetter => typeof({cpuType}).GetProperty(\"CycleCount\")!.GetGetMethod()!;");
        sb.AppendLine($"        public System.Reflection.MethodInfo InterruptPendingGetter => typeof({cpuType}).GetProperty(\"InterruptPending\")!.GetGetMethod()!;");
        sb.AppendLine($"        public CpuEmulator.Core.Jit.DecodeResult Decode(CpuEmulator.Core.Jit.IFetchStream stream) => {cpuType}.Decode(stream);");
        sb.AppendLine($"        public CpuEmulator.Core.Jit.OpcodeDescriptor DescriptorFor(uint operationKey) => {cpuType}.DescriptorFor(operationKey);");
        sb.AppendLine($"        public System.Collections.Generic.IReadOnlyList<string> RegisterNames => s_registerNames;");
        sb.AppendLine("    }");
    }

    private static void EmitExecution(StringBuilder sb, SpecModel model, FlagBitMap flags)
    {
        var pcRegister = model.Registers.First(r => r.Role == "ProgramCounter");
        string pc = pcRegister.Name;
        string pcType = FieldType(pcRegister.Bits);

        // Status register (for SetNZ emission)
        var statusRegister = model.Registers.FirstOrDefault(r => r.Role == "Status");
        string? statusReg = statusRegister?.Name;

        // StackPointer register (stack/flow templates use its NAME; the parser guarantees
        // presence for stack/flow instructions via CPUGEN010)
        var spRegister = model.Registers.FirstOrDefault(r => r.Role == "StackPointer");
        string? spReg = spRegister?.Name;

        sb.AppendLine();
        sb.AppendLine("    // Instruction table parsed from the spec:");
        foreach (var instruction in model.Instructions)
            sb.AppendLine($"    //   0x{instruction.Opcode:X2} {instruction.Mnemonic} {instruction.Mode}");

        // M3.4e-3: a structured (multi-byte) CPU stashes the decode walk's low operand byte here so a
        // parameterless Op{key}() body (the DDCB/FDCB compound forms) can read the displacement the walk
        // already consumed WITHOUT a second bus access. The 6502 (Decode null) takes the degenerate Step
        // and never references this field, so it is emitted only for structured CPUs (byte-identity guard).
        if (model.Decode is not null)
        {
            sb.AppendLine();
            sb.AppendLine("    /// <summary>The low operand byte the decode walk consumed last (M3.4e-3): the");
            sb.AppendLine("    /// DDCB/FDCB compound displacement, surfaced to the parameterless compound body so it");
            sb.AppendLine("    /// need not re-read the bus (which would add a spurious traced access).</summary>");
            sb.AppendLine("    private byte _decodeOperandLo;");
        }

        sb.AppendLine();
        sb.AppendLine("    /// <summary>Execute one instruction — or service one pending interrupt at this");
        sb.AppendLine("    /// instruction boundary (the hook runs before the opcode fetch). Always advances");
        sb.AppendLine("    /// CycleCount by at least one.</summary>");
        sb.AppendLine("    public void Step()");
        sb.AppendLine("    {");
        sb.AppendLine("        if (TryServiceInterrupt())");
        sb.AppendLine("            return;");
        // M3.2 (Ground truth B.1): the halted guard is emitted ONLY when the model has a HaltOp.
        // TryServiceInterrupt ran first (it clears the latch on a serviced interrupt — the wake), so
        // when still halted, idle exactly one cycle (advancing CycleCount, NOT fetching). A CPU with
        // no HaltOp (the 6502) gets NEITHER line, so its Step is byte-identical (Ground truth E).
        bool hasHaltOp = model.Instructions.Any(
            i => i.Ops.Length > 0 && i.Ops[0].Kind == "Halt");
        if (hasHaltOp)
        {
            sb.AppendLine("        if (Halted)");
            sb.AppendLine("        {");
            sb.AppendLine("            IdleCycle();   // halted: idle one cycle — do NOT fetch (Ground truth B.1)");
            sb.AppendLine("            return;");
            sb.AppendLine("        }");
        }
        if (model.FieldGrammar is not null)
        {
            // M4.5a: the word-granular field-decode interpreter. Fetch the operword + extension words via the
            // live big-endian word stream (which reads the operword EXACTLY once — surfaced on __r.Operword,
            // so dispatch needs no second Read16 of PC), advance PC by the computed length, dispatch on the
            // decoded opIndex. Non-MOVE families route to HandleUndefinedOpcode (their bodies are M4.5b-d).
            sb.AppendLine("        var __stream = new CpuEmulator.Core.Jit.M68000FetchStream(_bus, PC);");
            sb.AppendLine("        var __r = Decode(__stream);");
            sb.AppendLine("        uint __operword = __r.Operword;               // the operword the fetch read once");
            sb.AppendLine("        // Each fetched word (operword + extension words) is a .w bus transaction worth 4 clocks.");
            sb.AppendLine("        // The fetch stream traced the Read16s (matching the vector's fetch transactions); charge their");
            sb.AppendLine("        // cycles here (the literal 4 keeps the generated Step self-contained — a synthetic FieldGrammar");
            sb.AppendLine("        // CPU has no hand-written WordAccessCycles constant).");
            sb.AppendLine("        _cycles += __stream.UnitsConsumed * 4;");
            sb.AppendLine("        // PC-relative EAs (d16(PC)/d8(PC,Xn)) are based on the address of the FIRST extension word");
            sb.AppendLine("        // = operword address + 2 (the operword is at the pre-advance PC). Capture it BEFORE the");
            sb.AppendLine("        // advance so ComputeEa's PcForEa reads the right base (the live PC moves past the whole insn).");
            sb.AppendLine("        _eaPcBase = PC + 2u;");
            sb.AppendLine("        PC += (uint)__r.Length;                       // advance past operword + extension words");
            sb.AppendLine("        if (__r.OperationKey == 0xFFFFFFFFu) { HandleUndefinedOpcode(unchecked((byte)__operword)); return; }");
            sb.AppendLine("        uint __opIndex = (__r.OperationKey >> 8) & 0xFFFFu;   // unpack opIndex from the key");
            sb.AppendLine("        uint __size = __r.OperationKey & 0xFFu;               // 0=b,1=w,2=l");
            sb.AppendLine("        uint __ea = __operword & 0x3Fu;");
            sb.AppendLine("        uint __srcMode = (__ea >> 3) & 7u, __srcReg = __ea & 7u;");
            sb.AppendLine("        switch (__opIndex)");
            sb.AppendLine("        {");
            // Emit one dispatch arm per MOVE-family opIndex, matched by the dataset operation name.
            EmitMoveDispatchArms(sb, model.FieldGrammar);
            sb.AppendLine("            default:");
            sb.AppendLine("                HandleUndefinedOpcode(unchecked((byte)__operword));   // M4.5b-d families");
            sb.AppendLine("                break;");
            sb.AppendLine("        }");
            sb.AppendLine("        _eaPcBase = 0u;   // clear the PC-relative base so the synthetic ComputeEaProbe's");
            sb.AppendLine("                          // \": PC\" fallback is valid again after a Step (review finding).");
        }
        else if (model.Decode is null)
        {
            // Degenerate (6502): the byte-fetch Step is UNCHANGED (Ground truth E). The per-op bodies
            // do their own ReadBus(PC); PC++; for the 6502 key == opcode so Execute(opcode) dispatches
            // on the resolved key — they are equal.
            sb.AppendLine($"        byte opcode = ReadBus({pc});");
            sb.AppendLine($"        {pc} = unchecked(({pcType})({pc} + 1));");
            sb.AppendLine("        Execute(opcode);");
        }
        else
        {
            // Structured CPU: dispatch on the resolved operation-key from the walk (the prefix/group/
            // ModR/M decode the per-op bodies cannot infer from a single byte). The synthetic fixture
            // exercises the DECODE walk; this keeps Step compiling key-based for a multi-byte CPU.
            sb.AppendLine($"        var __r = Decode(new CpuEmulator.Core.Jit.AddressSpaceFetchStream(_bus, {pc}));");
            sb.AppendLine($"        {pc} = unchecked(({pcType})({pc} + __r.Length));");
            // M3.4e-3: surface the walk's decoded low operand byte (the DDCB/FDCB compound displacement,
            // packed by the compound decode walk) to the parameterless body via a field — the body must
            // NOT re-read it from the bus (that would add a spurious traced bus access the per-T-state
            // TomHarte trace does not record; the d byte was already fetched once by the walk above).
            sb.AppendLine("        _decodeOperandLo = __r.Operands.Lo;");
            // M3.4a: charge the opcode-fetch T-state(s) — the decode walk reads them via the fetch
            // stream (which does NOT charge), so Step charges one cycle per consumed key byte. The
            // per-op body charges the remaining T-states (Ground truth G). The fetch-side hook lets a
            // CPU bump a refresh register (the Z80 R) — a partial method, elided when unimplemented so
            // the synthetic decode CPU is unaffected. The 6502 takes the degenerate branch above and
            // never sees this code (its generated Step is byte-identical).
            sb.AppendLine("        _cycles += __r.Length;");
            // The R-refresh bumps once per M1 (opcode-fetch) cycle, NOT per byte. For a base op (length 1)
            // or a plain prefixed op (length 2 = prefix + opcode, the displacement is read in-body) the M1
            // count equals __r.Length. But a 24-bit COMPOUND key (DDCB/FDCB, M3.4e-3) consumes 4 bytes
            // (DD CB d op) yet has only 2 M1 fetches — the two PREFIX bytes; the displacement + final
            // opcode are not M1 cycles. So R bumps by 2 there (vector-confirmed: dd cb __ NN.json R+2),
            // while _cycles still charges all 4 fetch cycles above.
            sb.AppendLine("        OnInstructionFetched(__r.OperationKey > 0xFFFF ? 2 : __r.Length);");
            sb.AppendLine("        Execute(__r.OperationKey);");
        }
        sb.AppendLine("    }");
        if (model.Decode is not null || model.FieldGrammar is not null)
        {
            sb.AppendLine();
            sb.AppendLine("    /// <summary>Fetch-side hook (M3.4a): called once per instruction after the opcode +");
            sb.AppendLine("    /// prefix bytes are consumed, with the count of key bytes fetched. A CPU may implement it");
            sb.AppendLine("    /// to bump a refresh register (the Z80 R increments its low 7 bits per fetch). Partial —");
            sb.AppendLine("    /// elided when unimplemented, so a structured CPU that needs no refresh is unaffected.</summary>");
            sb.AppendLine("    partial void OnInstructionFetched(int keyBytes);");
            sb.AppendLine();
            sb.AppendLine("    /// <summary>Interrupt-enable hook (M3.5-1): the EI micro-op body calls this");
            sb.AppendLine("    /// instead of writing the IFF latches directly, so the hand-written partial can");
            sb.AppendLine("    /// model the Z80 EI one-instruction delay. Partial — elided when unimplemented");
            sb.AppendLine("    /// (a structured CPU with no EI-delay is unaffected; the 6502 never emits EI).</summary>");
            sb.AppendLine("    partial void OnInterruptEnable();");
        }
        if (model.FieldGrammar is not null)
        {
            sb.AppendLine();
            sb.AppendLine("    // M4.5a: the MOVE-family op bodies — implemented by the hand-written M68000Cpu.Move partial.");
            sb.AppendLine("    // Classic `partial void` (implicitly private): elided when unimplemented (Task 3 has no body");
            sb.AppendLine("    // yet — the MOVE arms are no-ops), implemented by M68000Cpu.Move.cs from Task 4 onward.");
            sb.AppendLine("    partial void MoveExecute(uint operword, CpuEmulator.Core.Jit.DecodeResult r, uint size, uint srcMode, uint srcReg);");
            sb.AppendLine("    partial void MoveAExecute(uint operword, CpuEmulator.Core.Jit.DecodeResult r, uint size, uint srcMode, uint srcReg);");
            sb.AppendLine("    partial void MoveToSrExecute(uint operword, CpuEmulator.Core.Jit.DecodeResult r, uint srcMode, uint srcReg);");
            sb.AppendLine("    partial void MoveToCcrExecute(uint operword, CpuEmulator.Core.Jit.DecodeResult r, uint srcMode, uint srcReg);");
            sb.AppendLine("    partial void MoveFromSrExecute(uint operword, CpuEmulator.Core.Jit.DecodeResult r, uint srcMode, uint srcReg);");
            sb.AppendLine("    partial void MoveUspExecute(uint operword);");
            sb.AppendLine();
            sb.AppendLine("    // M4.5b: the integer-ALU op bodies — implemented by the hand-written M68000Cpu.Alu partial.");
            sb.AppendLine("    // Classic `partial void` (implicitly private): elided when unimplemented (so the dispatch arms");
            sb.AppendLine("    // are no-ops until each family's body lands), implemented by M68000Cpu.Alu.cs.");
            foreach (var name in new[] {
                "Add","Sub","And","Or","Eor","Cmp","AddA","SubA","CmpA",
                "AddI","SubI","AndI","OrI","EorI","CmpI","AddQ","SubQ",
                "Neg","NegX","Not","Clr","Tst","Ext","AddX","SubX","MulU","MulS","DivU","DivS" })
            {
                sb.AppendLine($"    partial void {name}Execute(uint operword, CpuEmulator.Core.Jit.DecodeResult r, uint size, uint srcMode, uint srcReg);");
            }
        }

        // ── The IM-expressibility contract (M3.2 Ground truth C.3 — DOCUMENTED, no code) ──────────
        // The interrupt seam is ALREADY generic (Ground truth C): servicing is the hand-written
        // partial's TryServiceInterrupt; InterruptPending is the partial's own predicate; both tiers
        // boundary-sample the predicate policy-blind; the line is wired-OR. M3.2 adds ZERO interrupt
        // machinery. A CPU's TryServiceInterrupt MAY therefore implement ANY boundary-sampled
        // interrupt policy WITHOUT a framework change:
        //   • a fixed vector (6502: $FFFA/$FFFE);
        //   • a mode-selected vector (Z80 IM 0/1/2 — device-supplied opcode / fixed RST 38h /
        //     I-register high byte + a device-supplied table-index low byte; the interrupt-acknowledge
        //     byte is read via ReadIo, the Io-bus reachability item (1) delivers — the ONE enabling
        //     change, M3.2);
        //   • an NMI with its own vector;
        //   • a vector table (8086 IVT) — "exactly as the 6502 does, no Core change".
        // It performs the full service bus sequence itself (charging cycles via ReadBus/WriteBus),
        // clears any halted latch (the HALT/STOP wake), and returns true. The generated side is
        // policy-blind: it only calls the hook and, if it returns false, proceeds to the
        // (halt-or-)fetch path. This note is a SOURCE comment (for the M3.4 author), NOT emitted into
        // the generated output — so the 6502's generated .g.cs is byte-identical (Ground truth E).
        // The synthetic SyntheticHaltInterruptTests proves a NON-6502 (table-vectored) shape against
        // this UNCHANGED seam — the positive genericity finding: nothing here needs a Core change.
        sb.AppendLine();
        sb.AppendLine("    /// <summary>Interrupt-service hook, called at every instruction boundary before the");
        sb.AppendLine("    /// opcode fetch. The hand-written partial implements the CPU's interrupt policy and");
        sb.AppendLine("    /// MUST return false when nothing is pending. When it services an interrupt it performs");
        sb.AppendLine("    /// the full bus sequence itself (charging cycles via ReadBus/WriteBus) and returns true;");
        sb.AppendLine("    /// Step then ends without fetching an opcode.</summary>");
        sb.AppendLine("    private partial bool TryServiceInterrupt();");

        // Halted is part of the IMonitorSupport surface (the JIT dispatcher's J6 halted fast path
        // queries a uniform Halted on the inner CPU). A CPU that uses Halt() declares a
        // `partial bool Halted` whose body the hand-written partial owns (the latch); a CPU with NO
        // HALT op gets a generated constant-false Halted, so EVERY generated CPU satisfies the
        // interface without a hand-written hook (the 6502's former hand-written `Halted => false` is
        // now generated here — one less hand-written member, and synthetic CPUs compile uniformly).
        if (hasHaltOp)
        {
            sb.AppendLine();
            sb.AppendLine("    /// <summary>True while the halted latch is set (M3.2 Ground truth B). The hand-written");
            sb.AppendLine("    /// partial owns the latch (set by the Halt() micro-op's DoHalt(), cleared in");
            sb.AppendLine("    /// TryServiceInterrupt — the wake). Step consults this to idle a cycle instead of");
            sb.AppendLine("    /// fetching.</summary>");
            sb.AppendLine("    public partial bool Halted { get; }");
        }
        else
        {
            sb.AppendLine();
            sb.AppendLine("    /// <summary>A CPU with no HALT instruction never enters the halted state (M3.2 Ground");
            sb.AppendLine("    /// truth B), so Halted is a constant false — the JIT dispatcher's halted fast path branch");
            sb.AppendLine("    /// is dead for it (byte-identical JIT). Generated so every CPU satisfies IMonitorSupport.</summary>");
            sb.AppendLine("    public bool Halted => false;");
        }

        sb.AppendLine();
        sb.AppendLine("    public void Run(ref long cycleBudget)");
        sb.AppendLine("    {");
        sb.AppendLine("        while (cycleBudget > 0)");
        sb.AppendLine("        {");
        sb.AppendLine("            long before = _cycles;");
        sb.AppendLine("            Step();");
        sb.AppendLine("            cycleBudget -= _cycles - before;");
        sb.AppendLine("        }");
        sb.AppendLine("    }");

        // Dispatch parameter: the 6502 (degenerate) dispatches on the fetched opcode BYTE (key ==
        // opcode — byte-identical to before). A structured CPU dispatches on the opaque uint key the
        // walk resolved (the per-op methods are named by OperationKey to disambiguate prefixed/bare/
        // group rows that share an opcode byte). The case-label key is OperationKey in both — for the
        // 6502 OperationKey == opcode (≤ 0xFF) so the emitted arms are textually identical.
        bool keyedDispatch = model.Decode is not null || model.FieldGrammar is not null;
        string execParam = keyedDispatch ? "uint opcode" : "byte opcode";
        sb.AppendLine();
        sb.AppendLine($"    private void Execute({execParam})");
        sb.AppendLine("    {");
        sb.AppendLine("        switch (opcode)");
        sb.AppendLine("        {");
        foreach (var instruction in model.Instructions)
            sb.AppendLine($"            case 0x{instruction.OperationKey:X2}: Op{instruction.OperationKey:X2}(); break;");
        sb.AppendLine("            default:");
        sb.AppendLine(keyedDispatch
            ? "                HandleUndefinedOpcode(unchecked((byte)opcode));"
            : "                HandleUndefinedOpcode(opcode);");
        sb.AppendLine("                break;");
        sb.AppendLine("        }");
        sb.AppendLine("    }");

        // Emit all per-opcode methods (named by OperationKey — for the 6502 key == opcode, so OpA9
        // etc. are byte-identical method names). `structured` = a declared DecodeStructure (the Z80);
        // the degenerate (6502) CPU passes false so its register/implied bodies are byte-identical.
        // (A FieldGrammar CPU has zero instruction rows in M4.3a, so this loop is empty.)
        bool structured = model.Decode is not null;
        foreach (var instruction in model.Instructions)
            EmitOpcodeMethod(sb, instruction, pc, pcType, statusReg, spReg, flags, structured);
    }

    private static void EmitOpcodeMethod(
        StringBuilder sb,
        InstructionModel instruction,
        string pc,
        string pcType,
        string? statusReg,
        string? spReg,
        FlagBitMap flags,
        bool structured)
    {
        // Classification is carried on the model — the parser classified it once (CPUGEN010).
        // The emitter consumes instruction.Class directly; no parallel classifier here.
        InstructionClass opClass = instruction.Class;
        bool isZ80 = opClass is InstructionClass.Z80Alu or InstructionClass.Z80Ld
            or InstructionClass.Z80Stack or InstructionClass.Z80Exchange
            or InstructionClass.Z80Flow or InstructionClass.Z80Misc
            or InstructionClass.Z80Rot or InstructionClass.Z80Bit
            or InstructionClass.Z80EdIo or InstructionClass.Z80EdOp
            or InstructionClass.Z80EdBlock or InstructionClass.Z80Indexed
            or InstructionClass.Z80DdCb;
        int cycleCount = isZ80
            ? Z80Cycles(instruction.Mode, opClass, instruction.Ops.Length > 0 ? instruction.Ops[0].Kind : "")
            : ComputeCycles(instruction.Mode, opClass);
        bool isPageCross = instruction.Mode is "AbsoluteX" or "AbsoluteY" or "IndirectY"
            && opClass is InstructionClass.Load or InstructionClass.Alu;
        string cycleStr = (opClass == InstructionClass.Branch) ? "2-4 cycles"
            : isPageCross ? $"{cycleCount}-{cycleCount + 1} cycles (+1 on page cross)"
            : (opClass == InstructionClass.Stack) ? ComputeStackCycleStr(instruction.Ops)
            : (opClass == InstructionClass.Flow) ? ComputeFlowCycleStr(instruction.Ops)
            : $"{cycleCount} cycles";

        // Method name keyed by OperationKey: for the 6502 key == opcode (≤ 0xFF) so OpA9 etc. are
        // byte-identical; a structured CPU's prefixed/group rows get distinct names (Op CB10, Op 7B0).
        sb.AppendLine();
        sb.AppendLine($"    /// <summary>0x{instruction.Opcode:X2} {instruction.Mnemonic} {instruction.Mode} — {cycleStr}.</summary>");
        sb.AppendLine($"    private void Op{instruction.OperationKey:X2}()");
        sb.AppendLine("    {");

        // M3.4e-2: a DD/FD prefix is a non-flag-writing M1 fetch, so by the documented Q lifecycle it
        // sets Q = 0 BEFORE the inner opcode runs. Only SCF/CCF READ Q mid-body (the X/Y quirk uses
        // (Q ^ F) | A) — for a DD/FD-prefixed SCF/CCF (e.g. DD 37 / DD 3F, inert) the prefix has already
        // zeroed Q, so the seeded q is ignored. Reset Q = 0 up front for every prefixed row; non-Q
        // ops are unaffected (they overwrite Q at the body's end). Vector-confirmed against dd/fd 37/3f.
        bool ddFdPrefixed = instruction.OperationKey is >= 0xDD00 and <= 0xDDFF
                         or (>= 0xFD00 and <= 0xFDFF)
                         or (>= 0xDDCB00 and <= 0xDDCBFF)     // M3.4e-3: the DDCB compound key range (H2)
                         or (>= 0xFDCB00 and <= 0xFDCBFF);    // M3.4e-3: the FDCB compound key range (H2)
        if (structured && ddFdPrefixed)
            sb.AppendLine("        Q = 0;   // DD/FD prefix M1 zeroes Q before the inner opcode (SCF/CCF quirk)");

        switch (opClass)
        {
            case InstructionClass.Load:
                EmitLoadBody(sb, instruction, pc, pcType, statusReg, flags, structured);
                break;
            case InstructionClass.Register:
                EmitRegisterBody(sb, instruction, pc, statusReg, flags, structured);
                break;
            case InstructionClass.Store:
                EmitStoreBody(sb, instruction, pc, pcType);
                break;
            case InstructionClass.Jump:
                EmitJumpBody(sb, instruction, pc, pcType);
                break;
            case InstructionClass.Branch:
                EmitBranchBody(sb, instruction, pc, pcType, statusReg, flags);
                break;
            case InstructionClass.Alu:
                EmitAluBody(sb, instruction, pc, pcType, statusReg);
                break;
            case InstructionClass.Rmw:
                EmitRmwBody(sb, instruction, pc, pcType, statusReg);
                break;
            case InstructionClass.Stack:
                EmitStackBody(sb, instruction, pc, statusReg, spReg);
                break;
            case InstructionClass.Flow:
                EmitFlowBody(sb, instruction, pc, pcType, statusReg, spReg);
                break;
            case InstructionClass.Port:
                EmitPortBody(sb, instruction, pc, pcType, structured);
                break;
            // ── M3.4a Z80 classes ──
            case InstructionClass.Z80Alu:
                EmitZ80AluBody(sb, instruction, pc, pcType, statusReg, flags);
                break;
            case InstructionClass.Z80Ld:
                EmitZ80LdBody(sb, instruction, pc, pcType);
                break;
            case InstructionClass.Z80Stack:
                EmitZ80StackBody(sb, instruction, pc, spReg);
                break;
            case InstructionClass.Z80Exchange:
                EmitZ80ExchangeBody(sb, instruction, pc, spReg);
                break;
            case InstructionClass.Z80Flow:
                EmitZ80FlowBody(sb, instruction, pc, pcType, statusReg, spReg, flags);
                break;
            case InstructionClass.Z80Misc:
                EmitZ80MiscBody(sb, instruction, pc, statusReg, flags);
                break;
            // ── M3.4b CB plane + rotate-accumulators ──
            case InstructionClass.Z80Rot:
                EmitZ80RotBody(sb, instruction, pc, pcType, statusReg, flags);
                break;
            case InstructionClass.Z80Bit:
                EmitZ80BitBody(sb, instruction, pc, statusReg, flags);
                break;
            // ── M3.4c ED-core classes (classification only — STUB bodies, real behavior in B-Tasks 2-7) ──
            case InstructionClass.Z80EdIo:
                EmitZ80EdIoBody(sb, instruction, pc, statusReg, flags);
                break;
            case InstructionClass.Z80EdOp:
                EmitZ80EdOpBody(sb, instruction, pc, pcType, statusReg, spReg, flags);
                break;
            case InstructionClass.Z80EdBlock:
                EmitZ80EdBlockBody(sb, instruction, pc, pcType, statusReg, flags);
                break;
            // ── M3.4e-2 DD/FD indexed plane ──
            case InstructionClass.Z80Indexed:
                EmitZ80IndexedBody(sb, instruction, pc, pcType, statusReg, flags);
                break;
            // ── M3.4e-3 DDCB/FDCB compound plane ──
            case InstructionClass.Z80DdCb:
                EmitZ80DdCbBody(sb, instruction, pc, pcType, statusReg, flags);
                break;
            default:
                throw new System.InvalidOperationException(
                    $"emitter has no body template for class '{opClass}' (opcode 0x{instruction.Opcode:X2})");
        }

        // M3.4e-2: the DD/FD INERT/half/16-bit ops REUSE the base emit arms (G6), which compute their
        // T-state total from the BASE op (Z80Cycles) and balance against a 1-byte opcode fetch. But a
        // DD/FD-prefixed op pays an EXTRA M1 (the prefix fetch = +4 T) and Step charges 2 key bytes
        // (prefix + opcode) rather than 1. Net surcharge = +4 (prefix M1) − 1 (the extra key byte Step
        // already charged) = +3 internal T-states. The Z80Indexed arms compute their own vector-pinned
        // totals (already accounting for the 2-byte key fetch), so they are EXCLUDED. M3.4e-3: the Z80DdCb
        // compound arms likewise self-account their full T-state total (subtracting Step's 4 key bytes),
        // so they are EXCLUDED too. Confirmed against the vectors: DD 04 = 8 T (base 4 + 4), DD 09 = 15 T,
        // DD EA = 14 T; the compound DD CB d 06 = 23 T (self-accounted, no surcharge).
        if (ddFdPrefixed && opClass is not (InstructionClass.Z80Indexed or InstructionClass.Z80DdCb))
            sb.AppendLine("        _cycles += 3;   // DD/FD prefix M1 surcharge (+4 prefix − 1 extra key byte)");

        // M3.4b: the cross-instruction Q lifecycle. Every Z80 op sets Q at the end: Q = F if it wrote
        // flags, else Q = 0. SCF/CCF read the PREVIOUS Q (seeded as pre-state by the harness / the prior
        // instruction). The 6502 has no Z80 class, so this never fires for it (Q is undeclared there).
        // Every Z80 op BODY falls through to here (no generated body emits an early return), so this
        // Q-write is always reached on every exit path — incl. the conditional flow forms (JP/JR/CALL/RET
        // cc), whose generated bodies use `if (...) { ... }` then fall through, never `return`.
        // M3.4c (Piece A): the Q lifecycle is UNIVERSAL on a structured (Z80) CPU — every op sets Q,
        // including the shared 6502-shaped classes the base plane reuses (LD r,r' = Register → Q=0).
        // `structured` is Z80-only (model.Decode is not null), so the 6502 (Decode null) never sets Q.
        if (structured)
            sb.AppendLine(Z80WritesFlags(opClass, instruction)
                ? $"        Q = {statusReg ?? "F"};"
                : "        Q = 0;");

        sb.AppendLine("    }");
    }

    /// <summary>Does this Z80 instruction WRITE the flag word (→ Q = F) or not (→ Q = 0)? Z80Alu writes
    /// flags EXCEPT Inc16/Dec16 (the 16-bit INC/DEC set none); Z80Misc writes EXCEPT Di/Ei; Z80Rot
    /// always writes; Z80Bit writes only for BIT (RES/SET set none); Z80EdIo writes only for EdIn (IN
    /// r,(C) sets S/Z/Y/X/P; OUT (C),r sets none); Z80Ld/Stack/Exchange/Flow never.</summary>
    private static bool Z80WritesFlags(InstructionClass cls, InstructionModel insn)
    {
        string kind = insn.Ops.Length > 0 ? insn.Ops[0].Kind : "";
        return cls switch
        {
            InstructionClass.Z80Alu => kind is not ("Inc16" or "Dec16"),
            InstructionClass.Z80Misc => kind is not ("Di" or "Ei"),
            InstructionClass.Z80Rot => true,
            InstructionClass.Z80Bit => Unquote(insn.Ops[0].Args[0]) == "BIT",
            InstructionClass.Z80EdIo => kind == "EdIn",   // IN sets flags; OUT does not
            InstructionClass.Z80EdOp => kind switch
            {
                "EdAdcSbc16" or "EdNeg" or "EdRrdRld" => true,
                "EdLdIaRa" => Unquote(insn.Ops[0].Args[0]) is "A_I" or "A_R",  // LD A,I/A,R set flags; I,A/R,A don't
                _ => false,   // EdLdNnRp / EdRetn / EdIm / EdNop write no flags
            },
            InstructionClass.Z80EdBlock => true,   // every block op writes F
            // M3.4e-2: ALU + INC/DEC (IX+d) write F; LD r,(IX+d) / (IX+d),r / (IX+d),n do not.
            InstructionClass.Z80Indexed => kind is "DdFdAluIndexed" or "DdFdIncDecIndexed",
            // M3.4e-3: rotate/shift + BIT (IX+d) write F (Q = F); RES/SET preserve F and end with Q = 0
            // (vector-confirmed: dd cb __ 86/80/c6 — F unchanged, q final = 0). Per-op-family, mirroring
            // the Z80Bit arm above (BIT writes F; RES/SET do not).
            InstructionClass.Z80DdCb => Unquote(insn.Ops[0].Args[0]) is not ("RES" or "SET"),
            _ => false,   // Z80Ld / Z80Stack / Z80Exchange / Z80Flow
        };
    }

    private static int ComputeCycles(string mode, InstructionClass opClass) => (mode, opClass) switch
    {
        // 1 (opcode fetch) + template cycles
        ("Implied", InstructionClass.Register) => 2,           // +1 dummy read
        ("Implied", InstructionClass.Stack) => 2,              // varies (push=3, pull=4) — see doc string
        ("Implied", InstructionClass.Flow) => 2,               // varies (rts=6) — see doc string
        ("Immediate", _) => 2,                                 // +1 operand read
        ("ZeroPage", InstructionClass.Load) => 3,              // +1 addr +1 data
        ("ZeroPage", InstructionClass.Store) => 3,             // +1 addr +1 write
        ("ZeroPage", InstructionClass.Alu) => 3,               // alu = load shape
        ("ZeroPage", InstructionClass.Rmw) => 5,               // +1 addr +1 data +1 dummy-write +1 write
        ("ZeroPageX", InstructionClass.Load) => 4,             // +1 addr +1 dummy +1 data
        ("ZeroPageX", InstructionClass.Store) => 4,            // +1 addr +1 dummy +1 write
        ("ZeroPageX", InstructionClass.Alu) => 4,              // alu = load shape
        ("ZeroPageX", InstructionClass.Rmw) => 6,              // +1 addr +1 dummy +1 data +1 dummy-write +1 write
        ("ZeroPageY", InstructionClass.Load) => 4,             // +1 addr +1 dummy +1 data
        ("ZeroPageY", InstructionClass.Store) => 4,            // +1 addr +1 dummy +1 write
        ("ZeroPageY", InstructionClass.Alu) => 4,              // alu = load shape
        ("Absolute", InstructionClass.Load) => 4,              // +1 lo +1 hi +1 data
        ("Absolute", InstructionClass.Store) => 4,             // +1 lo +1 hi +1 write
        ("Absolute", InstructionClass.Alu) => 4,               // alu = load shape
        ("Absolute", InstructionClass.Jump) => 3,              // +1 lo +1 hi
        ("Absolute", InstructionClass.Rmw) => 6,               // +1 lo +1 hi +1 data +1 dummy-write +1 write
        ("Absolute", InstructionClass.Flow) => 6,              // JSR = 6 cycles
        ("AbsoluteX", InstructionClass.Load) => 4,             // 4-5 (+1 cross) — variable
        ("AbsoluteX", InstructionClass.Store) => 5,            // always 5 (dummy read)
        ("AbsoluteX", InstructionClass.Alu) => 4,              // 4-5 (+1 cross) — variable
        ("AbsoluteX", InstructionClass.Rmw) => 7,              // always-dummy read + double-write = 7
        ("AbsoluteY", InstructionClass.Load) => 4,             // 4-5 (+1 cross) — variable
        ("AbsoluteY", InstructionClass.Store) => 5,            // always 5 (dummy read)
        ("AbsoluteY", InstructionClass.Alu) => 4,              // 4-5 (+1 cross) — variable
        ("IndirectX", InstructionClass.Load) => 6,             // 6 cycles
        ("IndirectX", InstructionClass.Store) => 6,            // 6 cycles
        ("IndirectX", InstructionClass.Alu) => 6,              // alu = load shape
        ("IndirectY", InstructionClass.Load) => 5,             // 5-6 (+1 cross) — variable
        ("IndirectY", InstructionClass.Store) => 6,            // always 6 (dummy read)
        ("IndirectY", InstructionClass.Alu) => 5,              // 5-6 (+1 cross) — variable
        ("Indirect", InstructionClass.Jump) => 5,              // 5 cycles (JMP indirect)
        ("Accumulator", InstructionClass.Rmw) => 2,            // +1 dummy read; operate on A
        ("Relative", InstructionClass.Branch) => 0,            // variable: 2/3/4 — doc string says "2-4 cycles"
        // Port (M3.2): opcode fetch + (the (n) operand fetch) + the Io access. (C) form has no operand.
        ("IoPortImmediate", InstructionClass.Port) => 3,       // opcode + (n) operand + Io access
        ("IoPortIndirect", InstructionClass.Port) => 2,        // opcode + Io access (port from a reg)
        // M3.4a: Z80 register-shape modes reused by the 6502 Load/Store/Register/Jump classes (the
        // doc-string cycle hint; the body's real T-state accounting comes from Z80LoadStoreInternal).
        ("RegisterIndirect", InstructionClass.Load) => 7,      // LD r,(HL)
        ("RegisterIndirect", InstructionClass.Store) => 7,     // LD (HL),r
        ("ExtendedAddress", InstructionClass.Load) => 13,      // LD A,(nn)
        ("ExtendedAddress", InstructionClass.Store) => 13,     // LD (nn),A
        ("Register", InstructionClass.Load) => 4,
        ("Register", InstructionClass.Register) => 4,          // LD r,r' (Transfer in Register mode)
        ("ExtendedAddress", InstructionClass.Jump) => 10,      // JP nn (reuses Jump)
        ("RegisterIndirect", InstructionClass.Jump) => 4,      // JP (HL) (reuses Jump)
        _ => throw new System.InvalidOperationException(
            $"emitter has no cycle count for mode '{mode}' / class '{opClass}'"),
    };

    /// <summary>The Z80 base-plane T-state total for an instruction, keyed by (mode, class, op-kind)
    /// — the dataset's `cycles` field is deterministic from those three across the base plane (Ground
    /// truth G). For conditional flow this returns the NOT-TAKEN base; the emitted body adds the taken
    /// penalty (parallel to the 6502 branch +1). The 6502 never reaches this (it has no Z80 class).</summary>
    private static int Z80Cycles(string mode, InstructionClass cls, string opKind) => (cls, opKind, mode) switch
    {
        // ── 8-bit ALU: ADD A,r / INC r etc. ──
        (InstructionClass.Z80Alu, "Add16", _) => 11,                       // ADD HL,rr
        (InstructionClass.Z80Alu, "Inc16", _) => 6,                        // INC rr
        (InstructionClass.Z80Alu, "Dec16", _) => 6,                        // DEC rr
        (InstructionClass.Z80Alu, "IncMem8", _) => 11,                     // INC (HL)
        (InstructionClass.Z80Alu, "DecMem8", _) => 11,                     // DEC (HL)
        (InstructionClass.Z80Alu, _, "Register") => 4,                     // ADD A,r ; INC r ; DEC r
        (InstructionClass.Z80Alu, _, "RegisterIndirect") => 7,             // ADD A,(HL)
        (InstructionClass.Z80Alu, _, "Immediate") => 7,                    // ADD A,n
        // ── 16-bit LD ──
        (InstructionClass.Z80Ld, "Load16", "ImmediateExtended") => 10,     // LD rr,nn
        (InstructionClass.Z80Ld, "Store16", "ExtendedAddress") => 16,      // LD (nn),HL
        (InstructionClass.Z80Ld, "LoadMem16", "ExtendedAddress") => 16,    // LD HL,(nn)
        (InstructionClass.Z80Ld, "StoreImm8", _) => 10,                    // LD (HL),n (Immediate mode)
        // ── pair stack ──
        (InstructionClass.Z80Stack, "Push16", _) => 11,
        (InstructionClass.Z80Stack, "Pop16", _) => 10,
        // ── exchange ──
        (InstructionClass.Z80Exchange, "ExSpHl", _) => 19,                 // EX (SP),HL
        (InstructionClass.Z80Exchange, _, _) => 4,                         // EX DE,HL ; EX AF,AF' ; EXX
        // ── flow (NOT-TAKEN base for conditional forms) ──
        (InstructionClass.Z80Flow, "JumpIndirect", _) => 4,                // JP (HL)
        (InstructionClass.Z80Flow, "JumpAbs", _) => 10,                    // JP nn
        (InstructionClass.Z80Flow, "CallAbs", _) => 17,                    // CALL nn
        (InstructionClass.Z80Flow, "Ret", _) => 10,                        // RET
        (InstructionClass.Z80Flow, "JumpIf", _) => 10,                     // JP cc,nn (always 10)
        (InstructionClass.Z80Flow, "RelJump", _) => 12,                    // JR d
        (InstructionClass.Z80Flow, "RelJumpIf", _) => 7,                   // JR cc,d not-taken
        (InstructionClass.Z80Flow, "Djnz", _) => 8,                        // DJNZ not-taken
        (InstructionClass.Z80Flow, "CallIf", _) => 10,                     // CALL cc,nn not-taken
        (InstructionClass.Z80Flow, "RetCc", _) => 5,                       // RET cc not-taken
        (InstructionClass.Z80Flow, "Rst", _) => 11,                        // RST n
        // ── misc (Implied; all 4 T-states) ──
        (InstructionClass.Z80Misc, _, _) => 4,
        // ── rotate-accumulators (Implied, 4 T) + CB rotate/shift (Bit mode) ──
        (InstructionClass.Z80Rot, "Rlca", _) => 4,
        (InstructionClass.Z80Rot, "Rrca", _) => 4,
        (InstructionClass.Z80Rot, "Rla", _) => 4,
        (InstructionClass.Z80Rot, "Rra", _) => 4,
        (InstructionClass.Z80Rot, "CbRotate", "Bit") => 8,   // base; the (HL) form overrides to 15 in-body
        (InstructionClass.Z80Bit, _, _) => 8,    // placeholder — real cycles in Task 6/7
        (InstructionClass.Z80EdIo, _, _) => 12,   // placeholder — real cycles in B-Task 2
        (InstructionClass.Z80EdOp, "EdAdcSbc16", _) => 15,
        (InstructionClass.Z80EdOp, "EdLdNnRp", _) => 20,
        (InstructionClass.Z80EdOp, "EdNeg", _) => 8,
        (InstructionClass.Z80EdOp, "EdRetn", _) => 14,
        (InstructionClass.Z80EdOp, "EdIm", _) => 8,
        (InstructionClass.Z80EdOp, "EdLdIaRa", _) => 9,
        (InstructionClass.Z80EdOp, "EdRrdRld", _) => 18,
        (InstructionClass.Z80EdOp, "EdNop", _) => 8,
        (InstructionClass.Z80EdBlock, _, _) => 16,   // placeholder — base/final cycles; +5 on repeat in body
        // ── M3.4e-2 DD/FD indexed plane (vector-pinned totals) ──
        (InstructionClass.Z80Indexed, "DdFdIncDecIndexed", _) => 23,   // INC/DEC (IX+d)
        (InstructionClass.Z80Indexed, _, _) => 19,                     // LD r,(IX+d)/(IX+d),r/(IX+d),n ; ALU A,(IX+d)
        // ── M3.4e-3 DDCB/FDCB compound plane (descriptor base; the body self-accounts the interpreter
        // total per-family: rotate/shift + RES/SET = 23 T, BIT = 20 T — vector-pinned in EmitZ80DdCb*) ──
        (InstructionClass.Z80DdCb, _, _) => 23,
        _ => throw new System.InvalidOperationException(
            $"emitter has no Z80 cycle count for class '{cls}' op '{opKind}' mode '{mode}'"),
    };

    // ---- Load class ----

    private static void EmitLoadBody(
        StringBuilder sb,
        InstructionModel instruction,
        string pc,
        string pcType,
        string? statusReg,
        FlagBitMap flags,
        bool structured)
    {
        // First op is Load(target) — use shared operand resolution, then assign
        string target = instruction.Ops[0].Args[0]; // register name
        EmitOperandResolution(sb, instruction, pc, pcType);
        // M3.4c (Piece A): the Z80 LD A,(rp)/(nn) MEMPTR writes. ONLY LD A,(BC) (0x0A) / LD A,(DE)
        // (0x1A) → WZ = rp+1; LD A,(nn) (0x3A) → WZ = nn+1. LD r,(HL) leaves WZ UNCHANGED (vector-
        // confirmed: 46/7E keep init.wz). Guarded by `structured` (Z80-only); the 6502 never writes WZ.
        if (structured && instruction.Mode == "RegisterIndirect" && instruction.Opcode is 0x0A or 0x1A)
            EmitWz(sb, $"{Z80IndirectPair(instruction.Opcode)} + 1");
        else if (structured && instruction.Mode == "ExtendedAddress")
            EmitWz(sb, "(al | (ah << 8)) + 1");
        sb.AppendLine($"        {target} = data;");

        // Apply remaining register ops (SetNZ etc.)
        for (int i = 1; i < instruction.Ops.Length; i++)
            EmitRegisterOp(sb, instruction.Ops[i], statusReg, flags);

        // M3.4a: the Z80 LD is flag-transparent, but its T-state total (Register=4, RegisterIndirect/
        // Immediate=7, ExtendedAddress=13) exceeds the bus accesses charged — add internal T-states.
        // ONLY for a structured (Z80) CPU: the 6502 LDA #imm is 2 cycles (charged exactly by its bus
        // accesses), so this must NOT fire for the 6502 (which shares the Immediate mode name).
        if (structured)
            EmitZ80LoadStoreInternal(sb, instruction, isLoad: true);
    }

    /// <summary>For a Z80-mode Load/Store (structured CPU only), add the internal T-states so the total
    /// matches the dataset. The 6502 modes already charge exactly via bus accesses.</summary>
    private static void EmitZ80LoadStoreInternal(StringBuilder sb, InstructionModel insn, bool isLoad)
    {
        int? total = insn.Mode switch
        {
            "Register" => 4,                 // LD r,r' (the Register class handles LD SP,HL separately)
            "RegisterIndirect" => 7,         // LD r,(HL) / LD (HL),r / LD A,(BC) / LD (BC),A
            "ExtendedAddress" => 13,         // LD A,(nn) / LD (nn),A — byte
            "Immediate" => 7,                // LD r,n
            _ => null,                       // a 6502 mode — charged exactly by bus accesses
        };
        if (total is null) return;
        // Bus accesses already charged: Immediate=1 read; RegisterIndirect=1 (the (HL)/(BC) access);
        // ExtendedAddress=3 (2 addr bytes + 1 data); Register=0.
        int bus = insn.Mode switch
        {
            "Immediate" => 1,
            "RegisterIndirect" => 1,
            "ExtendedAddress" => 3,
            _ => 0,
        };
        int internalT = total.Value - 1 - bus;
        if (internalT > 0) sb.AppendLine($"        _cycles += {internalT};");
    }

    /// <summary>The Z80 register-indirect EA pair for an opcode: 0x02 (BC), 0x12 (DE), 0x0A (BC),
    /// 0x1A (DE); every other base-plane RegisterIndirect uses HL. Regular encoding.</summary>
    private static string Z80IndirectPair(byte opcode) => opcode switch
    {
        0x02 or 0x0A => "BC",
        0x12 or 0x1A => "DE",
        _ => "HL",
    };

    // ---- Register class (Implied mode) ----

    private static void EmitRegisterBody(
        StringBuilder sb,
        InstructionModel instruction,
        string pc,
        string? statusReg,
        FlagBitMap flags,
        bool structured)
    {
        // M3.4a: the Z80 register-shape mode (LD r,r' ; LD SP,HL). No dummy PC read (the Z80 does the
        // work in the fetch M-cycle); add the internal T-states (LD r,r'=4, LD SP,HL=6).
        if (instruction.Mode == "Register")
        {
            foreach (var op in instruction.Ops)
                EmitRegisterOp(sb, op, statusReg, flags);
            // LD SP,HL (0xF9) = 6 T-states; LD r,r' = 4. (Both are Register-class Transfer rows.)
            int total = instruction.Opcode == 0xF9 ? 6 : 4;
            int internalT = total - 1;
            if (internalT > 0) sb.AppendLine($"        _cycles += {internalT};");
            return;
        }

        if (instruction.Mode != "Implied")
            throw new System.InvalidOperationException(
                $"emitter has no register template for mode '{instruction.Mode}' (opcode 0x{instruction.Opcode:X2})");

        // M3.4a: a Z80 (structured) Implied register op (NOP, HALT) does NOT do the 6502 dummy PC read
        // — the Z80 NOP is a 4-T-state opcode-fetch M-cycle with no extra bus access. The fetch cycle
        // is charged by Step (= 1); add the 3 internal T-states. HALT also charges 4 (the latch is set,
        // and Step idles thereafter). The 6502 (structured == false) keeps its silicon-true dummy read.
        if (structured)
        {
            foreach (var op in instruction.Ops)
                EmitRegisterOp(sb, op, statusReg, flags);
            sb.AppendLine("        _cycles += 3;   // Z80 Implied register op: 4 T-states (fetch + 3 internal)");
            return;
        }

        // Dummy read at PC (does NOT increment PC)
        sb.AppendLine($"        _ = ReadBus({pc});");

        // Apply each op in order
        foreach (var op in instruction.Ops)
            EmitRegisterOp(sb, op, statusReg, flags);
    }

    private static void EmitRegisterOp(StringBuilder sb, OpModel op, string? statusReg, FlagBitMap flags)
    {
        switch (op.Kind)
        {
            case "Transfer":
            {
                string src = op.Args[0];
                string dst = op.Args[1];
                // A self-transfer (Z80 LD r,r where dst==src, e.g. LD B,B) is a documented no-op; emit
                // a discard to avoid the self-assignment warning (CS1717 under -warnaserror).
                sb.AppendLine(src == dst ? $"        _ = {src};" : $"        {dst} = {src};");
                break;
            }
            case "Increment":
            {
                string reg = op.Args[0];
                sb.AppendLine($"        {reg} = unchecked((byte)({reg} + 1));");
                break;
            }
            case "Decrement":
            {
                string reg = op.Args[0];
                sb.AppendLine($"        {reg} = unchecked((byte)({reg} - 1));");
                break;
            }
            case "SetNZ":
            {
                string src = op.Args[0];
                string p = statusReg ?? "P";
                // P = (P & 0x7D) | (src == 0 ? 0x02 : 0x00) | (src & 0x80)
                // 0x7D = 0111_1101 clears bits 1 (Z) and 7 (N)
                sb.AppendLine($"        {p} = unchecked((byte)(({p} & 0x7D) | ({src} == 0 ? 0x02 : 0x00) | ({src} & 0x80)));");
                break;
            }
            case "SetFlag":
            {
                string flagName = op.Args[0];
                bool setValue = op.Args[1] == "true";
                string p = statusReg ?? "P";
                byte mask = (byte)(1 << flags.BitOf(flagName));
                if (setValue)
                    sb.AppendLine($"        {p} = unchecked((byte)({p} | 0x{mask:X2}));");
                else
                    sb.AppendLine($"        {p} = unchecked((byte)({p} & ~0x{mask:X2}));");
                break;
            }
            case "Halt":
                // M3.2 (Ground truth B): set the halted latch via the partial's DoHalt(). The
                // generated Step's halted guard then idles a cycle per Step until an interrupt
                // services + clears the latch (the wake). The partial owns the latch + DoHalt.
                sb.AppendLine("        DoHalt();");
                break;
            // ── Composable flag micro-ops (M3.4a — general, 8086-reusable). Each is a read-modify-
            //    write of the Status register using PER-SPEC FlagBit masks (Ground truth C). ──
            case "SetSZ":
            {
                string src = op.Args[0];
                string p = statusReg ?? "P";
                byte sMask = (byte)(1 << flags.BitOf("S"));
                byte zMask = (byte)(1 << flags.BitOf("Z"));
                byte clear = (byte)~(sMask | zMask);
                // S = src bit7; Z = (src == 0). The src's bit7 is mapped to the S bit position.
                sb.AppendLine($"        {p} = unchecked((byte)(({p} & 0x{clear:X2})");
                sb.AppendLine($"            | ((({src} >> 7) & 1) << {flags.BitOf("S")})");
                sb.AppendLine($"            | ({src} == 0 ? 0x{zMask:X2} : 0x00)));");
                break;
            }
            case "SetParity":
            {
                string src = op.Args[0];
                string p = statusReg ?? "P";
                byte pMask = (byte)(1 << flags.BitOf("P"));
                byte clear = (byte)~pMask;
                // P/V = even parity of src: System.Numerics.BitOperations.PopCount(src) even ⇒ set.
                sb.AppendLine($"        {p} = unchecked((byte)(({p} & 0x{clear:X2})");
                sb.AppendLine($"            | ((System.Numerics.BitOperations.PopCount((uint){src}) & 1) == 0 ? 0x{pMask:X2} : 0x00)));");
                break;
            }
            case "SetXY":
            {
                string src = op.Args[0];
                string p = statusReg ?? "P";
                byte xMask = (byte)(1 << flags.BitOf("X"));
                byte yMask = (byte)(1 << flags.BitOf("Y"));
                byte clear = (byte)~(xMask | yMask);
                // X = src bit3 (mapped to the X bit position); Y = src bit5 (mapped to the Y bit position).
                sb.AppendLine($"        {p} = unchecked((byte)(({p} & 0x{clear:X2})");
                sb.AppendLine($"            | ((({src} >> 3) & 1) << {flags.BitOf("X")})");
                sb.AppendLine($"            | ((({src} >> 5) & 1) << {flags.BitOf("Y")})));");
                break;
            }
            case "SetAddSub":
            {
                bool subtract = op.Args[0] == "true";
                string p = statusReg ?? "P";
                byte nMask = (byte)(1 << flags.BitOf("N"));
                if (subtract)
                    sb.AppendLine($"        {p} = unchecked((byte)({p} | 0x{nMask:X2}));");
                else
                    sb.AppendLine($"        {p} = unchecked((byte)({p} & ~0x{nMask:X2}));");
                break;
            }
            default:
                throw new System.InvalidOperationException(
                    $"emitter has no template for register op kind '{op.Kind}'");
        }
    }

    // ---- Store class ----

    private static void EmitStoreBody(
        StringBuilder sb,
        InstructionModel instruction,
        string pc,
        string pcType)
    {
        string source = instruction.Ops[0].Args[0];

        switch (instruction.Mode)
        {
            // ── M3.4a Z80 register-shape store modes ──
            case "RegisterIndirect":
            {
                // LD (HL),r / LD (BC),A / LD (DE),A — write the source byte at the pair-view EA.
                // M3.4c (Piece A): ONLY LD (BC),A (0x02) / LD (DE),A (0x12) write WZ = (A<<8) |
                // ((rp+1)&0xFF) — vector-confirmed. LD (HL),r (0x70-0x77) leaves WZ UNCHANGED (also
                // vector-confirmed: 70/36/77 keep init.wz). These store modes are Z80-only, so no
                // `structured` guard is needed.
                string spair = Z80IndirectPair(instruction.Opcode);
                if (instruction.Opcode is 0x02 or 0x12)
                    EmitWz(sb, $"((uint)A << 8) | ((({spair} + 1u) & 0xFFu))");
                sb.AppendLine($"        WriteBus({spair}, {source});");
                sb.AppendLine($"        _cycles += {7 - 1 - 1};   // Z80 RegisterIndirect store = 7 T-states");
                return;
            }
            case "ExtendedAddress":
                // LD (nn),A — fetch the 16-bit address, write the source byte there.
                sb.AppendLine($"        byte al = ReadBus({pc});");
                sb.AppendLine($"        {pc} = unchecked(({pcType})({pc} + 1));");
                sb.AppendLine($"        byte ah = ReadBus({pc});");
                sb.AppendLine($"        {pc} = unchecked(({pcType})({pc} + 1));");
                sb.AppendLine("        uint ea = (uint)(al | (ah << 8));");
                EmitWz(sb, "((uint)A << 8) | ((ea + 1u) & 0xFFu)");   // LD (nn),A → WZ = (A<<8) | ((nn+1)&0xFF)
                sb.AppendLine($"        WriteBus(ea, {source});");
                sb.AppendLine($"        _cycles += {13 - 1 - 3};   // Z80 ExtendedAddress byte store = 13 T-states");
                return;
            case "ZeroPage":
                sb.AppendLine($"        uint addr = ReadBus({pc});");
                sb.AppendLine($"        {pc} = unchecked(({pcType})({pc} + 1));");
                sb.AppendLine($"        WriteBus(addr, {source});");
                break;
            case "ZeroPageX":
                sb.AppendLine($"        uint addr = ReadBus({pc});");
                sb.AppendLine($"        {pc} = unchecked(({pcType})({pc} + 1));");
                sb.AppendLine($"        _ = ReadBus(addr); // dummy read at unindexed zp");
                sb.AppendLine($"        WriteBus((addr + X) & 0xFF, {source});");
                break;
            case "ZeroPageY":
                sb.AppendLine($"        uint addr = ReadBus({pc});");
                sb.AppendLine($"        {pc} = unchecked(({pcType})({pc} + 1));");
                sb.AppendLine($"        _ = ReadBus(addr); // dummy read at unindexed zp");
                sb.AppendLine($"        WriteBus((addr + Y) & 0xFF, {source});");
                break;
            case "Absolute":
                sb.AppendLine($"        uint lo = ReadBus({pc});");
                sb.AppendLine($"        {pc} = unchecked(({pcType})({pc} + 1));");
                sb.AppendLine($"        uint hi = ReadBus({pc});");
                sb.AppendLine($"        {pc} = unchecked(({pcType})({pc} + 1));");
                sb.AppendLine($"        uint ea = lo | (hi << 8);");
                sb.AppendLine($"        WriteBus(ea, {source});");
                break;
            case "AbsoluteX":
                sb.AppendLine($"        uint lo = ReadBus({pc});");
                sb.AppendLine($"        {pc} = unchecked(({pcType})({pc} + 1));");
                sb.AppendLine($"        uint hi = ReadBus({pc});");
                sb.AppendLine($"        {pc} = unchecked(({pcType})({pc} + 1));");
                sb.AppendLine($"        uint ea = ((lo | (hi << 8)) + X) & 0xFFFF;");
                sb.AppendLine($"        _ = ReadBus((hi << 8) | ((lo + X) & 0xFF)); // dummy read (always, right or wrong addr)");
                sb.AppendLine($"        WriteBus(ea, {source});");
                break;
            case "AbsoluteY":
                sb.AppendLine($"        uint lo = ReadBus({pc});");
                sb.AppendLine($"        {pc} = unchecked(({pcType})({pc} + 1));");
                sb.AppendLine($"        uint hi = ReadBus({pc});");
                sb.AppendLine($"        {pc} = unchecked(({pcType})({pc} + 1));");
                sb.AppendLine($"        uint ea = ((lo | (hi << 8)) + Y) & 0xFFFF;");
                sb.AppendLine($"        _ = ReadBus((hi << 8) | ((lo + Y) & 0xFF)); // dummy read (always, right or wrong addr)");
                sb.AppendLine($"        WriteBus(ea, {source});");
                break;
            case "IndirectX":
                sb.AppendLine($"        uint ptr = ReadBus({pc});");
                sb.AppendLine($"        {pc} = unchecked(({pcType})({pc} + 1));");
                sb.AppendLine($"        _ = ReadBus(ptr); // dummy read at unindexed ptr");
                sb.AppendLine($"        uint lo = ReadBus((ptr + X) & 0xFF);");
                sb.AppendLine($"        uint hi = ReadBus((ptr + X + 1) & 0xFF);");
                sb.AppendLine($"        uint ea = lo | (hi << 8);");
                sb.AppendLine($"        WriteBus(ea, {source});");
                break;
            case "IndirectY":
                sb.AppendLine($"        uint ptr = ReadBus({pc});");
                sb.AppendLine($"        {pc} = unchecked(({pcType})({pc} + 1));");
                sb.AppendLine($"        uint lo = ReadBus(ptr);");
                sb.AppendLine($"        uint hi = ReadBus((ptr + 1) & 0xFF);");
                sb.AppendLine($"        uint ea = ((lo | (hi << 8)) + Y) & 0xFFFF;");
                sb.AppendLine($"        _ = ReadBus((hi << 8) | ((lo + Y) & 0xFF)); // dummy read (always)");
                sb.AppendLine($"        WriteBus(ea, {source});");
                break;
            default:
                throw new System.InvalidOperationException(
                    $"emitter has no store template for mode '{instruction.Mode}' (opcode 0x{instruction.Opcode:X2})");
        }
    }

    // ---- Jump class ----

    private static void EmitJumpBody(
        StringBuilder sb,
        InstructionModel instruction,
        string pc,
        string pcType)
    {
        switch (instruction.Mode)
        {
            case "Absolute":
                // Absolute jump: fetch lo, fetch hi, set PC = ea (no data access at target)
                sb.AppendLine($"        uint lo = ReadBus({pc});");
                sb.AppendLine($"        {pc} = unchecked(({pcType})({pc} + 1));");
                sb.AppendLine($"        uint hi = ReadBus({pc});");
                sb.AppendLine($"        {pc} = unchecked(({pcType})({pc} + 1));");
                sb.AppendLine($"        {pc} = unchecked(({pcType})(lo | (hi << 8)));");
                break;
            case "Indirect":
                // JMP (ptr): 5 cycles. Reproduces the NMOS page-wrap bug:
                // a pointer at $xxFF takes its high byte from $xx00.
                sb.AppendLine($"        uint lo = ReadBus({pc});");
                sb.AppendLine($"        {pc} = unchecked(({pcType})({pc} + 1));");
                sb.AppendLine($"        uint hi = ReadBus({pc});");
                sb.AppendLine($"        {pc} = unchecked(({pcType})({pc} + 1));");
                sb.AppendLine($"        uint ptr = lo | (hi << 8);");
                sb.AppendLine($"        uint target = ReadBus(ptr);");
                sb.AppendLine($"        target |= (uint)ReadBus((ptr & 0xFF00) | ((ptr + 1) & 0xFF)) << 8;");
                sb.AppendLine($"        {pc} = unchecked(({pcType})target);");
                break;
            default:
                throw new System.InvalidOperationException(
                    $"emitter has no jump template for mode '{instruction.Mode}' (opcode 0x{instruction.Opcode:X2})");
        }
    }

    // ---- Branch class ----

    // Flag name -> hardware bit position. M3.4a: PER-SPEC via the model's FlagBitMap (Ground truth B):
    // a spec that declares a FlagLayout resolves the Z80 bit positions (Z=6, N=1, …); the 6502 (no
    // layout) falls back to the Flag enum's 6502 values (C=0 Z=1 I=2 D=3 V=6 N=7) — byte-identical.

    private static void EmitBranchBody(
        StringBuilder sb,
        InstructionModel instruction,
        string pc,
        string pcType,
        string? statusReg,
        FlagBitMap flags)
    {
        if (instruction.Mode != "Relative")
            throw new System.InvalidOperationException(
                $"emitter has no branch template for mode '{instruction.Mode}' (opcode 0x{instruction.Opcode:X2})");

        string p = statusReg ?? "P";
        string flagName = instruction.Ops[0].Args[0];
        bool when = instruction.Ops[0].Args[1] == "true";
        int bit = flags.BitOf(flagName);
        int expectedBit = when ? 1 : 0;

        // Branch template from the plan:
        // byte offset = ReadBus(PC); PC++;
        // if (taken) {
        //   _ = ReadBus(PC);
        //   ushort target = (ushort)(PC + (sbyte)offset);
        //   if ((target & 0xFF00) != (PC & 0xFF00))
        //     _ = ReadBus((uint)((PC & 0xFF00) | (target & 0x00FF)));
        //   PC = target;
        // }
        sb.AppendLine($"        byte offset = ReadBus({pc});");
        sb.AppendLine($"        {pc} = unchecked(({pcType})({pc} + 1));");
        sb.AppendLine($"        if ((({p} >> {bit}) & 1) == {expectedBit})");
        sb.AppendLine("        {");
        sb.AppendLine($"            _ = ReadBus({pc});");
        sb.AppendLine($"            ushort target = unchecked((ushort)({pc} + (sbyte)offset));");
        sb.AppendLine($"            if ((target & 0xFF00) != ({pc} & 0xFF00))");
        sb.AppendLine($"                _ = ReadBus((uint)(({pc} & 0xFF00) | (target & 0x00FF)));");
        sb.AppendLine($"            {pc} = target;");
        sb.AppendLine("        }");
    }

    // ---- Cycle-string helpers for variable-cycle classes ----

    private static string ComputeStackCycleStr(EquatableArray<OpModel> ops)
    {
        if (ops.Length == 0) return "2 cycles";
        return ops[0].Kind switch
        {
            "Push" or "PushP" => "3 cycles",  // opcode + dummy read + write
            "Pull" or "PullP" => "4 cycles",  // opcode + dummy read + dummy stack read + real read
            _ => "2 cycles",
        };
    }

    private static string ComputeFlowCycleStr(EquatableArray<OpModel> ops)
    {
        if (ops.Length == 0) return "6 cycles";
        return ops[0].Kind switch
        {
            "Jsr" => "6 cycles",
            "Rts" => "6 cycles",
            "Brk" => "7 cycles",
            "Rti" => "6 cycles",
            _ => "6 cycles",
        };
    }

    // ---- ALU class ----

    /// <summary>Emits the per-mode operand resolution (shared with Load class) followed by
    /// the ALU application. The resolution code is identical to EmitLoadBody — this shared
    /// helper avoids duplicating 9 mode arms.</summary>
    private static void EmitAluBody(
        StringBuilder sb,
        InstructionModel instruction,
        string pc,
        string pcType,
        string? statusReg)
    {
        string p = statusReg ?? "P";

        // Emit operand resolution (same pattern as Load, reads into local 'data')
        EmitOperandResolution(sb, instruction, pc, pcType);

        // ALU application: varies by op kind
        switch (instruction.Ops[0].Kind)
        {
            case "Adc":
                sb.AppendLine($"        int temp = A + data + ({p} & 0x01);");
                sb.AppendLine($"        if (({p} & 0x08) != 0)");
                sb.AppendLine("        {");
                sb.AppendLine("            // NMOS decimal ADC (64doc): Z from the BINARY sum; N and V from the");
                sb.AppendLine("            // intermediate BCD sum (before the +0x60 correction); C from the corrected sum.");
                sb.AppendLine("            // Locals named from the reserved set ('before'=low nibble, 'sum'=BCD sum) to");
                sb.AppendLine("            // avoid colliding with the operand-resolution 'lo'/'hi' in memory modes.");
                sb.AppendLine($"            int before = (A & 0x0F) + (data & 0x0F) + ({p} & 0x01);");
                sb.AppendLine("            if (before >= 0x0A)");
                sb.AppendLine("                before = ((before + 0x06) & 0x0F) + 0x10;");
                sb.AppendLine("            int sum = (A & 0xF0) + (data & 0xF0) + before;");
                sb.AppendLine($"            {p} = unchecked((byte)(({p} & 0x3C)");
                sb.AppendLine("                | (sum & 0x80)");
                sb.AppendLine($"                | ((~(A ^ data) & (A ^ sum) & 0x80) != 0 ? 0x40 : 0x00)");
                sb.AppendLine($"                | ((temp & 0xFF) == 0 ? 0x02 : 0x00)));");
                sb.AppendLine("            if (sum >= 0xA0)");
                sb.AppendLine("                sum += 0x60;");
                sb.AppendLine($"            {p} = unchecked((byte)(({p} & 0xFE) | (sum >= 0x100 ? 0x01 : 0x00)));");
                sb.AppendLine("            A = unchecked((byte)sum);");
                sb.AppendLine("        }");
                sb.AppendLine("        else");
                sb.AppendLine("        {");
                sb.AppendLine($"            {p} = unchecked((byte)(({p} & 0xBE)");
                sb.AppendLine($"                | (temp > 0xFF ? 0x01 : 0x00)");
                sb.AppendLine($"                | ((~(A ^ data) & (A ^ temp) & 0x80) != 0 ? 0x40 : 0x00)));");
                sb.AppendLine("            A = unchecked((byte)temp);");
                sb.AppendLine($"            {p} = unchecked((byte)(({p} & 0x7D) | (A == 0 ? 0x02 : 0x00) | (A & 0x80)));");
                sb.AppendLine("        }");
                break;
            case "Sbc":
                sb.AppendLine($"        int temp = A + (data ^ 0xFF) + ({p} & 0x01);");
                sb.AppendLine($"        if (({p} & 0x08) != 0)");
                sb.AppendLine("        {");
                sb.AppendLine("            // NMOS decimal SBC (64doc): ALL flags are the binary-mode flags — only the");
                sb.AppendLine("            // result byte receives the BCD correction.");
                sb.AppendLine("            // Locals named from the reserved set ('before'=low nibble, 'sum'=BCD sum) to");
                sb.AppendLine("            // avoid colliding with the operand-resolution 'lo'/'hi' in memory modes.");
                sb.AppendLine($"            int before = (A & 0x0F) - (data & 0x0F) + ({p} & 0x01) - 1;");
                sb.AppendLine("            if (before < 0)");
                sb.AppendLine("                before = ((before - 0x06) & 0x0F) - 0x10;");
                sb.AppendLine("            int sum = (A & 0xF0) - (data & 0xF0) + before;");
                sb.AppendLine("            if (sum < 0)");
                sb.AppendLine("                sum -= 0x60;");
                sb.AppendLine($"            {p} = unchecked((byte)(({p} & 0x3C)");
                sb.AppendLine($"                | (temp > 0xFF ? 0x01 : 0x00)");
                sb.AppendLine($"                | (((A ^ data) & (A ^ temp) & 0x80) != 0 ? 0x40 : 0x00)");
                sb.AppendLine($"                | ((temp & 0xFF) == 0 ? 0x02 : 0x00)");
                sb.AppendLine($"                | (temp & 0x80)));");
                sb.AppendLine("            A = unchecked((byte)sum);");
                sb.AppendLine("        }");
                sb.AppendLine("        else");
                sb.AppendLine("        {");
                sb.AppendLine($"            {p} = unchecked((byte)(({p} & 0xBE)");
                sb.AppendLine($"                | (temp > 0xFF ? 0x01 : 0x00)");
                sb.AppendLine($"                | (((A ^ data) & (A ^ temp) & 0x80) != 0 ? 0x40 : 0x00)));");
                sb.AppendLine("            A = unchecked((byte)temp);");
                sb.AppendLine($"            {p} = unchecked((byte)(({p} & 0x7D) | (A == 0 ? 0x02 : 0x00) | (A & 0x80)));");
                sb.AppendLine("        }");
                break;
            case "And":
                sb.AppendLine($"        A = unchecked((byte)(A & data));");
                sb.AppendLine($"        {p} = unchecked((byte)(({p} & 0x7D) | (A == 0 ? 0x02 : 0x00) | (A & 0x80)));");
                break;
            case "Ora":
                sb.AppendLine($"        A = unchecked((byte)(A | data));");
                sb.AppendLine($"        {p} = unchecked((byte)(({p} & 0x7D) | (A == 0 ? 0x02 : 0x00) | (A & 0x80)));");
                break;
            case "Eor":
                sb.AppendLine($"        A = unchecked((byte)(A ^ data));");
                sb.AppendLine($"        {p} = unchecked((byte)(({p} & 0x7D) | (A == 0 ? 0x02 : 0x00) | (A & 0x80)));");
                break;
            case "Compare":
            {
                string reg = instruction.Ops[0].Args[0]; // the register to compare
                // C = reg >= data; Z = reg == data; N = (reg-data) bit7; V unaffected
                // 0x7C clears N+Z+C
                sb.AppendLine($"        int temp = {reg} - data;");
                sb.AppendLine($"        {p} = unchecked((byte)(({p} & 0x7C) | ({reg} >= data ? 0x01 : 0x00)");
                sb.AppendLine($"            | ((temp & 0xFF) == 0 ? 0x02 : 0x00) | (temp & 0x80)));");
                break;
            }
            case "Bit":
                // N=d7, V=d6, Z=(A&d)==0; C unaffected; 0x3D clears N+V+Z
                sb.AppendLine($"        {p} = unchecked((byte)(({p} & 0x3D) | ((A & data) == 0 ? 0x02 : 0x00) | (data & 0xC0)));");
                break;
            default:
                throw new System.InvalidOperationException(
                    $"emitter has no ALU template for op '{instruction.Ops[0].Kind}' (opcode 0x{instruction.Opcode:X2})");
        }
    }

    /// <summary>Emits operand resolution for Load and ALU bodies (reads memory into local
    /// <c>byte data</c>). All 9 allowed modes are covered; default throws.</summary>
    private static void EmitOperandResolution(
        StringBuilder sb,
        InstructionModel instruction,
        string pc,
        string pcType)
    {
        switch (instruction.Mode)
        {
            // ── M3.4a Z80 register-shape modes ──
            case "RegisterIndirect":
                // LD r,(HL) / LD A,(BC) / LD A,(DE) — read the byte at the pair-view EA.
                sb.AppendLine($"        byte data = ReadBus({Z80IndirectPair(instruction.Opcode)});");
                break;
            case "ExtendedAddress":
                // LD A,(nn) — fetch the 16-bit address, read the byte there.
                sb.AppendLine($"        byte al = ReadBus({pc});");
                sb.AppendLine($"        {pc} = unchecked(({pcType})({pc} + 1));");
                sb.AppendLine($"        byte ah = ReadBus({pc});");
                sb.AppendLine($"        {pc} = unchecked(({pcType})({pc} + 1));");
                sb.AppendLine("        byte data = ReadBus((uint)(al | (ah << 8)));");
                break;
            case "Immediate":
                sb.AppendLine($"        byte data = ReadBus({pc});");
                sb.AppendLine($"        {pc} = unchecked(({pcType})({pc} + 1));");
                break;
            case "ZeroPage":
                sb.AppendLine($"        uint addr = ReadBus({pc});");
                sb.AppendLine($"        {pc} = unchecked(({pcType})({pc} + 1));");
                sb.AppendLine($"        byte data = ReadBus(addr);");
                break;
            case "ZeroPageX":
                sb.AppendLine($"        uint addr = ReadBus({pc});");
                sb.AppendLine($"        {pc} = unchecked(({pcType})({pc} + 1));");
                sb.AppendLine($"        _ = ReadBus(addr); // dummy read at unindexed zp");
                sb.AppendLine($"        byte data = ReadBus((addr + X) & 0xFF);");
                break;
            case "ZeroPageY":
                sb.AppendLine($"        uint addr = ReadBus({pc});");
                sb.AppendLine($"        {pc} = unchecked(({pcType})({pc} + 1));");
                sb.AppendLine($"        _ = ReadBus(addr); // dummy read at unindexed zp");
                sb.AppendLine($"        byte data = ReadBus((addr + Y) & 0xFF);");
                break;
            case "Absolute":
                sb.AppendLine($"        uint lo = ReadBus({pc});");
                sb.AppendLine($"        {pc} = unchecked(({pcType})({pc} + 1));");
                sb.AppendLine($"        uint hi = ReadBus({pc});");
                sb.AppendLine($"        {pc} = unchecked(({pcType})({pc} + 1));");
                sb.AppendLine($"        uint ea = lo | (hi << 8);");
                sb.AppendLine($"        byte data = ReadBus(ea);");
                break;
            case "AbsoluteX":
                sb.AppendLine($"        uint lo = ReadBus({pc});");
                sb.AppendLine($"        {pc} = unchecked(({pcType})({pc} + 1));");
                sb.AppendLine($"        uint hi = ReadBus({pc});");
                sb.AppendLine($"        {pc} = unchecked(({pcType})({pc} + 1));");
                sb.AppendLine($"        uint ea = ((lo | (hi << 8)) + X) & 0xFFFF;");
                sb.AppendLine($"        byte data = ReadBus((hi << 8) | ((lo + X) & 0xFF));");
                sb.AppendLine($"        if (((lo + X) & 0x100) != 0)");
                sb.AppendLine($"            data = ReadBus(ea);");
                break;
            case "AbsoluteY":
                sb.AppendLine($"        uint lo = ReadBus({pc});");
                sb.AppendLine($"        {pc} = unchecked(({pcType})({pc} + 1));");
                sb.AppendLine($"        uint hi = ReadBus({pc});");
                sb.AppendLine($"        {pc} = unchecked(({pcType})({pc} + 1));");
                sb.AppendLine($"        uint ea = ((lo | (hi << 8)) + Y) & 0xFFFF;");
                sb.AppendLine($"        byte data = ReadBus((hi << 8) | ((lo + Y) & 0xFF));");
                sb.AppendLine($"        if (((lo + Y) & 0x100) != 0)");
                sb.AppendLine($"            data = ReadBus(ea);");
                break;
            case "IndirectX":
                sb.AppendLine($"        uint ptr = ReadBus({pc});");
                sb.AppendLine($"        {pc} = unchecked(({pcType})({pc} + 1));");
                sb.AppendLine($"        _ = ReadBus(ptr); // dummy read at unindexed ptr");
                sb.AppendLine($"        uint lo = ReadBus((ptr + X) & 0xFF);");
                sb.AppendLine($"        uint hi = ReadBus((ptr + X + 1) & 0xFF);");
                sb.AppendLine($"        uint ea = lo | (hi << 8);");
                sb.AppendLine($"        byte data = ReadBus(ea);");
                break;
            case "IndirectY":
                sb.AppendLine($"        uint ptr = ReadBus({pc});");
                sb.AppendLine($"        {pc} = unchecked(({pcType})({pc} + 1));");
                sb.AppendLine($"        uint lo = ReadBus(ptr);");
                sb.AppendLine($"        uint hi = ReadBus((ptr + 1) & 0xFF);");
                sb.AppendLine($"        uint ea = ((lo | (hi << 8)) + Y) & 0xFFFF;");
                sb.AppendLine($"        byte data = ReadBus((hi << 8) | ((lo + Y) & 0xFF));");
                sb.AppendLine($"        if (((lo + Y) & 0x100) != 0)");
                sb.AppendLine($"            data = ReadBus(ea);");
                break;
            default:
                throw new System.InvalidOperationException(
                    $"emitter has no operand-resolution template for mode '{instruction.Mode}' (opcode 0x{instruction.Opcode:X2})");
        }
    }

    // ---- RMW class ----

    private static void EmitRmwBody(
        StringBuilder sb,
        InstructionModel instruction,
        string pc,
        string pcType,
        string? statusReg)
    {
        string p = statusReg ?? "P";

        if (instruction.Mode == "Accumulator")
        {
            // Accumulator form: dummy read at PC (no increment), then operate on A
            sb.AppendLine($"        _ = ReadBus({pc}); // dummy read at PC (no increment)");
            EmitRmwCompute(sb, instruction.Ops[0].Kind, "A", p, instruction.Opcode);
            return;
        }

        // Memory forms: fetch address, read value, dummy write, write modified
        switch (instruction.Mode)
        {
            case "ZeroPage":
                sb.AppendLine($"        uint ea = ReadBus({pc});");
                sb.AppendLine($"        {pc} = unchecked(({pcType})({pc} + 1));");
                sb.AppendLine($"        byte value = ReadBus(ea);");
                sb.AppendLine($"        WriteBus(ea, value); // RMW dummy write of the unmodified value (silicon-true)");
                break;
            case "ZeroPageX":
                sb.AppendLine($"        uint addr = ReadBus({pc});");
                sb.AppendLine($"        {pc} = unchecked(({pcType})({pc} + 1));");
                sb.AppendLine($"        _ = ReadBus(addr); // dummy read at unindexed zp");
                sb.AppendLine($"        uint ea = (addr + X) & 0xFF;");
                sb.AppendLine($"        byte value = ReadBus(ea);");
                sb.AppendLine($"        WriteBus(ea, value); // RMW dummy write of the unmodified value");
                break;
            case "Absolute":
                sb.AppendLine($"        uint lo = ReadBus({pc});");
                sb.AppendLine($"        {pc} = unchecked(({pcType})({pc} + 1));");
                sb.AppendLine($"        uint hi = ReadBus({pc});");
                sb.AppendLine($"        {pc} = unchecked(({pcType})({pc} + 1));");
                sb.AppendLine($"        uint ea = lo | (hi << 8);");
                sb.AppendLine($"        byte value = ReadBus(ea);");
                sb.AppendLine($"        WriteBus(ea, value); // RMW dummy write of the unmodified value (silicon-true)");
                break;
            case "AbsoluteX":
                // Always-dummy read at wrong address (cross or not), then real read at ea
                sb.AppendLine($"        uint lo = ReadBus({pc});");
                sb.AppendLine($"        {pc} = unchecked(({pcType})({pc} + 1));");
                sb.AppendLine($"        uint hi = ReadBus({pc});");
                sb.AppendLine($"        {pc} = unchecked(({pcType})({pc} + 1));");
                sb.AppendLine($"        uint ea = ((lo | (hi << 8)) + X) & 0xFFFF;");
                sb.AppendLine($"        _ = ReadBus((hi << 8) | ((lo + X) & 0xFF)); // dummy read at wrong addr (ALWAYS)");
                sb.AppendLine($"        byte value = ReadBus(ea);");
                sb.AppendLine($"        WriteBus(ea, value); // RMW dummy write of the unmodified value");
                break;
            default:
                throw new System.InvalidOperationException(
                    $"emitter has no RMW template for mode '{instruction.Mode}' (opcode 0x{instruction.Opcode:X2})");
        }

        EmitRmwCompute(sb, instruction.Ops[0].Kind, null, p, instruction.Opcode);
        sb.AppendLine($"        WriteBus(ea, temp);");
        sb.AppendLine($"        {p} = unchecked((byte)(({p} & 0x7D) | (temp == 0 ? 0x02 : 0x00) | (temp & 0x80)));");
    }

    /// <summary>Emits the compute portion of an RMW body: sets C flag and produces temp.
    /// For accumulator form, 'target' is "A" and the final assignment is included here.
    /// For memory forms, 'target' is null and the caller writes WriteBus+SetNZ.</summary>
    private static void EmitRmwCompute(StringBuilder sb, string opKind, string? target, string p, byte opcode)
    {
        bool isAccumulator = target != null;
        string src = isAccumulator ? target! : "value";

        switch (opKind)
        {
            case "ShiftLeft":
                sb.AppendLine($"        byte temp = unchecked((byte)({src} << 1));");
                sb.AppendLine($"        {p} = unchecked((byte)(({p} & 0xFE) | (({src} >> 7) & 1)));"); // C = bit7
                break;
            case "ShiftRight":
                sb.AppendLine($"        byte temp = unchecked((byte)({src} >> 1));");
                sb.AppendLine($"        {p} = unchecked((byte)(({p} & 0xFE) | ({src} & 1)));"); // C = bit0; N always 0
                break;
            case "RotateLeft":
                sb.AppendLine($"        byte temp = unchecked((byte)(({src} << 1) | ({p} & 0x01)));");
                sb.AppendLine($"        {p} = unchecked((byte)(({p} & 0xFE) | (({src} >> 7) & 1)));"); // C = old bit7
                break;
            case "RotateRight":
                sb.AppendLine($"        byte temp = unchecked((byte)(({src} >> 1) | (({p} & 0x01) << 7)));");
                sb.AppendLine($"        {p} = unchecked((byte)(({p} & 0xFE) | ({src} & 1)));"); // C = old bit0
                break;
            case "IncrementMem":
                sb.AppendLine($"        byte temp = unchecked((byte)({src} + 1));");
                break;
            case "DecrementMem":
                sb.AppendLine($"        byte temp = unchecked((byte)({src} - 1));");
                break;
            default:
                throw new System.InvalidOperationException(
                    $"emitter has no RMW compute template for op '{opKind}' (opcode 0x{opcode:X2})");
        }

        if (isAccumulator)
        {
            sb.AppendLine($"        {target} = temp;");
            sb.AppendLine($"        {p} = unchecked((byte)(({p} & 0x7D) | ({target} == 0 ? 0x02 : 0x00) | ({target} & 0x80)));");
        }
    }

    // ---- Stack class ----

    private static void EmitStackBody(
        StringBuilder sb,
        InstructionModel instruction,
        string pc,
        string? statusReg,
        string? spReg)
    {
        if (instruction.Mode != "Implied")
            throw new System.InvalidOperationException(
                $"emitter has no stack template for mode '{instruction.Mode}' (opcode 0x{instruction.Opcode:X2})");

        // The parser rejects stack-class instructions in specs without a StackPointer-role
        // register (CPUGEN010), so spReg is always present here — throw loudly if not.
        string sp = spReg ?? throw new System.InvalidOperationException(
            $"stack template requires a StackPointer-role register (opcode 0x{instruction.Opcode:X2})");
        string p = statusReg ?? "P";
        var op = instruction.Ops[0];

        switch (op.Kind)
        {
            case "Push":
            {
                string src = op.Args[0];
                sb.AppendLine($"        _ = ReadBus({pc}); // dummy read at PC (no increment)");
                sb.AppendLine($"        WriteBus(0x100u + {sp}, {src});");
                sb.AppendLine($"        {sp} = unchecked((byte)({sp} - 1));");
                break;
            }
            case "Pull":
            {
                string dst = op.Args[0];
                sb.AppendLine($"        _ = ReadBus({pc}); // dummy read at PC");
                sb.AppendLine($"        _ = ReadBus(0x100u + {sp}); // dummy read at old S (increment cycle)");
                sb.AppendLine($"        {sp} = unchecked((byte)({sp} + 1));");
                sb.AppendLine($"        {dst} = ReadBus(0x100u + {sp});");
                // NZ baked into Pull
                sb.AppendLine($"        {p} = unchecked((byte)(({p} & 0x7D) | ({dst} == 0 ? 0x02 : 0x00) | ({dst} & 0x80)));");
                break;
            }
            case "PushP":
                sb.AppendLine($"        _ = ReadBus({pc}); // dummy read at PC");
                sb.AppendLine($"        WriteBus(0x100u + {sp}, unchecked((byte)({p} | 0x30))); // phantom bits 4+5 set on push");
                sb.AppendLine($"        {sp} = unchecked((byte)({sp} - 1));");
                break;
            case "PullP":
                sb.AppendLine($"        _ = ReadBus({pc}); // dummy read at PC");
                sb.AppendLine($"        _ = ReadBus(0x100u + {sp}); // dummy read at old S");
                sb.AppendLine($"        {sp} = unchecked((byte)({sp} + 1));");
                // Real hardware: bit5 is always 1, bit4 (B) is forced to 0 in the CPU register
                // (bit4 is only meaningful in the stacked byte, not the live register).
                // TomHarte vectors confirm this convention (plan 3b-i truing — pre-authorized).
                sb.AppendLine($"        {p} = unchecked((byte)((ReadBus(0x100u + {sp}) | 0x20) & 0xEF));");
                break;
            default:
                throw new System.InvalidOperationException(
                    $"emitter has no stack op template for '{op.Kind}' (opcode 0x{instruction.Opcode:X2})");
        }
    }

    // ---- Flow class ----

    private static void EmitFlowBody(
        StringBuilder sb,
        InstructionModel instruction,
        string pc,
        string pcType,
        string? statusReg,
        string? spReg)
    {
        // The parser rejects flow-class instructions in specs without a StackPointer-role
        // register (CPUGEN010), so spReg is always present here — throw loudly if not.
        string sp = spReg ?? throw new System.InvalidOperationException(
            $"flow template requires a StackPointer-role register (opcode 0x{instruction.Opcode:X2})");
        var op = instruction.Ops[0];
        switch (op.Kind)
        {
            case "Jsr":
                if (instruction.Mode != "Absolute")
                    throw new System.InvalidOperationException(
                        $"emitter has no JSR template for mode '{instruction.Mode}' (opcode 0x{instruction.Opcode:X2})");
                // JSR Absolute — 6 cycles. Fetch lo (PC++); dummy read at $0100+S;
                // push PCH; S--; push PCL; S--; fetch hi at PC; PC = hi:lo.
                // The pushed PC is return-address = 1 before the next instruction.
                sb.AppendLine($"        uint lo = ReadBus({pc});");
                sb.AppendLine($"        {pc} = unchecked(({pcType})({pc} + 1));");
                sb.AppendLine($"        _ = ReadBus(0x100u + {sp}); // stack dummy read");
                sb.AppendLine($"        WriteBus(0x100u + {sp}, unchecked((byte)({pc} >> 8)));");
                sb.AppendLine($"        {sp} = unchecked((byte)({sp} - 1));");
                sb.AppendLine($"        WriteBus(0x100u + {sp}, unchecked((byte){pc}));");
                sb.AppendLine($"        {sp} = unchecked((byte)({sp} - 1));");
                sb.AppendLine($"        uint hi = ReadBus({pc}); // hi byte (PC still at hi operand)");
                sb.AppendLine($"        {pc} = unchecked(({pcType})(lo | (hi << 8)));");
                break;
            case "Rts":
                if (instruction.Mode != "Implied")
                    throw new System.InvalidOperationException(
                        $"emitter has no RTS template for mode '{instruction.Mode}' (opcode 0x{instruction.Opcode:X2})");
                // RTS — 6 cycles. Dummy read at PC; dummy read at old S; S++; pull PCL; S++;
                // pull PCH; dummy read at new PC; PC++.
                sb.AppendLine($"        _ = ReadBus({pc}); // dummy read at PC");
                sb.AppendLine($"        _ = ReadBus(0x100u + {sp}); // dummy read at old S");
                sb.AppendLine($"        {sp} = unchecked((byte)({sp} + 1));");
                sb.AppendLine($"        uint lo = ReadBus(0x100u + {sp});");
                sb.AppendLine($"        {sp} = unchecked((byte)({sp} + 1));");
                sb.AppendLine($"        uint hi = ReadBus(0x100u + {sp});");
                sb.AppendLine($"        {pc} = unchecked(({pcType})(lo | (hi << 8)));");
                sb.AppendLine($"        _ = ReadBus({pc}); // dummy read at new PC before increment");
                sb.AppendLine($"        {pc} = unchecked(({pcType})({pc} + 1));");
                break;
            case "Brk":
                if (instruction.Mode != "Implied")
                    throw new System.InvalidOperationException(
                        $"emitter has no BRK template for mode '{instruction.Mode}' (opcode 0x{instruction.Opcode:X2})");
                {
                    string p = statusReg ?? "P";
                    sb.AppendLine($"        _ = ReadBus({pc}); // padding-byte read: BRK is a 2-byte instruction");
                    sb.AppendLine($"        {pc} = unchecked(({pcType})({pc} + 1));");
                    sb.AppendLine($"        WriteBus(0x100u + {sp}, unchecked((byte)({pc} >> 8)));");
                    sb.AppendLine($"        {sp} = unchecked((byte)({sp} - 1));");
                    sb.AppendLine($"        WriteBus(0x100u + {sp}, unchecked((byte){pc}));");
                    sb.AppendLine($"        {sp} = unchecked((byte)({sp} - 1));");
                    sb.AppendLine($"        WriteBus(0x100u + {sp}, unchecked((byte)({p} | 0x30))); // stacked B=1 marks BRK/PHP");
                    sb.AppendLine($"        {sp} = unchecked((byte)({sp} - 1));");
                    sb.AppendLine($"        uint lo = ReadBus(0xFFFE);");
                    sb.AppendLine($"        uint hi = ReadBus(0xFFFF);");
                    sb.AppendLine($"        {p} = unchecked((byte)({p} | 0x04)); // I set; D untouched (NMOS — CLD-on-BRK is 65C02)");
                    sb.AppendLine($"        {pc} = unchecked(({pcType})(lo | (hi << 8)));");
                }
                break;
            case "Rti":
                if (instruction.Mode != "Implied")
                    throw new System.InvalidOperationException(
                        $"emitter has no RTI template for mode '{instruction.Mode}' (opcode 0x{instruction.Opcode:X2})");
                {
                    string p = statusReg ?? "P";
                    sb.AppendLine($"        _ = ReadBus({pc}); // dummy read at PC (no increment)");
                    sb.AppendLine($"        _ = ReadBus(0x100u + {sp}); // dummy read at old S (increment cycle)");
                    sb.AppendLine($"        {sp} = unchecked((byte)({sp} + 1));");
                    sb.AppendLine($"        {p} = unchecked((byte)((ReadBus(0x100u + {sp}) | 0x20) & 0xEF)); // phantom bits: 5=1, 4=0");
                    sb.AppendLine($"        {sp} = unchecked((byte)({sp} + 1));");
                    sb.AppendLine($"        uint lo = ReadBus(0x100u + {sp});");
                    sb.AppendLine($"        {sp} = unchecked((byte)({sp} + 1));");
                    sb.AppendLine($"        uint hi = ReadBus(0x100u + {sp});");
                    sb.AppendLine($"        {pc} = unchecked(({pcType})(lo | (hi << 8))); // no increment, no dummy at new PC (≠ RTS)");
                }
                break;
            default:
                throw new System.InvalidOperationException(
                    $"emitter has no flow op template for '{op.Kind}' (opcode 0x{instruction.Opcode:X2})");
        }
    }

    // ---- Port class (M3.2 — the Io bus) ----

    /// <summary>Emit a PortIn/PortOut body. The port op targets the Io bus via the partial's
    /// ReadIo/WriteIo (the I/O analogues of ReadBus/WriteBus) — NEVER ReadBus/WriteBus, so a
    /// PortIn reads the Io space, never the program space (the load-bearing Io-targeting invariant,
    /// Ground truth A). IoPortImmediate: an 8-bit (n) port operand consumed from the program bus
    /// (length 2). IoPortIndirect: the port comes from the named register (the Z80 (C) form,
    /// length 1) — the minimal synthetic shape (Ground truth A scope honesty; the real (C) is M3.4).</summary>
    private static void EmitPortBody(
        StringBuilder sb,
        InstructionModel instruction,
        string pc,
        string pcType,
        bool structured)
    {
        var op = instruction.Ops[0];
        string reg = op.Args[0];   // PortIn target / PortOut source — register NAME (J2)

        // Resolve the port number into local 'uint port'.
        switch (instruction.Mode)
        {
            case "IoPortImmediate":
                // (n): one operand byte off the program bus (charges 1 fetch cycle), then PC++.
                // On the Z80, IN A,(n)/OUT (n),A drive the FULL 16-bit address (A<<8)|n on the I/O bus
                // (the documented behavior TomHarte's ports array records). The 6502 has no port op.
                sb.AppendLine($"        byte pn = ReadBus({pc});");
                sb.AppendLine($"        {pc} = unchecked(({pcType})({pc} + 1));");
                sb.AppendLine(structured
                    ? $"        uint port = (uint)(({reg} << 8) | pn);"
                    : "        uint port = pn;");
                break;
            case "IoPortIndirect":
                // (C): the port number comes from the named register; no operand byte (length 1).
                sb.AppendLine($"        uint port = {reg};");
                break;
            default:
                throw new System.InvalidOperationException(
                    $"emitter has no port template for mode '{instruction.Mode}' (opcode 0x{instruction.Opcode:X2})");
        }

        switch (op.Kind)
        {
            case "PortIn":
                sb.AppendLine($"        {reg} = ReadIo(port);");   // the Io bus — NEVER ReadBus
                break;
            case "PortOut":
                sb.AppendLine($"        WriteIo(port, {reg});");   // the Io bus — NEVER WriteBus
                break;
            default:
                throw new System.InvalidOperationException(
                    $"emitter has no port template for op '{op.Kind}' (opcode 0x{instruction.Opcode:X2})");
        }

        // M3.4c (Piece A): the Z80 IN A,(n)/OUT (n),A MEMPTR write — the two forms DIFFER (vector-
        // confirmed). IN A,(n): WZ = port + 1 = ((A<<8)|n)+1, the FULL 16-bit increment, so the n=0xFF
        // carry propagates into the high byte (`db 0066`: A=0x3E,n=0xFF → WZ=0x3F00). OUT (n),A: WZ =
        // (A<<8) | ((n+1)&0xFF), the A-high quirk — NO carry (`d3 00BC`: A=0x9A,n=0xFF → WZ=0x9A00).
        // Derived from `port` (= (A_pre<<8)|n) so IN uses the PRE-read A. Z80-only (`structured`).
        if (structured && instruction.Mode == "IoPortImmediate")
            EmitWz(sb, op.Kind == "PortIn"
                ? "port + 1u"
                : "(port & 0xFF00u) | ((pn + 1u) & 0xFFu)");

        // M3.4a: the Z80 IN A,(n)/OUT (n),A are 11 T-states. Charged so far: Step fetch (1) + the (n)
        // operand read (1) + the Io access (ReadIo/WriteIo charge 1) = 3. Add the 8 internal T-states.
        if (structured && instruction.Mode == "IoPortImmediate")
            sb.AppendLine("        _cycles += 8;   // Z80 IN A,(n)/OUT (n),A = 11 T-states");
    }

    // ════════════════════════════════════════════════════════════════════════════════════════
    // M3.4a — the Z80 base-plane bodies. Cycle model (Ground truth G): each body does the real bus
    // reads/writes (1 T-state each via ReadBus/WriteBus), then adds the remaining INTERNAL T-states
    // with `_cycles += N;` so the per-instruction total equals the dataset T-state count (and the
    // TomHarte cycle-count). Bus-trace ordering is staged-gated in Task 8.
    // ════════════════════════════════════════════════════════════════════════════════════════

    // ---- Z80 ALU class (8-bit ALU + INC/DEC + 16-bit ALU) ----

    private static void EmitZ80AluBody(
        StringBuilder sb, InstructionModel insn, string pc, string pcType, string? statusReg, FlagBitMap flags)
    {
        string f = statusReg ?? "F";
        string kind = insn.Ops[0].Kind;
        int total = Z80Cycles(insn.Mode, InstructionClass.Z80Alu, kind);

        switch (kind)
        {
            case "Add16": EmitZ80Add16(sb, insn, f, flags, total); return;
            case "Inc16": EmitZ80IncDec16(sb, insn, increment: true, total); return;
            case "Dec16": EmitZ80IncDec16(sb, insn, increment: false, total); return;
            case "IncReg": EmitZ80IncDec8(sb, insn.Ops[0].Args[0], f, flags, increment: true, isMem: false, pc, total); return;
            case "DecReg": EmitZ80IncDec8(sb, insn.Ops[0].Args[0], f, flags, increment: false, isMem: false, pc, total); return;
            case "IncMem8": EmitZ80IncDec8(sb, null, f, flags, increment: true, isMem: true, pc, total); return;
            case "DecMem8": EmitZ80IncDec8(sb, null, f, flags, increment: false, isMem: true, pc, total); return;
        }

        // 8-bit ALU (ADD/ADC/SUB/SBC/AND/OR/XOR/CP A,s). Resolve the source into `byte data`.
        int busReads = EmitZ80AluSource(sb, insn, pc, pcType);
        EmitZ80Alu8(sb, kind, f, flags);
        // Internal T-states = total − (opcode fetch already charged by Step) − operand bus reads.
        // Step's ReadBus(opcode) charged 1; this body charged `busReads`. Add the remainder.
        int internalT = total - 1 - busReads;
        if (internalT > 0) sb.AppendLine($"        _cycles += {internalT};");
    }

    /// <summary>Resolve the 8-bit ALU/compare source into <c>byte data</c>. Returns the number of
    /// ReadBus calls this emits (so the caller can balance the T-state total).</summary>
    private static int EmitZ80AluSource(StringBuilder sb, InstructionModel insn, string pc, string pcType)
    {
        switch (insn.Mode)
        {
            case "Register":
                string srcReg = insn.Ops[0].Args.Length > 1 ? insn.Ops[0].Args[1] : SourceRegFromOpcode(insn);
                sb.AppendLine($"        byte data = {srcReg};");
                return 0;
            case "RegisterIndirect":
                sb.AppendLine("        byte data = ReadBus(HL);");
                return 1;
            case "Immediate":
                sb.AppendLine($"        byte data = ReadBus({pc});");
                sb.AppendLine($"        {pc} = unchecked(({pcType})({pc} + 1));");
                return 1;
            default:
                throw new System.InvalidOperationException(
                    $"Z80 ALU: no source resolution for mode '{insn.Mode}' (opcode 0x{insn.Opcode:X2})");
        }
    }

    /// <summary>The 8-bit ALU register source named in the opcode's low 3 bits (B C D E H L _ A).
    /// (HL) is opcode bits == 6 — handled by RegisterIndirect, not here. M3.4e-2: a DD/FD-prefixed
    /// ALU register row (e.g. DD 84 = ADD A,IXh) re-reads the H/L source slot as the index half
    /// (IXh/IXl/IYh/IYl) — the undoc half ALU forms; the prefix is the OperationKey high byte.</summary>
    private static string SourceRegFromOpcode(InstructionModel insn)
    {
        int slot = insn.Opcode & 0x07;
        uint prefix = insn.OperationKey >> 8;
        if (prefix is 0xDD or 0xFD && slot is 4 or 5)
            return prefix == 0xDD
                ? (slot == 4 ? "IXh" : "IXl")
                : (slot == 4 ? "IYh" : "IYl");
        string[] regs = ["B", "C", "D", "E", "H", "L", "(HL)", "A"];
        return regs[slot];
    }

    private static void EmitZ80Alu8(StringBuilder sb, string kind, string f, FlagBitMap flags)
    {
        // Resolved Z80 flag masks (per-spec via FlagBit): S=bit7 Z H X=bit3 Y=bit5 P N C.
        string sMask = $"0x{(byte)(1 << flags.BitOf("S")):X2}";
        string zMask = $"0x{(byte)(1 << flags.BitOf("Z")):X2}";
        string yMask = $"0x{(byte)(1 << flags.BitOf("Y")):X2}";
        string hMask = $"0x{(byte)(1 << flags.BitOf("H")):X2}";
        string xMask = $"0x{(byte)(1 << flags.BitOf("X")):X2}";
        string pMask = $"0x{(byte)(1 << flags.BitOf("P")):X2}";
        string nMask = $"0x{(byte)(1 << flags.BitOf("N")):X2}";
        string cMask = $"0x{(byte)(1 << flags.BitOf("C")):X2}";

        switch (kind)
        {
            case "Add8":
            case "Adc8":
            {
                string carryIn = kind == "Adc8" ? $"(({f} & {cMask}) != 0 ? 1 : 0)" : "0";
                sb.AppendLine($"        int cin = {carryIn};");
                sb.AppendLine("        int sum = A + data + cin;");
                sb.AppendLine("        int half = (A & 0x0F) + (data & 0x0F) + cin;");
                sb.AppendLine("        byte res = unchecked((byte)sum);");
                sb.AppendLine("        int ov = (~(A ^ data) & (A ^ res) & 0x80);");
                EmitZ80FlagWord(sb, f, sMask, zMask, yMask, hMask, xMask, pMask, nMask, cMask,
                    halfExpr: "((half & 0x10) != 0)", ovExpr: "(ov != 0)", subtract: false,
                    carryExpr: "(sum > 0xFF)", resultVar: "res", xyFrom: "res");
                sb.AppendLine("        A = res;");
                return;
            }
            case "Sub8":
            case "Sbc8":
            case "Cp8":
            {
                string carryIn = kind == "Sbc8" ? $"(({f} & {cMask}) != 0 ? 1 : 0)" : "0";
                sb.AppendLine($"        int cin = {carryIn};");
                sb.AppendLine("        int diff = A - data - cin;");
                sb.AppendLine("        int half = (A & 0x0F) - (data & 0x0F) - cin;");
                sb.AppendLine("        byte res = unchecked((byte)diff);");
                sb.AppendLine("        int ov = ((A ^ data) & (A ^ res) & 0x80);");
                // CP takes X/Y from the OPERAND (data), not the result (the Z80 quirk).
                string xy = kind == "Cp8" ? "data" : "res";
                EmitZ80FlagWord(sb, f, sMask, zMask, yMask, hMask, xMask, pMask, nMask, cMask,
                    halfExpr: "((half & 0x10) != 0)", ovExpr: "(ov != 0)", subtract: true,
                    carryExpr: "(diff < 0)", resultVar: "res", xyFrom: xy);
                if (kind != "Cp8") sb.AppendLine("        A = res;");
                return;
            }
            case "And8":
            case "Or8":
            case "Xor8":
            {
                string opExpr = kind switch { "And8" => "A & data", "Or8" => "A | data", _ => "A ^ data" };
                sb.AppendLine($"        byte res = unchecked((byte)({opExpr}));");
                // H: AND sets H=1, OR/XOR set H=0. P/V = parity. N=0. C=0.
                string hSet = kind == "And8" ? hMask : "0x00";
                sb.AppendLine($"        {f} = unchecked((byte)(");
                sb.AppendLine($"              ((res & 0x80) != 0 ? {sMask} : 0x00)");
                sb.AppendLine($"            | (res == 0 ? {zMask} : 0x00)");
                sb.AppendLine($"            | ((res & 0x20) != 0 ? {yMask} : 0x00)");
                sb.AppendLine($"            | {hSet}");
                sb.AppendLine($"            | ((res & 0x08) != 0 ? {xMask} : 0x00)");
                sb.AppendLine($"            | ((System.Numerics.BitOperations.PopCount((uint)res) & 1) == 0 ? {pMask} : 0x00)));");
                sb.AppendLine("        A = res;");
                return;
            }
            default:
                throw new System.InvalidOperationException($"Z80 ALU: no template for op '{kind}'");
        }
    }

    /// <summary>Emit the full F flag word for an add/sub-shaped ALU op. Uses the per-spec masks.</summary>
    private static void EmitZ80FlagWord(
        StringBuilder sb, string f, string sMask, string zMask, string yMask, string hMask,
        string xMask, string pMask, string nMask, string cMask,
        string halfExpr, string ovExpr, bool subtract, string carryExpr, string resultVar, string xyFrom)
    {
        sb.AppendLine($"        {f} = unchecked((byte)(");
        sb.AppendLine($"              (({resultVar} & 0x80) != 0 ? {sMask} : 0x00)");
        sb.AppendLine($"            | ({resultVar} == 0 ? {zMask} : 0x00)");
        sb.AppendLine($"            | (({xyFrom} & 0x20) != 0 ? {yMask} : 0x00)");
        sb.AppendLine($"            | ({halfExpr} ? {hMask} : 0x00)");
        sb.AppendLine($"            | (({xyFrom} & 0x08) != 0 ? {xMask} : 0x00)");
        sb.AppendLine($"            | ({ovExpr} ? {pMask} : 0x00)");
        sb.AppendLine($"            | {(subtract ? nMask : "0x00")}");
        sb.AppendLine($"            | ({carryExpr} ? {cMask} : 0x00)));");
    }

    private static void EmitZ80IncDec8(
        StringBuilder sb, string? reg, string f, FlagBitMap flags, bool increment, bool isMem, string pc, int total)
    {
        string sMask = $"0x{(byte)(1 << flags.BitOf("S")):X2}";
        string zMask = $"0x{(byte)(1 << flags.BitOf("Z")):X2}";
        string yMask = $"0x{(byte)(1 << flags.BitOf("Y")):X2}";
        string hMask = $"0x{(byte)(1 << flags.BitOf("H")):X2}";
        string xMask = $"0x{(byte)(1 << flags.BitOf("X")):X2}";
        string pMask = $"0x{(byte)(1 << flags.BitOf("P")):X2}";
        string nMask = $"0x{(byte)(1 << flags.BitOf("N")):X2}";
        string cMask = $"0x{(byte)(1 << flags.BitOf("C")):X2}";
        string delta = increment ? "+ 1" : "- 1";
        int busReads = 0, busWrites = 0;

        if (isMem)
        {
            sb.AppendLine("        byte before = ReadBus(HL);");
            sb.AppendLine($"        byte res = unchecked((byte)(before {delta}));");
            busReads = 1;
        }
        else
        {
            sb.AppendLine($"        byte before = {reg};");
            sb.AppendLine($"        byte res = unchecked((byte)(before {delta}));");
        }

        // H: INC = (before&0xF)==0xF; DEC = (before&0xF)==0. P/V: INC overflow at 0x7F→0x80; DEC at 0x80→0x7F.
        string halfExpr = increment ? "((before & 0x0F) == 0x0F)" : "((before & 0x0F) == 0x00)";
        string ovExpr = increment ? "(before == 0x7F)" : "(before == 0x80)";
        // C is PRESERVED — start from the old C bit only.
        sb.AppendLine($"        {f} = unchecked((byte)(({f} & {cMask})");
        sb.AppendLine($"            | ((res & 0x80) != 0 ? {sMask} : 0x00)");
        sb.AppendLine($"            | (res == 0 ? {zMask} : 0x00)");
        sb.AppendLine($"            | ((res & 0x20) != 0 ? {yMask} : 0x00)");
        sb.AppendLine($"            | ({halfExpr} ? {hMask} : 0x00)");
        sb.AppendLine($"            | ((res & 0x08) != 0 ? {xMask} : 0x00)");
        sb.AppendLine($"            | ({ovExpr} ? {pMask} : 0x00)");
        sb.AppendLine($"            | {(increment ? "0x00" : nMask)}));");

        if (isMem)
        {
            sb.AppendLine("        WriteBus(HL, res);");
            busWrites = 1;
        }
        else
            sb.AppendLine($"        {reg} = res;");

        int internalT = total - 1 - busReads - busWrites;
        if (internalT > 0) sb.AppendLine($"        _cycles += {internalT};");
    }

    private static void EmitZ80Add16(StringBuilder sb, InstructionModel insn, string f, FlagBitMap flags, int total)
    {
        // ADD HL,rr (0x09/19/29/39) ; M3.4e-2: ADD IX,rr / ADD IY,rr (DD/FD). Target = Args[0]
        // (HL by default; IX/IY for the prefixed plane), source = Args[1].
        string dst = insn.Ops[0].Args[0];
        string src = insn.Ops[0].Args[1];
        string hMask = $"0x{(byte)(1 << flags.BitOf("H")):X2}";
        string nMask = $"0x{(byte)(1 << flags.BitOf("N")):X2}";
        string cMask = $"0x{(byte)(1 << flags.BitOf("C")):X2}";
        string yMask = $"0x{(byte)(1 << flags.BitOf("Y")):X2}";
        string xMask = $"0x{(byte)(1 << flags.BitOf("X")):X2}";
        // S/Z/P-V preserved; H from bit 11; C from bit 15; N=0; X/Y from the high byte of the result.
        sb.AppendLine($"        int hl = {dst};");
        EmitWz(sb, "hl + 1");   // ADD dst,rr → WZ = pre-op dst + 1 (vector-confirmed; IX+1 for ADD IX,rr)
        sb.AppendLine($"        int rr = {src};");
        sb.AppendLine("        int sum16 = hl + rr;");
        sb.AppendLine("        int half16 = (hl & 0x0FFF) + (rr & 0x0FFF);");
        sb.AppendLine("        ushort res16 = unchecked((ushort)sum16);");
        string preserve = $"0x{(byte)(1 << flags.BitOf("S") | 1 << flags.BitOf("Z") | 1 << flags.BitOf("P")):X2}";
        sb.AppendLine($"        {f} = unchecked((byte)(({f} & {preserve})");
        sb.AppendLine($"            | ((half16 & 0x1000) != 0 ? {hMask} : 0x00)");
        sb.AppendLine($"            | (sum16 > 0xFFFF ? {cMask} : 0x00)");
        sb.AppendLine($"            | (((res16 >> 8) & 0x20) != 0 ? {yMask} : 0x00)");
        sb.AppendLine($"            | (((res16 >> 8) & 0x08) != 0 ? {xMask} : 0x00)));");
        sb.AppendLine($"        {dst} = res16;");
        int internalT = total - 1;   // no bus access beyond the fetch; the rest is internal
        if (internalT > 0) sb.AppendLine($"        _cycles += {internalT};");
    }

    private static void EmitZ80IncDec16(StringBuilder sb, InstructionModel insn, bool increment, int total)
    {
        // INC rr / DEC rr — NO flags (the Z80 quirk). target pair view named in the op arg.
        string target = insn.Ops[0].Args[0];
        string delta = increment ? "+ 1" : "- 1";
        sb.AppendLine($"        {target} = unchecked((ushort)({target} {delta}));");
        int internalT = total - 1;
        if (internalT > 0) sb.AppendLine($"        _cycles += {internalT};");
    }

    // ---- Z80 16-bit LD class (LD rr,nn ; LD (nn),HL ; LD HL,(nn) ; LD (HL),n) ----

    private static void EmitZ80LdBody(StringBuilder sb, InstructionModel insn, string pc, string pcType)
    {
        string kind = insn.Ops[0].Kind;
        int total = Z80Cycles(insn.Mode, InstructionClass.Z80Ld, kind);
        switch (kind)
        {
            case "Load16":   // LD rr,nn — two operand bytes (little-endian) → the pair/16-bit reg.
            {
                string target = insn.Ops[0].Args[0];
                sb.AppendLine($"        byte lo = ReadBus({pc});");
                sb.AppendLine($"        {pc} = unchecked(({pcType})({pc} + 1));");
                sb.AppendLine($"        byte hi = ReadBus({pc});");
                sb.AppendLine($"        {pc} = unchecked(({pcType})({pc} + 1));");
                sb.AppendLine($"        {target} = unchecked((ushort)(lo | (hi << 8)));");
                EmitInternal(sb, total, busReads: 2, busWrites: 0);
                return;
            }
            case "Store16":  // LD (nn),rr — fetch addr, write lo then hi.
            {
                string source = insn.Ops[0].Args[0];
                sb.AppendLine($"        byte al = ReadBus({pc});");
                sb.AppendLine($"        {pc} = unchecked(({pcType})({pc} + 1));");
                sb.AppendLine($"        byte ah = ReadBus({pc});");
                sb.AppendLine($"        {pc} = unchecked(({pcType})({pc} + 1));");
                sb.AppendLine("        uint ea = (uint)(al | (ah << 8));");
                EmitWz(sb, "ea + 1");   // LD (nn),rr → WZ = nn + 1
                sb.AppendLine($"        WriteBus(ea, unchecked((byte){source}));");
                sb.AppendLine($"        WriteBus((ea + 1) & 0xFFFF, unchecked((byte)({source} >> 8)));");
                EmitInternal(sb, total, busReads: 2, busWrites: 2);
                return;
            }
            case "LoadMem16":  // LD rr,(nn) — fetch addr, read lo then hi.
            {
                string target = insn.Ops[0].Args[0];
                sb.AppendLine($"        byte al = ReadBus({pc});");
                sb.AppendLine($"        {pc} = unchecked(({pcType})({pc} + 1));");
                sb.AppendLine($"        byte ah = ReadBus({pc});");
                sb.AppendLine($"        {pc} = unchecked(({pcType})({pc} + 1));");
                sb.AppendLine("        uint ea = (uint)(al | (ah << 8));");
                EmitWz(sb, "ea + 1");   // LD rr,(nn) → WZ = nn + 1
                sb.AppendLine("        byte vlo = ReadBus(ea);");
                sb.AppendLine("        byte vhi = ReadBus((ea + 1) & 0xFFFF);");
                sb.AppendLine($"        {target} = unchecked((ushort)(vlo | (vhi << 8)));");
                EmitInternal(sb, total, busReads: 4, busWrites: 0);
                return;
            }
            case "StoreImm8":  // LD (HL),n — fetch n, write to (HL).
            {
                sb.AppendLine($"        byte data = ReadBus({pc});");
                sb.AppendLine($"        {pc} = unchecked(({pcType})({pc} + 1));");
                sb.AppendLine("        WriteBus(HL, data);");
                EmitInternal(sb, total, busReads: 1, busWrites: 1);
                return;
            }
            default:
                throw new System.InvalidOperationException($"Z80 LD: no template for op '{kind}'");
        }
    }

    // ---- Z80 pair stack (PUSH rr / POP rr) ----

    private static void EmitZ80StackBody(StringBuilder sb, InstructionModel insn, string pc, string? spReg)
    {
        string sp = spReg ?? "SP";
        string kind = insn.Ops[0].Kind;
        string pair = insn.Ops[0].Args[0];
        int total = Z80Cycles(insn.Mode, InstructionClass.Z80Stack, kind);
        if (kind == "Push16")
        {
            // SP-=1, write hi; SP-=1, write lo.
            sb.AppendLine($"        {sp} = unchecked((ushort)({sp} - 1));");
            sb.AppendLine($"        WriteBus({sp}, unchecked((byte)({pair} >> 8)));");
            sb.AppendLine($"        {sp} = unchecked((ushort)({sp} - 1));");
            sb.AppendLine($"        WriteBus({sp}, unchecked((byte){pair}));");
            EmitInternal(sb, total, busReads: 0, busWrites: 2);
        }
        else // Pop16
        {
            sb.AppendLine($"        byte lo = ReadBus({sp});");
            sb.AppendLine($"        {sp} = unchecked((ushort)({sp} + 1));");
            sb.AppendLine($"        byte hi = ReadBus({sp});");
            sb.AppendLine($"        {sp} = unchecked((ushort)({sp} + 1));");
            sb.AppendLine($"        {pair} = unchecked((ushort)(lo | (hi << 8)));");
            EmitInternal(sb, total, busReads: 2, busWrites: 0);
        }
    }

    // ---- Z80 exchange (EX DE,HL ; EX AF,AF' ; EXX ; EX (SP),HL) ----

    private static void EmitZ80ExchangeBody(StringBuilder sb, InstructionModel insn, string pc, string? spReg)
    {
        string sp = spReg ?? "SP";
        string kind = insn.Ops[0].Kind;
        int total = Z80Cycles(insn.Mode, InstructionClass.Z80Exchange, kind);
        switch (kind)
        {
            case "ExDeHl":
                sb.AppendLine("        (D, H) = (H, D);");
                sb.AppendLine("        (E, L) = (L, E);");
                EmitInternal(sb, total, 0, 0);
                return;
            case "ExAfAf":
                sb.AppendLine("        (A, A_) = (A_, A);");
                sb.AppendLine("        (F, F_) = (F_, F);");
                EmitInternal(sb, total, 0, 0);
                return;
            case "Exx":
                sb.AppendLine("        (B, B_) = (B_, B);");
                sb.AppendLine("        (C, C_) = (C_, C);");
                sb.AppendLine("        (D, D_) = (D_, D);");
                sb.AppendLine("        (E, E_) = (E_, E);");
                sb.AppendLine("        (H, H_) = (H_, H);");
                sb.AppendLine("        (L, L_) = (L_, L);");
                EmitInternal(sb, total, 0, 0);
                return;
            case "ExSpHl":  // EX (SP),HL — swap HL with the word at (SP). The Z80 reads (SP) then (SP+1),
                            // then writes (SP+1)=H BEFORE (SP)=L (the documented write order TomHarte checks).
                            // M3.4e-2: EX (SP),IX / EX (SP),IY (DD/FD) — the pair is read from the prefix
                            // (0xDD -> IX, else IY); a base (unprefixed) row uses HL (byte-identical output).
            {
                string pair = (insn.OperationKey >> 8) == 0xDD ? "IX"
                            : (insn.OperationKey >> 8) == 0xFD ? "IY"
                            : "HL";
                sb.AppendLine($"        byte slo = ReadBus({sp});");
                sb.AppendLine($"        byte shi = ReadBus((uint)(({sp} + 1) & 0xFFFF));");
                sb.AppendLine($"        WriteBus((uint)(({sp} + 1) & 0xFFFF), unchecked((byte)({pair} >> 8)));");
                sb.AppendLine($"        WriteBus({sp}, unchecked((byte){pair}));");
                sb.AppendLine($"        {pair} = unchecked((ushort)(slo | (shi << 8)));");
                EmitWz(sb, pair);   // EX (SP),pair → WZ = the new pair value (post-exchange; vector-confirmed)
                EmitInternal(sb, total, busReads: 2, busWrites: 2);
                return;
            }
            default:
                throw new System.InvalidOperationException($"Z80 exchange: no template for op '{kind}'");
        }
    }

    // ---- Z80 misc (DAA / CPL / SCF / CCF / DI / EI) ----

    private static void EmitZ80MiscBody(StringBuilder sb, InstructionModel insn, string pc, string? statusReg, FlagBitMap flags)
    {
        string f = statusReg ?? "F";
        string kind = insn.Ops[0].Kind;
        int total = Z80Cycles(insn.Mode, InstructionClass.Z80Misc, kind);
        string sMask = $"0x{(byte)(1 << flags.BitOf("S")):X2}";
        string zMask = $"0x{(byte)(1 << flags.BitOf("Z")):X2}";
        string yMask = $"0x{(byte)(1 << flags.BitOf("Y")):X2}";
        string hMask = $"0x{(byte)(1 << flags.BitOf("H")):X2}";
        string xMask = $"0x{(byte)(1 << flags.BitOf("X")):X2}";
        string pMask = $"0x{(byte)(1 << flags.BitOf("P")):X2}";
        string nMask = $"0x{(byte)(1 << flags.BitOf("N")):X2}";
        string cMask = $"0x{(byte)(1 << flags.BitOf("C")):X2}";
        switch (kind)
        {
            case "Cpl":  // A = ~A; H=1, N=1; X/Y from new A; S/Z/P/C preserved.
                sb.AppendLine("        A = unchecked((byte)~A);");
                sb.AppendLine($"        {f} = unchecked((byte)(({f} & {(string)$"0x{(byte)~(byte)((1<<flags.BitOf("H"))|(1<<flags.BitOf("N"))|(1<<flags.BitOf("X"))|(1<<flags.BitOf("Y"))):X2}"})");
                sb.AppendLine($"            | {hMask} | {nMask}");
                sb.AppendLine($"            | ((A & 0x20) != 0 ? {yMask} : 0x00)");
                sb.AppendLine($"            | ((A & 0x08) != 0 ? {xMask} : 0x00)));");
                break;
            case "Scf":  // C=1, H=0, N=0; X/Y from (Q ^ F) | A (the q-quirk); S/Z/P preserved.
                sb.AppendLine($"        int xy = (Q ^ {f}) | A;");
                sb.AppendLine($"        {f} = unchecked((byte)(({f} & {(string)$"0x{(byte)(1<<flags.BitOf("S")|1<<flags.BitOf("Z")|1<<flags.BitOf("P")):X2}"})");
                sb.AppendLine($"            | {cMask}");
                sb.AppendLine($"            | ((xy & 0x20) != 0 ? {yMask} : 0x00)");
                sb.AppendLine($"            | ((xy & 0x08) != 0 ? {xMask} : 0x00)));");
                break;
            case "Ccf":  // C = ~C, H = old C, N=0; X/Y from (Q ^ F) | A; S/Z/P preserved.
                sb.AppendLine($"        bool oldC = ({f} & {cMask}) != 0;");
                sb.AppendLine($"        int xy = (Q ^ {f}) | A;");
                sb.AppendLine($"        {f} = unchecked((byte)(({f} & {(string)$"0x{(byte)(1<<flags.BitOf("S")|1<<flags.BitOf("Z")|1<<flags.BitOf("P")):X2}"})");
                sb.AppendLine($"            | (oldC ? 0x00 : {cMask})");
                sb.AppendLine($"            | (oldC ? {hMask} : 0x00)");
                sb.AppendLine($"            | ((xy & 0x20) != 0 ? {yMask} : 0x00)");
                sb.AppendLine($"            | ((xy & 0x08) != 0 ? {xMask} : 0x00)));");
                break;
            case "Daa":
                EmitZ80Daa(sb, f, sMask, zMask, yMask, hMask, xMask, pMask, nMask, cMask);
                break;
            case "Di":
                sb.AppendLine("        _iff1 = false; _iff2 = false;");
                break;
            case "Ei":
                // M3.5-1: EI has a one-instruction delay (interrupts enable only AFTER the next
                // instruction). The partial owns the delay latch via OnInterruptEnable(); the generated
                // body delegates to it rather than writing _iff1/_iff2 directly.
                // CONTRACT: a structured CPU that declares an `Ei` op MUST implement the
                // `partial void OnInterruptEnable()` hook to set its IFF latches — because it is a
                // `partial void`, an UNIMPLEMENTED hook makes the C# compiler ELIDE this call entirely,
                // so EI would silently do NOTHING (not merely "no delay" — no enable at all). The Z80
                // partial implements it (sets IFF1/IFF2 + the delay window). The 6502 has no `Ei` op and
                // never reaches this arm, so its generated body is byte-identical.
                sb.AppendLine("        OnInterruptEnable();");
                break;
            default:
                throw new System.InvalidOperationException($"Z80 misc: no template for op '{kind}'");
        }
        EmitInternal(sb, total, 0, 0);
    }

    /// <summary>DAA — the documented Z80 BCD correction (truth = the 0x27 TomHarte vectors). Uses H
    /// and N. Sets S/Z/X/Y/P(parity)/C/H.</summary>
    private static void EmitZ80Daa(
        StringBuilder sb, string f, string sMask, string zMask, string yMask, string hMask,
        string xMask, string pMask, string nMask, string cMask)
    {
        sb.AppendLine($"        bool nflag = ({f} & {nMask}) != 0;");
        sb.AppendLine($"        bool hflag = ({f} & {hMask}) != 0;");
        sb.AppendLine($"        bool cflag = ({f} & {cMask}) != 0;");
        sb.AppendLine("        int corr = 0;");
        sb.AppendLine("        bool newC = cflag;");
        sb.AppendLine("        if (hflag || (A & 0x0F) > 0x09) corr |= 0x06;");
        sb.AppendLine("        if (cflag || A > 0x99) { corr |= 0x60; newC = true; }");
        sb.AppendLine("        int before = A;");
        sb.AppendLine("        byte res = unchecked((byte)(nflag ? A - corr : A + corr));");
        // H after DAA: for add, H = (low nibble carry); for sub, H = borrow. Documented formula:
        sb.AppendLine("        bool newH = nflag ? (hflag && (before & 0x0F) < 0x06) : ((before & 0x0F) > 0x09);");
        sb.AppendLine("        A = res;");
        sb.AppendLine($"        {f} = unchecked((byte)(");
        sb.AppendLine($"              ((res & 0x80) != 0 ? {sMask} : 0x00)");
        sb.AppendLine($"            | (res == 0 ? {zMask} : 0x00)");
        sb.AppendLine($"            | ((res & 0x20) != 0 ? {yMask} : 0x00)");
        sb.AppendLine($"            | (newH ? {hMask} : 0x00)");
        sb.AppendLine($"            | ((res & 0x08) != 0 ? {xMask} : 0x00)");
        sb.AppendLine($"            | ((System.Numerics.BitOperations.PopCount((uint)res) & 1) == 0 ? {pMask} : 0x00)");
        sb.AppendLine($"            | (nflag ? {nMask} : 0x00)");
        sb.AppendLine($"            | (newC ? {cMask} : 0x00)));");
    }

    // ---- Z80 flow (JP/CALL/RET/RST/JR/DJNZ — conditional + relative) ----

    /// <summary>M3.4c (Piece A): emit the WZ/MEMPTR write <c>WZ = unchecked((ushort)(&lt;expr&gt;));</c>. The
    /// MEMPTR rules are per-op (the documented Z80 internal pointer); each Z80 emit arm appends the
    /// right WZ assignment so the runner's universal final-WZ check (A-Task 3) passes. WZ is a declared
    /// register (Z80Spec.cs), so this compiles on the real spec + every WZ-declaring synthetic spec.</summary>
    private static void EmitWz(StringBuilder sb, string expr) =>
        sb.AppendLine($"        WZ = unchecked((ushort)({expr}));");

    /// <summary>The 12-space-indented variant of <see cref="EmitWz"/>, for a WZ write INSIDE an
    /// <c>if (taken) {{ … }}</c> block (JR cc / DJNZ / RET cc — WZ is written only when taken).</summary>
    private static void EmitWzIndented(StringBuilder sb, string expr) =>
        sb.AppendLine($"            WZ = unchecked((ushort)({expr}));");

    /// <summary>M3.4e-1a (Z80 IX/IY): emit the indexed effective-address computation
    /// <c>ushort __ea = unchecked((ushort)(&lt;indexReg&gt; + (sbyte)(&lt;dispExpr&gt;)));</c>. The
    /// displacement is SIGNED (the (IX+d) range is IX-128..IX+127). <paramref name="indexReg"/> is the
    /// 16-bit index register NAME ("IX"/"IY"); <paramref name="dispExpr"/> is the displacement-byte
    /// expression — for the DD/FD-core forms the decode walk's first operand byte (the byte after the
    /// opcode); for the DDCB/FDCB compound forms the byte the compound walk surfaces (M3.4e-1b). Every
    /// indexed emit arm (M3.4e-2/3) calls this so the EA is computed identically and lives in a known
    /// local (__ea). e-1a ships the helper; no live opcode calls it yet. Marked internal so the test
    /// assembly unit-tests it directly (InternalsVisibleTo("CpuEmulator.Tests")).</summary>
    internal static void EmitZ80IndexedEa(StringBuilder sb, string indexReg, string dispExpr) =>
        sb.AppendLine($"        ushort __ea = unchecked((ushort)({indexReg} + (sbyte)({dispExpr})));");

    private static void EmitZ80FlowBody(
        StringBuilder sb, InstructionModel insn, string pc, string pcType, string? statusReg, string? spReg, FlagBitMap flags)
    {
        string sp = spReg ?? "SP";
        string f = statusReg ?? "F";
        var op = insn.Ops[0];
        string kind = op.Kind;
        int total = Z80Cycles(insn.Mode, InstructionClass.Z80Flow, kind);

        // The condition-code test (Flag + sense), shared by JumpIf/CallIf/RetCc/RelJumpIf.
        string CondExpr()
        {
            int bit = flags.BitOf(op.Args[0]);
            bool when = op.Args[1] == "true";
            return $"((({f} >> {bit}) & 1) == {(when ? 1 : 0)})";
        }

        switch (kind)
        {
            case "JumpIndirect":  // JP (HL) — PC = HL (no memory read). M3.4e-2: JP (IX)/JP (IY) (DD/FD) —
                                  // the pair is read from the prefix (0xDD -> IX, else IY); base uses HL.
            {
                string pair = (insn.OperationKey >> 8) == 0xDD ? "IX"
                            : (insn.OperationKey >> 8) == 0xFD ? "IY"
                            : "HL";
                sb.AppendLine($"        {pc} = {pair};");
                EmitInternal(sb, total, 0, 0);
                return;
            }
            case "JumpAbs":  // JP nn — read the 16-bit target, PC = nn. 10 T-states.
                sb.AppendLine($"        byte jl = ReadBus({pc});");
                sb.AppendLine($"        {pc} = unchecked(({pcType})({pc} + 1));");
                sb.AppendLine($"        byte jh = ReadBus({pc});");
                sb.AppendLine($"        {pc} = unchecked(({pcType})(jl | (jh << 8)));");
                EmitWz(sb, pc);   // WZ = nn (the new PC)
                EmitInternal(sb, total, busReads: 2, busWrites: 0);
                return;
            case "CallAbs":  // CALL nn — read nn, push PC, PC = nn. 17 T-states.
                sb.AppendLine($"        byte cl = ReadBus({pc});");
                sb.AppendLine($"        {pc} = unchecked(({pcType})({pc} + 1));");
                sb.AppendLine($"        byte ch = ReadBus({pc});");
                sb.AppendLine($"        {pc} = unchecked(({pcType})({pc} + 1));");
                sb.AppendLine($"        {sp} = unchecked((ushort)({sp} - 1));");
                sb.AppendLine($"        WriteBus({sp}, unchecked((byte)({pc} >> 8)));");
                sb.AppendLine($"        {sp} = unchecked((ushort)({sp} - 1));");
                sb.AppendLine($"        WriteBus({sp}, unchecked((byte){pc}));");
                sb.AppendLine($"        {pc} = unchecked(({pcType})(cl | (ch << 8)));");
                EmitWz(sb, pc);   // WZ = nn (the new PC)
                EmitInternal(sb, total, busReads: 2, busWrites: 2);
                return;
            case "Ret":  // RET — pop PC. 10 T-states.
                sb.AppendLine($"        byte rl = ReadBus({sp});");
                sb.AppendLine($"        {sp} = unchecked((ushort)({sp} + 1));");
                sb.AppendLine($"        byte rh = ReadBus({sp});");
                sb.AppendLine($"        {sp} = unchecked((ushort)({sp} + 1));");
                sb.AppendLine($"        {pc} = unchecked(({pcType})(rl | (rh << 8)));");
                EmitWz(sb, pc);   // WZ = popped PC
                EmitInternal(sb, total, busReads: 2, busWrites: 0);
                return;
            case "RelJump":  // JR d — read signed d, PC += d.
                sb.AppendLine($"        sbyte d = unchecked((sbyte)ReadBus({pc}));");
                sb.AppendLine($"        {pc} = unchecked(({pcType})({pc} + 1));");
                sb.AppendLine($"        {pc} = unchecked(({pcType})({pc} + d));");
                EmitWz(sb, pc);   // WZ = dest (the new PC)
                EmitInternal(sb, total, busReads: 1, busWrites: 0);
                return;
            case "RelJumpIf":  // JR cc,d — always reads d; if taken, PC += d (taken adds 5 T-states).
                sb.AppendLine($"        sbyte d = unchecked((sbyte)ReadBus({pc}));");
                sb.AppendLine($"        {pc} = unchecked(({pcType})({pc} + 1));");
                sb.AppendLine($"        if ({CondExpr()})");
                sb.AppendLine("        {");
                sb.AppendLine($"            {pc} = unchecked(({pcType})({pc} + d));");
                sb.AppendLine("            _cycles += 5;   // taken penalty (7 → 12)");
                EmitWzIndented(sb, pc);   // WZ = dest ONLY when taken (vector-confirmed: JR cc not-taken leaves WZ)
                sb.AppendLine("        }");
                EmitInternal(sb, total, busReads: 1, busWrites: 0);
                return;
            case "Djnz":  // B--; read d; if B!=0 PC+=d.
            {
                string b = op.Args[0];
                sb.AppendLine($"        {b} = unchecked((byte)({b} - 1));");
                sb.AppendLine($"        sbyte d = unchecked((sbyte)ReadBus({pc}));");
                sb.AppendLine($"        {pc} = unchecked(({pcType})({pc} + 1));");
                sb.AppendLine($"        if ({b} != 0)");
                sb.AppendLine("        {");
                sb.AppendLine($"            {pc} = unchecked(({pcType})({pc} + d));");
                sb.AppendLine("            _cycles += 5;   // taken penalty (8 → 13)");
                EmitWzIndented(sb, pc);   // WZ = dest ONLY when taken
                sb.AppendLine("        }");
                EmitInternal(sb, total, busReads: 1, busWrites: 0);
                return;
            }
            case "JumpIf":  // JP cc,nn — always reads nn (16); if taken PC = nn. Always 10 T-states.
                sb.AppendLine($"        byte jl = ReadBus({pc});");
                sb.AppendLine($"        {pc} = unchecked(({pcType})({pc} + 1));");
                sb.AppendLine($"        byte jh = ReadBus({pc});");
                sb.AppendLine($"        {pc} = unchecked(({pcType})({pc} + 1));");
                EmitWz(sb, "jl | (jh << 8)");   // WZ = nn UNCONDITIONALLY (operand always fetched; vector-confirmed)
                sb.AppendLine($"        if ({CondExpr()}) {pc} = unchecked(({pcType})(jl | (jh << 8)));");
                EmitInternal(sb, total, busReads: 2, busWrites: 0);
                return;
            case "CallIf":  // CALL cc,nn — read nn; if taken push PC, PC = nn (taken adds 7 T-states).
                sb.AppendLine($"        byte cl = ReadBus({pc});");
                sb.AppendLine($"        {pc} = unchecked(({pcType})({pc} + 1));");
                sb.AppendLine($"        byte ch = ReadBus({pc});");
                sb.AppendLine($"        {pc} = unchecked(({pcType})({pc} + 1));");
                EmitWz(sb, "cl | (ch << 8)");   // WZ = nn UNCONDITIONALLY (operand always fetched; vector-confirmed)
                sb.AppendLine($"        if ({CondExpr()})");
                sb.AppendLine("        {");
                sb.AppendLine($"            {sp} = unchecked((ushort)({sp} - 1));");
                sb.AppendLine($"            WriteBus({sp}, unchecked((byte)({pc} >> 8)));");
                sb.AppendLine($"            {sp} = unchecked((ushort)({sp} - 1));");
                sb.AppendLine($"            WriteBus({sp}, unchecked((byte){pc}));");
                sb.AppendLine($"            {pc} = unchecked(({pcType})(cl | (ch << 8)));");
                sb.AppendLine("            _cycles += 5;   // taken penalty: 10 → 17, minus the 2 push writes charged inline");
                sb.AppendLine("        }");
                EmitInternal(sb, total, busReads: 2, busWrites: 0);
                return;
            case "RetCc":  // RET cc — if taken pop PC (taken adds 6 T-states; not-taken = 5).
                sb.AppendLine($"        if ({CondExpr()})");
                sb.AppendLine("        {");
                sb.AppendLine($"            byte rl = ReadBus({sp});");
                sb.AppendLine($"            {sp} = unchecked((ushort)({sp} + 1));");
                sb.AppendLine($"            byte rh = ReadBus({sp});");
                sb.AppendLine($"            {sp} = unchecked((ushort)({sp} + 1));");
                sb.AppendLine($"            {pc} = unchecked(({pcType})(rl | (rh << 8)));");
                sb.AppendLine("            _cycles += 4;   // taken penalty: 5 → 11, minus the 2 pop reads charged inline");
                EmitWzIndented(sb, pc);   // WZ = popped PC ONLY when taken (vector-confirmed)
                sb.AppendLine("        }");
                EmitInternal(sb, total, busReads: 0, busWrites: 0);
                return;
            case "Rst":  // RST n — push PC, PC = vector (opcode & 0x38). Always 11 T-states.
            {
                int vec = insn.Opcode & 0x38;
                sb.AppendLine($"        {sp} = unchecked((ushort)({sp} - 1));");
                sb.AppendLine($"        WriteBus({sp}, unchecked((byte)({pc} >> 8)));");
                sb.AppendLine($"        {sp} = unchecked((ushort)({sp} - 1));");
                sb.AppendLine($"        WriteBus({sp}, unchecked((byte){pc}));");
                sb.AppendLine($"        {pc} = 0x{vec:X2};");
                EmitWz(sb, $"0x{vec:X2}");   // WZ = the RST vector n
                EmitInternal(sb, total, busReads: 0, busWrites: 2);
                return;
            }
            default:
                throw new System.InvalidOperationException($"Z80 flow: no template for op '{kind}'");
        }
    }

    /// <summary>Add the internal (non-bus) T-states so the per-instruction cycle total equals the
    /// dataset T-state count: total − 1 (the opcode fetch Step already charged) − the body's bus
    /// accesses. Conditional taken-penalties are added inline in the body (so this is the not-taken
    /// remainder).</summary>
    private static void EmitInternal(StringBuilder sb, int total, int busReads, int busWrites)
    {
        int internalT = total - 1 - busReads - busWrites;
        if (internalT > 0) sb.AppendLine($"        _cycles += {internalT};");
    }

    // ── M3.4e-2 DD/FD indexed plane: LD/ALU/INC-DEC on the (IX+d)/(IY+d) effective address ──
    // Every form: read the displacement byte (the byte after the opcode), compute the signed EA via
    // EmitZ80IndexedEa, set WZ = EA (the (IX+d) MEMPTR rule), then operate on __ea. The index register
    // (IX vs IY) is read from the OperationKey prefix high byte (0xDD -> IX, else IY). Step charges the
    // 2 key bytes (prefix + opcode); the body charges (total - 2 - <body bus accesses>), the ED
    // precedent's cycle balance. The disp/imm reads and the memory access each charge 1 via ReadBus/
    // WriteBus on the real Z80Cpu.
    private static void EmitZ80IndexedBody(
        StringBuilder sb, InstructionModel insn, string pc, string pcType, string? statusReg, FlagBitMap flags)
    {
        string f = statusReg ?? "F";
        string ix = (insn.OperationKey >> 8) == 0xDD ? "IX" : "IY";   // the index register (G1 / Task 1)
        // Read the displacement byte and compute the signed EA, then publish WZ = EA.
        sb.AppendLine($"        byte d = ReadBus({pc});");
        sb.AppendLine($"        {pc} = unchecked(({pcType})({pc} + 1));");
        EmitZ80IndexedEa(sb, ix, "d");   // -> ushort __ea = unchecked((ushort)(IX + (sbyte)(d)));
        EmitWz(sb, "__ea");              // WZ = the computed EA

        switch (insn.Ops[0].Kind)
        {
            case "DdFdLdIndexed":
            {
                string op = Unquote(insn.Ops[0].Args[0]);    // LOAD / STORE
                string reg = Unquote(insn.Ops[0].Args[1]);   // B..A
                if (op == "LOAD")
                    sb.AppendLine($"        {reg} = ReadBus(__ea);");
                else
                    sb.AppendLine($"        WriteBus(__ea, {reg});");
                // 19 T: -2 key bytes (Step), -1 disp read, -1 memory access.
                sb.AppendLine($"        _cycles += {19 - 2 - 1 - 1};");
                return;
            }
            case "DdFdStoreImmIndexed":
            {
                sb.AppendLine($"        byte n = ReadBus({pc});");
                sb.AppendLine($"        {pc} = unchecked(({pcType})({pc} + 1));");
                sb.AppendLine("        WriteBus(__ea, n);");
                // 19 T: -2 key, -1 disp, -1 imm, -1 write.
                sb.AppendLine($"        _cycles += {19 - 2 - 1 - 1 - 1};");
                return;
            }
            case "DdFdAluIndexed":    EmitZ80IndexedAlu(sb, insn, f, flags); return;     // Task 3
            case "DdFdIncDecIndexed": EmitZ80IndexedIncDec(sb, insn, f, flags); return;  // Task 4
            default:
                throw new System.InvalidOperationException($"Z80Indexed: no template for '{insn.Ops[0].Kind}'");
        }
    }

    /// <summary>ALU A,(IX+d): data = ReadBus(__ea); run the 8-bit ALU op against A (reusing the base
    /// EmitZ80Alu8 flag math). __ea + WZ are already emitted by EmitZ80IndexedBody. Cycles 19.</summary>
    private static void EmitZ80IndexedAlu(StringBuilder sb, InstructionModel insn, string f, FlagBitMap flags)
    {
        // The op arg ("ADD".."CP") maps to the EmitZ80Alu8 kind ("Add8".."Cp8").
        string kind = Unquote(insn.Ops[0].Args[0]) switch
        {
            "ADD" => "Add8", "ADC" => "Adc8", "SUB" => "Sub8", "SBC" => "Sbc8",
            "AND" => "And8", "XOR" => "Xor8", "OR" => "Or8", "CP" => "Cp8",
            var other => throw new System.InvalidOperationException($"Z80 indexed ALU: unknown op '{other}'"),
        };
        sb.AppendLine("        byte data = ReadBus(__ea);");
        EmitZ80Alu8(sb, kind, f, flags);   // the EXISTING 8-bit ALU flag-word emitter (reads `data`, `A`)
        // 19 T: -2 key bytes (Step), -1 disp read, -1 memory read.
        sb.AppendLine($"        _cycles += {19 - 2 - 1 - 1};");
    }

    /// <summary>INC/DEC (IX+d): RMW on the indexed EA with full INC/DEC flags (S/Z/Y/H/X/P-V from
    /// before/res, N per op, C preserved) — the SAME flag word EmitZ80IncDec8 computes for the (HL)
    /// form, differing only in the address (__ea). __ea + WZ are already emitted by EmitZ80IndexedBody.
    /// Cycles 23.</summary>
    private static void EmitZ80IndexedIncDec(StringBuilder sb, InstructionModel insn, string f, FlagBitMap flags)
    {
        bool dec = insn.Ops[0].Args[0] == "true";   // IsDec — bool args stored as the bare word (M3.4c)
        string sMask = $"0x{(byte)(1 << flags.BitOf("S")):X2}";
        string zMask = $"0x{(byte)(1 << flags.BitOf("Z")):X2}";
        string yMask = $"0x{(byte)(1 << flags.BitOf("Y")):X2}";
        string hMask = $"0x{(byte)(1 << flags.BitOf("H")):X2}";
        string xMask = $"0x{(byte)(1 << flags.BitOf("X")):X2}";
        string pMask = $"0x{(byte)(1 << flags.BitOf("P")):X2}";
        string nMask = $"0x{(byte)(1 << flags.BitOf("N")):X2}";
        string cMask = $"0x{(byte)(1 << flags.BitOf("C")):X2}";
        string delta = dec ? "- 1" : "+ 1";
        sb.AppendLine("        byte before = ReadBus(__ea);");
        sb.AppendLine($"        byte res = unchecked((byte)(before {delta}));");
        // H: INC = (before&0xF)==0xF; DEC = (before&0xF)==0. P/V: INC overflow at 0x7F->0x80; DEC at 0x80->0x7F.
        string halfExpr = dec ? "((before & 0x0F) == 0x00)" : "((before & 0x0F) == 0x0F)";
        string ovExpr = dec ? "(before == 0x80)" : "(before == 0x7F)";
        // C is PRESERVED — start from the old C bit only.
        sb.AppendLine($"        {f} = unchecked((byte)(({f} & {cMask})");
        sb.AppendLine($"            | ((res & 0x80) != 0 ? {sMask} : 0x00)");
        sb.AppendLine($"            | (res == 0 ? {zMask} : 0x00)");
        sb.AppendLine($"            | ((res & 0x20) != 0 ? {yMask} : 0x00)");
        sb.AppendLine($"            | ({halfExpr} ? {hMask} : 0x00)");
        sb.AppendLine($"            | ((res & 0x08) != 0 ? {xMask} : 0x00)");
        sb.AppendLine($"            | ({ovExpr} ? {pMask} : 0x00)");
        sb.AppendLine($"            | {(dec ? nMask : "0x00")}));");
        sb.AppendLine("        WriteBus(__ea, res);");
        // 23 T: -2 key bytes (Step), -1 disp read, -1 memory read, -1 memory write.
        sb.AppendLine($"        _cycles += {23 - 2 - 1 - 1 - 1};");
    }

    // ── M3.4b CB plane + rotate-accumulators ──

    /// <summary>Emit the rotate/shift of an 8-bit value held in C# local <c>v</c> (byte), producing the
    /// result in local <c>r</c> (byte) and the carry-out in local <c>cout</c> (int 0/1). <paramref
    /// name="op"/> ∈ RLC/RRC/RL/RR/SLA/SRA/SLL/SRL. RL/RR consume the current carry via <paramref
    /// name="oldCarryExpr"/> (an int 0/1 expression). Shared by the rotate-accumulators (Task 4) and the
    /// CB rotate/shift (Task 5).</summary>
    private static void EmitRotateMath(StringBuilder sb, string op, string oldCarryExpr)
    {
        switch (op)
        {
            case "RLC":
                sb.AppendLine("        int cout = (v >> 7) & 1;");
                sb.AppendLine("        byte r = unchecked((byte)((v << 1) | cout));");
                break;
            case "RRC":
                sb.AppendLine("        int cout = v & 1;");
                sb.AppendLine("        byte r = unchecked((byte)((v >> 1) | (cout << 7)));");
                break;
            case "RL":
                sb.AppendLine("        int cout = (v >> 7) & 1;");
                sb.AppendLine($"        byte r = unchecked((byte)((v << 1) | {oldCarryExpr}));");
                break;
            case "RR":
                sb.AppendLine("        int cout = v & 1;");
                sb.AppendLine($"        byte r = unchecked((byte)((v >> 1) | ({oldCarryExpr} << 7)));");
                break;
            case "SLA":
                sb.AppendLine("        int cout = (v >> 7) & 1;");
                sb.AppendLine("        byte r = unchecked((byte)(v << 1));");
                break;
            case "SRA":
                sb.AppendLine("        int cout = v & 1;");
                sb.AppendLine("        byte r = unchecked((byte)((v >> 1) | (v & 0x80)));");
                break;
            case "SLL":   // undocumented: shift left, bit0 forced to 1
                sb.AppendLine("        int cout = (v >> 7) & 1;");
                sb.AppendLine("        byte r = unchecked((byte)((v << 1) | 1));");
                break;
            case "SRL":
                sb.AppendLine("        int cout = v & 1;");
                sb.AppendLine("        byte r = unchecked((byte)(v >> 1));");
                break;
            default:
                throw new System.InvalidOperationException($"unknown rotate op '{op}'");
        }
    }

    private static void EmitZ80RotBody(
        StringBuilder sb, InstructionModel insn, string pc, string pcType, string? statusReg, FlagBitMap flags)
    {
        string f = statusReg ?? "F";
        string kind = insn.Ops[0].Kind;
        // CB rotate/shift (CbRotate, Bit mode) is Task 5. Here: the four base-plane rotate-accumulators.
        if (kind == "CbRotate")
        {
            EmitZ80CbRotate(sb, insn, pc, f, flags);   // Task 5
            return;
        }

        // Rotate-accumulators: operate on A, set ONLY C/H/N + X/Y (from new A); PRESERVE S/Z/P-V.
        string cMask = $"0x{(byte)(1 << flags.BitOf("C")):X2}";
        string xMask = $"0x{(byte)(1 << flags.BitOf("X")):X2}";
        string yMask = $"0x{(byte)(1 << flags.BitOf("Y")):X2}";
        // Preserve mask = S|Z|P bits (everything the rotate-accumulators leave alone). H and N are NOT
        // in the mask, so they fall out at 0 — exactly the documented H=0, N=0.
        byte preserveBits = (byte)((1 << flags.BitOf("S")) | (1 << flags.BitOf("Z")) | (1 << flags.BitOf("P")));
        string preserve = $"0x{preserveBits:X2}";
        string op = kind switch { "Rlca" => "RLC", "Rrca" => "RRC", "Rla" => "RL", _ => "RR" };
        string oldCarry = $"(({f} & {cMask}) != 0 ? 1 : 0)";

        sb.AppendLine("        byte v = A;");
        EmitRotateMath(sb, op, oldCarry);
        sb.AppendLine("        A = r;");
        sb.AppendLine($"        {f} = unchecked((byte)(({f} & {preserve})");
        sb.AppendLine($"            | (cout != 0 ? {cMask} : 0x00)");
        sb.AppendLine($"            | ((r & 0x20) != 0 ? {yMask} : 0x00)");
        sb.AppendLine($"            | ((r & 0x08) != 0 ? {xMask} : 0x00)));");
        sb.AppendLine("        _cycles += 3;   // RLCA/RRCA/RLA/RRA = 4 T-states (fetch + 3 internal)");
    }

    /// <summary>Strip the surrounding quotes from a CbRotate/CbBit string arg ("RLC" → RLC, "(HL)" →
    /// (HL)). The parser stores Str args WITH quotes (Task 2) so the emitter can tell a string operand
    /// from a register operand.</summary>
    private static string Unquote(string s) =>
        s.Length >= 2 && s[0] == '"' ? s.Substring(1, s.Length - 2) : s;

    /// <summary>CB rotate/shift on reg[z] or (HL). Flags: S,Z from result; H=0; N=0; P/V=parity;
    /// C=bit shifted out; X=res bit3, Y=res bit5. Writes the result back (z=6: read/op/write (HL)).
    /// Cycles: register = 8 T, (HL) = 15 T. Step charges the 2 key bytes (prefix + opcode); ReadBus/
    /// WriteBus each charge one; the body charges the remaining internal T-states.</summary>
    private static void EmitZ80CbRotate(StringBuilder sb, InstructionModel insn, string pc, string f, FlagBitMap flags)
    {
        string op = Unquote(insn.Ops[0].Args[0]);       // "RLC".."SRL"
        string target = Unquote(insn.Ops[0].Args[1]);   // "B".."A" or "(HL)"
        bool isMem = target == "(HL)";
        string cMask = $"0x{(byte)(1 << flags.BitOf("C")):X2}";
        string oldCarry = $"(({f} & {cMask}) != 0 ? 1 : 0)";

        if (isMem)
            sb.AppendLine("        byte v = ReadBus(HL);");
        else
            sb.AppendLine($"        byte v = {target};");

        EmitRotateMath(sb, op, oldCarry);   // produces byte r + int cout

        // Full CB flag word: S/Z/Y/H(=0)/X/P(parity)/N(=0)/C(=cout). Reuse the per-spec masks.
        EmitZ80CbRotateFlags(sb, f, flags);

        if (isMem)
            sb.AppendLine("        WriteBus(HL, r);");
        else
            sb.AppendLine($"        {target} = r;");

        // Cycles (2 key bytes charged by Step): register = 8 T → +6 internal (no bus). (HL) = 15 T →
        // +11 internal (1 ReadBus + 1 WriteBus already charge 2).
        if (isMem)
            sb.AppendLine($"        _cycles += {15 - 2 - 1 - 1};   // RLC/…/(HL) = 15 T-states");
        else
            sb.AppendLine($"        _cycles += {8 - 2};   // RLC/… r = 8 T-states");
    }

    /// <summary>Emit the CB rotate/shift flag word from the result <c>r</c> + carry-out <c>cout</c>
    /// (the locals EmitRotateMath produced). S/Z/Y/X/P computed; H=0, N=0; C=cout.</summary>
    private static void EmitZ80CbRotateFlags(StringBuilder sb, string f, FlagBitMap flags)
    {
        string sMask = $"0x{(byte)(1 << flags.BitOf("S")):X2}";
        string zMask = $"0x{(byte)(1 << flags.BitOf("Z")):X2}";
        string yMask = $"0x{(byte)(1 << flags.BitOf("Y")):X2}";
        string xMask = $"0x{(byte)(1 << flags.BitOf("X")):X2}";
        string pMask = $"0x{(byte)(1 << flags.BitOf("P")):X2}";
        string cMask = $"0x{(byte)(1 << flags.BitOf("C")):X2}";
        sb.AppendLine($"        {f} = unchecked((byte)(");
        sb.AppendLine($"              ((r & 0x80) != 0 ? {sMask} : 0x00)");
        sb.AppendLine($"            | (r == 0 ? {zMask} : 0x00)");
        sb.AppendLine($"            | ((r & 0x20) != 0 ? {yMask} : 0x00)");
        sb.AppendLine($"            | ((r & 0x08) != 0 ? {xMask} : 0x00)");
        sb.AppendLine($"            | ((System.Numerics.BitOperations.PopCount((uint)r) & 1) == 0 ? {pMask} : 0x00)");
        sb.AppendLine($"            | (cout != 0 ? {cMask} : 0x00)));");
        // H and N are left at 0 (not ORed in) — the full-word assignment clears them.
    }

    private static void EmitZ80BitBody(
        StringBuilder sb, InstructionModel insn, string pc, string? statusReg, FlagBitMap flags)
    {
        string f = statusReg ?? "F";
        string opName = Unquote(insn.Ops[0].Args[0]);    // "BIT" / "RES" / "SET"
        int bit = int.Parse(insn.Ops[0].Args[1], System.Globalization.CultureInfo.InvariantCulture);
        string target = Unquote(insn.Ops[0].Args[2]);    // "B".."A" or "(HL)"
        bool isMem = target == "(HL)";

        if (opName == "BIT")
        {
            EmitZ80CbBit(sb, f, flags, bit, target, isMem);
            return;
        }
        // RES/SET — Task 7.
        EmitZ80CbResSet(sb, opName, bit, target, isMem);
    }

    /// <summary>BIT y,reg[z]/(HL): Z=(bit==0), P/V=Z, H=1, N=0, S=(y==7 && bit set), C preserved.
    /// X/Y: register operand → operand bits 3/5; (HL) → W=(WZ>>8) bits 3/5. NOT written back.
    /// Cycles: reg 8 T, (HL) 12 T (2 key bytes charged by Step; ReadBus charges 1 for the (HL) read).</summary>
    private static void EmitZ80CbBit(StringBuilder sb, string f, FlagBitMap flags, int bit, string target, bool isMem)
    {
        string sMask = $"0x{(byte)(1 << flags.BitOf("S")):X2}";
        string zMask = $"0x{(byte)(1 << flags.BitOf("Z")):X2}";
        string yMask = $"0x{(byte)(1 << flags.BitOf("Y")):X2}";
        string hMask = $"0x{(byte)(1 << flags.BitOf("H")):X2}";
        string xMask = $"0x{(byte)(1 << flags.BitOf("X")):X2}";
        string pMask = $"0x{(byte)(1 << flags.BitOf("P")):X2}";
        string cMask = $"0x{(byte)(1 << flags.BitOf("C")):X2}";

        if (isMem)
            sb.AppendLine("        byte v = ReadBus(HL);");
        else
            sb.AppendLine($"        byte v = {target};");
        sb.AppendLine($"        bool bitSet = (v & 0x{(1 << bit):X2}) != 0;");
        // X/Y source: (HL) → W (WZ high byte); register → the operand v.
        string xySrc = isMem ? "(byte)(WZ >> 8)" : "v";
        sb.AppendLine($"        int xy = {xySrc};");
        sb.AppendLine($"        {f} = unchecked((byte)(({f} & {cMask})");   // C preserved
        sb.AppendLine($"            | (bitSet ? 0x00 : {zMask})");           // Z = (bit == 0)
        sb.AppendLine($"            | {hMask}");                              // H = 1
        sb.AppendLine($"            | (bitSet ? 0x00 : {pMask})");           // P/V = Z
        sb.AppendLine($"            | ((bitSet && {bit} == 7) ? {sMask} : 0x00)");  // S = (y==7 && bit set)
        sb.AppendLine($"            | ((xy & 0x20) != 0 ? {yMask} : 0x00)");  // Y
        sb.AppendLine($"            | ((xy & 0x08) != 0 ? {xMask} : 0x00)));"); // X
        // Cycles: reg 8 → +6 internal (no bus). (HL) 12 → +9 internal (1 ReadBus charges 1).
        if (isMem)
            sb.AppendLine($"        _cycles += {12 - 2 - 1};   // BIT y,(HL) = 12 T-states");
        else
            sb.AppendLine($"        _cycles += {8 - 2};   // BIT y,r = 8 T-states");
    }

    /// <summary>RES/SET y,reg[z]/(HL): clear/set bit y. NO flag changes. Cycles: reg 8 T, (HL) 15 T
    /// (2 key bytes by Step; the (HL) ReadBus + WriteBus charge 2 more).</summary>
    private static void EmitZ80CbResSet(StringBuilder sb, string op, int bit, string target, bool isMem)
    {
        string mask = $"0x{(1 << bit):X2}";
        string expr = op == "SET" ? $"(v | {mask})" : $"(v & ~{mask})";
        if (isMem)
        {
            sb.AppendLine("        byte v = ReadBus(HL);");
            sb.AppendLine($"        WriteBus(HL, unchecked((byte){expr}));");
            sb.AppendLine($"        _cycles += {15 - 2 - 1 - 1};   // RES/SET y,(HL) = 15 T-states");
        }
        else
        {
            sb.AppendLine($"        byte v = {target};");
            sb.AppendLine($"        {target} = unchecked((byte){expr});");
            sb.AppendLine($"        _cycles += {8 - 2};   // RES/SET y,r = 8 T-states");
        }
    }

    // ── M3.4e-3 DDCB/FDCB compound plane: bit/rotate/shift on (IX+d)/(IY+d) + the undoc store-copy ──

    /// <summary>The compound DDCB/FDCB body. The e-1b compound decode walk consumed the displacement
    /// into DecodeResult.Operands.Lo and advanced PC by 4 (the layout is DD CB d op). The parameterless
    /// Op{key}() body cannot reach __r, so it re-reads d via the RAW, NON-CHARGING _bus.Read8 at (PC - 2)
    /// — the d fetch was already charged ONCE by Step's _cycles += __r.Length (D10/H3; ReadBus would
    /// double-charge). Then compute the EA (EmitZ80IndexedEa) and publish WZ = EA (= IX+d for ALL
    /// compound forms, vector-confirmed). The index register (IX vs IY) is the compound key's p1 byte
    /// (>> 16, the 24-bit key — NOT >> 8). Then switch on the op family:
    ///   x=0 rotate/shift: RMW + the full CB rotate/shift flags + the undoc store-copy (z != 6);
    ///   x=1 BIT:          test bit, X/Y from (EA>>8), no store, z ignored;
    ///   x=2/3 RES/SET:    RMW clear/set, no flags, the undoc store-copy (z != 6).</summary>
    private static void EmitZ80DdCbBody(
        StringBuilder sb, InstructionModel insn, string pc, string pcType, string? statusReg, FlagBitMap flags)
    {
        string f = statusReg ?? "F";
        string ix = (insn.OperationKey >> 16) == 0xDD ? "IX" : "IY";   // 24-bit compound key (H1)
        string op = Unquote(insn.Ops[0].Args[0]);                      // "RLC".."SRL" | "BIT"/"RES"/"SET"
        int index = int.Parse(insn.Ops[0].Args[1], System.Globalization.CultureInfo.InvariantCulture);
        string copyReg = Unquote(insn.Ops[0].Args[2]);                 // "B".."A" | "-" (no copy)

        // The displacement was consumed by the compound decode walk and stashed into _decodeOperandLo by
        // Step (M3.4e-3) — read it from there, NOT from the bus: a second bus read would add a spurious
        // traced access the per-T-state TomHarte trace does not record (the d fetch is already counted in
        // Step's _cycles += __r.Length = 4 and recorded once by the walk's fetch stream).
        sb.AppendLine("        byte d = _decodeOperandLo;");
        EmitZ80IndexedEa(sb, ix, "d");   // -> ushort __ea = unchecked((ushort)(IX + (sbyte)(d)));
        EmitWz(sb, "__ea");              // WZ = the computed EA (the (IX+d) MEMPTR — all compound forms)

        bool isBit = op == "BIT";
        bool isResSet = op is "RES" or "SET";

        if (!isBit && !isResSet)
        {
            // x=0: rotate/shift the EA byte. RMW + the CB rotate/shift flag word + the store-copy.
            string cMask = $"0x{(byte)(1 << flags.BitOf("C")):X2}";
            string oldCarry = $"(({f} & {cMask}) != 0 ? 1 : 0)";
            sb.AppendLine("        byte v = ReadBus(__ea);");
            EmitRotateMath(sb, op, oldCarry);          // -> byte r + int cout (reused from M3.4b)
            EmitZ80CbRotateFlags(sb, f, flags);        // the full S/Z/Y/H(=0)/X/P/N(=0)/C(=cout) word (reused)
            sb.AppendLine("        WriteBus(__ea, r);");
            if (copyReg != "-")
                sb.AppendLine($"        {copyReg} = r;");   // the undoc store-copy (z != 6) — plain register (H5)
            // 23 T: -4 key bytes charged by Step (__r.Length = 4: DD CB d op), -1 ReadBus(__ea), -1 WriteBus(__ea).
            sb.AppendLine($"        _cycles += {23 - 4 - 1 - 1};");   // vector-pinned: dd cb __ 06.json = 23 T
            return;
        }

        if (isResSet)
        {
            EmitZ80DdCbResSet(sb, op, index, copyReg);
            return;
        }
        EmitZ80DdCbBit(sb, f, flags, index);
    }

    /// <summary>BIT y,(IX+d): test bit y of ReadBus(EA). Z=(bit==0), P/V=Z, H=1, N=0, S=(y==7 &amp;&amp; bit
    /// set), C preserved. X/Y from the EA HIGH byte (EA>>8) — the documented DDCB BIT quirk (the value's
    /// bits are NOT used; vector-confirmed dd cb __ 46.json). NO store-copy (z is ignored for BIT — all
    /// of dd cb __ 40..47 produce the identical case). __ea + WZ are emitted by the preamble. Cycles 20 T.</summary>
    private static void EmitZ80DdCbBit(StringBuilder sb, string f, FlagBitMap flags, int bit)
    {
        string sMask = $"0x{(byte)(1 << flags.BitOf("S")):X2}";
        string zMask = $"0x{(byte)(1 << flags.BitOf("Z")):X2}";
        string yMask = $"0x{(byte)(1 << flags.BitOf("Y")):X2}";
        string hMask = $"0x{(byte)(1 << flags.BitOf("H")):X2}";
        string xMask = $"0x{(byte)(1 << flags.BitOf("X")):X2}";
        string pMask = $"0x{(byte)(1 << flags.BitOf("P")):X2}";
        string cMask = $"0x{(byte)(1 << flags.BitOf("C")):X2}";
        sb.AppendLine("        byte v = ReadBus(__ea);");
        sb.AppendLine($"        bool bitSet = (v & 0x{(1 << bit):X2}) != 0;");
        sb.AppendLine("        int xy = (byte)(__ea >> 8);");   // the DDCB BIT quirk: X/Y from the EA high byte
        sb.AppendLine($"        {f} = unchecked((byte)(({f} & {cMask})");   // C preserved
        sb.AppendLine($"            | (bitSet ? 0x00 : {zMask})");           // Z = (bit == 0)
        sb.AppendLine($"            | {hMask}");                              // H = 1
        sb.AppendLine($"            | (bitSet ? 0x00 : {pMask})");           // P/V = Z
        sb.AppendLine($"            | ((bitSet && {bit} == 7) ? {sMask} : 0x00)");  // S = (y==7 && bit set)
        sb.AppendLine($"            | ((xy & 0x20) != 0 ? {yMask} : 0x00)");  // Y from (EA>>8) bit 5
        sb.AppendLine($"            | ((xy & 0x08) != 0 ? {xMask} : 0x00)));"); // X from (EA>>8) bit 3
        // 20 T: -4 (Step's __r.Length), -1 ReadBus(__ea); no write. Vector-pinned: dd cb __ 46.json = 20 T.
        sb.AppendLine($"        _cycles += {20 - 4 - 1};");
    }

    /// <summary>RES/SET y,(IX+d): clear/set bit y of ReadBus(EA), write back. NO flag change (F preserved
    /// — Q ends 0; vector-confirmed dd cb __ 86/c6.json). The undoc store-copy (z != 6) ALSO writes the
    /// result to the plain register (H5). __ea + WZ are emitted by the preamble. Cycles 23 T. The Q=0
    /// outcome is realized by Z80WritesFlags(Z80DdCb) returning false for RES/SET (the body does not
    /// touch F, the trailing Q lifecycle emits Q = 0).</summary>
    private static void EmitZ80DdCbResSet(StringBuilder sb, string op, int bit, string copyReg)
    {
        string mask = $"0x{(1 << bit):X2}";
        string expr = op == "SET" ? $"(v | {mask})" : $"(v & ~{mask})";
        sb.AppendLine("        byte v = ReadBus(__ea);");
        sb.AppendLine($"        byte r = unchecked((byte){expr});");
        sb.AppendLine("        WriteBus(__ea, r);");
        if (copyReg != "-")
            sb.AppendLine($"        {copyReg} = r;");   // the undoc store-copy (z != 6) — plain register (H5)
        // 23 T: -4 (Step's __r.Length), -1 ReadBus(__ea), -1 WriteBus(__ea). Vector-pinned: dd cb __ 86.json = 23 T.
        sb.AppendLine($"        _cycles += {23 - 4 - 1 - 1};");
    }

    // ---- M3.4c ED-core classes (classification-only STUB bodies — real behavior in B-Tasks 2-7) ----

    /// <summary>ED IN r,(C) / OUT (C),r (+ the undoc IN (C) discard / OUT (C),0). The port is BC and
    /// both forms write WZ = BC+1 (MEMPTR). IN reads the Io bus, optionally stores it into r[y], and
    /// recomputes S/Z/Y/X/P from the input (H=0, N=0, C preserved); OUT writes r[y] (or 0) to the Io
    /// bus and touches NO flags. Cycles: 12 T — Step charges the 2 key bytes, ReadIo/WriteIo charge 1,
    /// the body adds the remaining 9 internal.</summary>
    private static void EmitZ80EdIoBody(
        StringBuilder sb, InstructionModel insn, string pc, string? statusReg, FlagBitMap flags)
    {
        string f = statusReg ?? "F";
        string kind = insn.Ops[0].Kind;
        string operand = Unquote(insn.Ops[0].Args[0]);   // "B".."A" / "none" / "zero"
        sb.AppendLine("        WZ = unchecked((ushort)(BC + 1));");   // both IN and OUT: WZ = BC+1

        if (kind == "EdIn")
        {
            string sMask = $"0x{(byte)(1 << flags.BitOf("S")):X2}";
            string zMask = $"0x{(byte)(1 << flags.BitOf("Z")):X2}";
            string yMask = $"0x{(byte)(1 << flags.BitOf("Y")):X2}";
            string xMask = $"0x{(byte)(1 << flags.BitOf("X")):X2}";
            string pMask = $"0x{(byte)(1 << flags.BitOf("P")):X2}";
            string cMask = $"0x{(byte)(1 << flags.BitOf("C")):X2}";
            sb.AppendLine("        byte inp = ReadIo(BC);");
            if (operand != "none")
                sb.AppendLine($"        {operand} = inp;");          // y!=6: store into r[y]
            sb.AppendLine($"        {f} = unchecked((byte)(({f} & {cMask})");
            sb.AppendLine($"            | ((inp & 0x80) != 0 ? {sMask} : 0x00)");
            sb.AppendLine($"            | (inp == 0 ? {zMask} : 0x00)");
            sb.AppendLine($"            | ((inp & 0x20) != 0 ? {yMask} : 0x00)");
            sb.AppendLine($"            | ((inp & 0x08) != 0 ? {xMask} : 0x00)");
            sb.AppendLine($"            | ((System.Numerics.BitOperations.PopCount((uint)inp) & 1) == 0 ? {pMask} : 0x00)));");
        }
        else // EdOut
        {
            string value = operand == "zero" ? "0" : operand;  // y=6: OUT (C),0
            sb.AppendLine($"        WriteIo(BC, unchecked((byte)({value})));");
        }
        // Cycles: 12 T. Step charged 2 (key bytes); the ReadIo/WriteIo charges 1. +9 internal.
        sb.AppendLine($"        _cycles += {12 - 2 - 1};   // IN/OUT (C) = 12 T-states");
    }

    private static void EmitZ80EdOpBody(
        StringBuilder sb, InstructionModel insn, string pc, string pcType, string? statusReg,
        string? spReg, FlagBitMap flags)
    {
        string f = statusReg ?? "F";
        switch (insn.Ops[0].Kind)
        {
            case "EdAdcSbc16": EmitZ80EdAdcSbc16(sb, insn, f, flags); return;
            case "EdLdNnRp":   EmitZ80EdLdNnRp(sb, insn, pc, pcType, flags); return;   // B-Task 4
            case "EdNeg":      EmitZ80EdNeg(sb, f, flags); return;                     // B-Task 5
            case "EdRetn":     EmitZ80EdRetn(sb, insn, pc, pcType, spReg); return;     // B-Task 6
            case "EdIm":       EmitZ80EdIm(sb, insn); return;                          // B-Task 6
            case "EdLdIaRa":   EmitZ80EdLdIaRa(sb, insn, f, flags); return;            // B-Task 7
            case "EdRrdRld":   EmitZ80EdRrdRld(sb, insn, f, flags); return;            // B-Task 7
            case "EdNop":      sb.AppendLine($"        _cycles += {8 - 2};   // ED NOP = 8 T"); return;
            default:
                throw new System.InvalidOperationException($"Z80 EdOp: no template for '{insn.Ops[0].Kind}'");
        }
    }

    private static void EmitZ80EdBlockBody(
        StringBuilder sb, InstructionModel insn, string pc, string pcType, string? statusReg,
        FlagBitMap flags)
    {
        string f = statusReg ?? "F";
        string mn = Unquote(insn.Ops[0].Args[0]);   // "LDI".."OTDR"
        // Flag masks (computed once).
        string sM = $"0x{(byte)(1 << flags.BitOf("S")):X2}";
        string zM = $"0x{(byte)(1 << flags.BitOf("Z")):X2}";
        string yM = $"0x{(byte)(1 << flags.BitOf("Y")):X2}";
        string hM = $"0x{(byte)(1 << flags.BitOf("H")):X2}";
        string xM = $"0x{(byte)(1 << flags.BitOf("X")):X2}";
        string pM = $"0x{(byte)(1 << flags.BitOf("P")):X2}";
        string nM = $"0x{(byte)(1 << flags.BitOf("N")):X2}";
        string cM = $"0x{(byte)(1 << flags.BitOf("C")):X2}";

        switch (mn)
        {
            case "LDI":  case "LDD":  case "LDIR": case "LDDR":
            {
                bool inc = mn is "LDI" or "LDIR";
                bool repeat = mn is "LDIR" or "LDDR";
                string delta = inc ? "+ 1" : "- 1";
                sb.AppendLine("        byte __n = ReadBus(HL);");
                sb.AppendLine("        WriteBus(DE, __n);");
                sb.AppendLine($"        HL = unchecked((ushort)(HL {delta}));");
                sb.AppendLine($"        DE = unchecked((ushort)(DE {delta}));");
                sb.AppendLine("        BC = unchecked((ushort)(BC - 1));");
                // n_xy = A + transferred byte (the LD-family X/Y quirk).
                sb.AppendLine("        int __xy = (A + __n) & 0xFF;");
                // H=0, N=0; P/V = (BC != 0); S/Z/C preserved; X = bit3 of __xy, Y = bit1 of __xy.
                sb.AppendLine($"        {f} = unchecked((byte)(({f} & ({sM} | {zM} | {cM}))");
                sb.AppendLine($"            | (BC != 0 ? {pM} : 0x00)");
                sb.AppendLine($"            | ((__xy & 0x08) != 0 ? {xM} : 0x00)");
                sb.AppendLine($"            | ((__xy & 0x02) != 0 ? {yM} : 0x00)));");
                // Cycles: 16 T base. Step charged 2 (key bytes); ReadBus + WriteBus charged 2. +12 internal.
                sb.AppendLine("        _cycles += 12;   // LDI/LDD = 16 T (16 - 2 fetch - 2 bus)");
                EmitBlockRepeatTail(sb, repeat, f, "BC != 0", xM, yM);   // WZ unchanged unless repeating
                break;
            }
            case "CPI":  case "CPD":  case "CPIR": case "CPDR":
            {
                bool inc = mn is "CPI" or "CPIR";
                bool repeat = mn is "CPIR" or "CPDR";
                string delta = inc ? "+ 1" : "- 1";
                sb.AppendLine("        byte __m = ReadBus(HL);");
                sb.AppendLine("        int __r = (A - __m) & 0xFF;");
                sb.AppendLine("        int __hc = ((A & 0x0F) - (__m & 0x0F)) < 0 ? 1 : 0;");  // half-borrow
                sb.AppendLine($"        HL = unchecked((ushort)(HL {delta}));");
                sb.AppendLine("        BC = unchecked((ushort)(BC - 1));");
                sb.AppendLine($"        WZ = unchecked((ushort)(WZ {(inc ? "+ 1" : "- 1")}));");
                // n_xy = (A - (HL) - H) for the X/Y quirk.
                sb.AppendLine("        int __xy = (__r - __hc) & 0xFF;");
                // S/Z from __r; H from __hc; N=1; P/V=(BC!=0); C preserved; X=bit3, Y=bit1 of __xy.
                sb.AppendLine($"        {f} = unchecked((byte)(({f} & {cM})");
                sb.AppendLine($"            | ((__r & 0x80) != 0 ? {sM} : 0x00)");
                sb.AppendLine($"            | (__r == 0 ? {zM} : 0x00)");
                sb.AppendLine($"            | (__hc != 0 ? {hM} : 0x00)");
                sb.AppendLine($"            | {nM}");
                sb.AppendLine($"            | (BC != 0 ? {pM} : 0x00)");
                sb.AppendLine($"            | ((__xy & 0x08) != 0 ? {xM} : 0x00)");
                sb.AppendLine($"            | ((__xy & 0x02) != 0 ? {yM} : 0x00)));");
                // Cycles: 16 T base. Step charged 2 (key bytes); ReadBus charged 1. +13 internal.
                sb.AppendLine("        _cycles += 13;   // CPI/CPD = 16 T (16 - 2 fetch - 1 bus)");
                // Repeat while BC != 0 AND not matched (Z == 0). The tail (after WZ +/- 1) overrides
                // WZ to instruction-PC+1 on repeat; on the final/match iteration WZ stays at WZ +/- 1.
                EmitBlockRepeatTail(sb, repeat, f, "BC != 0 && __r != 0", xM, yM);
                break;
            }
            case "INI":  case "IND":  case "INIR": case "INDR":
            {
                bool inc = mn is "INI" or "INIR";
                bool repeat = mn is "INIR" or "INDR";
                string hlDelta = inc ? "+ 1" : "- 1";
                sb.AppendLine("        byte __v = ReadIo(BC);");           // port read (BC)
                sb.AppendLine("        WriteBus(HL, __v);");               // (HL) <- input
                // WZ = (BC BEFORE the B decrement) +/- 1 (vector-derived: IN uses the ORIGINAL B).
                sb.AppendLine($"        WZ = unchecked((ushort)(BC {(inc ? "+ 1" : "- 1")}));");
                sb.AppendLine("        B = unchecked((byte)(B - 1));");    // the counter
                sb.AppendLine($"        HL = unchecked((ushort)(HL {hlDelta}));");
                // k = input + ((C +/- 1) & 0xFF) ; INI/INIR uses C+1, IND/INDR uses C-1.
                sb.AppendLine($"        int __k = __v + ((C {(inc ? "+ 1" : "- 1")}) & 0xFF);");
                EmitBlockIoFlags(sb, f, sM, zM, yM, hM, xM, pM, nM, cM, transferredByte: "__v");
                // Cycles: 16 T base. Step charged 2 (key bytes); ReadIo + WriteBus charged 2. +12 internal.
                sb.AppendLine("        _cycles += 12;   // INI/IND = 16 T (16 - 2 fetch - 2 bus)");
                EmitBlockRepeatTail(sb, repeat, f, "B != 0", xM, yM, ioRepeatFix: true, hM: hM, pM: pM);
                break;
            }
            case "OUTI": case "OUTD": case "OTIR": case "OTDR":
            {
                bool inc = mn is "OUTI" or "OTIR";
                bool repeat = mn is "OTIR" or "OTDR";
                string hlDelta = inc ? "+ 1" : "- 1";
                sb.AppendLine("        byte __v = ReadBus(HL);");          // (HL) -> output
                sb.AppendLine("        B = unchecked((byte)(B - 1));");    // OUT decrements B BEFORE WZ/port
                sb.AppendLine("        WriteIo(BC, __v);");                // port write (BC, B already decremented)
                sb.AppendLine($"        HL = unchecked((ushort)(HL {hlDelta}));");
                // WZ = (BC AFTER the B decrement) +/- 1 (vector-derived: OUT uses the DECREMENTED B).
                sb.AppendLine($"        WZ = unchecked((ushort)(BC {(inc ? "+ 1" : "- 1")}));");
                // k = output + L (L AFTER the HL adjust).
                sb.AppendLine("        int __k = __v + L;");
                EmitBlockIoFlags(sb, f, sM, zM, yM, hM, xM, pM, nM, cM, transferredByte: "__v");
                // Cycles: 16 T base. Step charged 2 (key bytes); ReadBus + WriteIo charged 2. +12 internal.
                sb.AppendLine("        _cycles += 12;   // OUTI/OUTD = 16 T (16 - 2 fetch - 2 bus)");
                EmitBlockRepeatTail(sb, repeat, f, "B != 0", xM, yM, ioRepeatFix: true, hM: hM, pM: pM);
                break;
            }
            default:
                throw new System.InvalidOperationException($"unknown ED block op '{mn}'");
        }
    }

    /// <summary>M3.4d: the IN/OUT block-op flag word. S/Z/X/Y from the DECREMENTED B; N = bit7 of the
    /// transferred byte; H = C = (k &gt; 0xFF); P/V = parity of ((k &amp; 7) ^ B). `__k` is in scope
    /// (the caller computed it per family); B is already decremented.</summary>
    private static void EmitBlockIoFlags(
        StringBuilder sb, string f, string sM, string zM, string yM, string hM, string xM,
        string pM, string nM, string cM, string transferredByte)
    {
        sb.AppendLine($"        {f} = unchecked((byte)(");
        sb.AppendLine($"              ((B & 0x80) != 0 ? {sM} : 0x00)");
        sb.AppendLine($"            | (B == 0 ? {zM} : 0x00)");
        sb.AppendLine($"            | ((B & 0x20) != 0 ? {yM} : 0x00)");
        sb.AppendLine($"            | ((B & 0x08) != 0 ? {xM} : 0x00)");
        sb.AppendLine($"            | (({transferredByte} & 0x80) != 0 ? {nM} : 0x00)");
        sb.AppendLine($"            | (__k > 0xFF ? ({hM} | {cM}) : 0x00)");
        sb.AppendLine($"            | ((System.Numerics.BitOperations.PopCount((uint)(((__k & 7) ^ B))) & 1) == 0 ? {pM} : 0x00)));");
    }

    /// <summary>M3.4d: the shared repeat tail. For a repeating *R op, when the loop is NOT done (the
    /// caller passes the family-specific condition — "BC != 0" for LD; "BC != 0 &amp;&amp; __r != 0" for CP;
    /// "B != 0" for IN/OUT), rewind PC by the 2 key bytes and set WZ = instruction-PC + 1 (Step has
    /// already advanced PC by 2, so the rewound PC + 1 = the original instruction PC + 1) and charge the
    /// +5 repeat T-states (21 - 16). Non-repeating ops leave PC + WZ as the body set them.
    /// <para>The repeat ALSO overrides the undocumented F3/F5 (X/Y) flags: on a repeating block op, X/Y
    /// come from bits 3/5 of the HIGH byte of the (rewound) instruction PC — NOT from the per-family
    /// transfer-byte value the body computed. Re-derived from the SingleStepTests vectors (ed b0..bb):
    /// across all 8 repeating families, F3=bit3 of PCH and F5=bit5 of PCH (PCH = high byte of the
    /// instruction PC) match every repeating case.</para></summary>
    private static void EmitBlockRepeatTail(
        StringBuilder sb, bool repeat, string f, string condition, string xM, string yM,
        bool ioRepeatFix = false, string hM = "", string pM = "")
    {
        if (!repeat)
            return;   // single ops: PC advances (Step did it); WZ rule is per-family (handled in-body).
        sb.AppendLine($"        if ({condition})");
        sb.AppendLine("        {");
        sb.AppendLine("            PC = unchecked((ushort)(PC - 2));");          // rewind to re-execute
        sb.AppendLine("            WZ = unchecked((ushort)(PC + 1));");          // MEMPTR = instr PC + 1
        sb.AppendLine("            _cycles += 5;");                              // 21 - 16 = +5 on repeat
        // The repeating IN/OUT ops get the documented "interrupted INxR/OTxR" H/P-V correction (Patrik
        // Rak / hoglet67 Z80Decoder). __k carries (k > 0xFF) = CF; __v is the data byte; B is decremented.
        // PF/HF on the left are the standard values already in F. Re-derived: 0 fails across ed b2/ba/b3/bb.
        if (ioRepeatFix)
        {
            sb.AppendLine("            if (__k > 0xFF)");
            sb.AppendLine("            {");
            sb.AppendLine($"                bool __pfold = (({f} & {pM}) != 0);");
            sb.AppendLine("                if ((__v & 0x80) != 0)");
            sb.AppendLine("                {");
            sb.AppendLine($"                    bool __pf = __pfold ^ ((System.Numerics.BitOperations.PopCount((uint)((B - 1) & 7)) & 1) == 0) ^ true;");
            sb.AppendLine($"                    {f} = unchecked((byte)(({f} & ~({pM} | {hM}))");
            sb.AppendLine($"                        | (__pf ? {pM} : 0x00)");
            sb.AppendLine($"                        | ((B & 0x0F) == 0x00 ? {hM} : 0x00)));");
            sb.AppendLine("                }");
            sb.AppendLine("                else");
            sb.AppendLine("                {");
            sb.AppendLine($"                    bool __pf = __pfold ^ ((System.Numerics.BitOperations.PopCount((uint)((B + 1) & 7)) & 1) == 0) ^ true;");
            sb.AppendLine($"                    {f} = unchecked((byte)(({f} & ~({pM} | {hM}))");
            sb.AppendLine($"                        | (__pf ? {pM} : 0x00)");
            sb.AppendLine($"                        | ((B & 0x0F) == 0x0F ? {hM} : 0x00)));");
            sb.AppendLine("                }");
            sb.AppendLine("            }");
            sb.AppendLine("            else");
            sb.AppendLine("            {");
            sb.AppendLine($"                bool __pf = (({f} & {pM}) != 0) ^ ((System.Numerics.BitOperations.PopCount((uint)(B & 7)) & 1) == 0) ^ true;");
            sb.AppendLine($"                {f} = unchecked((byte)(({f} & ~{pM}) | (__pf ? {pM} : 0x00)));");
            sb.AppendLine("            }");
        }
        // Repeat X/Y quirk: F3/F5 come from bits 3/5 of the high byte of the instruction PC (= rewound PC).
        sb.AppendLine("            int __pch = (PC >> 8) & 0xFF;");
        sb.AppendLine($"            {f} = unchecked((byte)(({f} & ~({xM} | {yM}))");
        sb.AppendLine($"                | ((__pch & 0x08) != 0 ? {xM} : 0x00)");
        sb.AppendLine($"                | ((__pch & 0x20) != 0 ? {yM} : 0x00)));");
        sb.AppendLine("        }");
    }

    /// <summary>ED ADC/SBC HL,rp (16-bit). S/Z from the 16-bit result; H from bit 11; P/V overflow;
    /// N=1(SBC)/0(ADC); C from bit 16; X/Y from the result high byte. WZ = HL+1 (pre-op). Cycles 15.</summary>
    private static void EmitZ80EdAdcSbc16(StringBuilder sb, InstructionModel insn, string f, FlagBitMap flags)
    {
        bool sub = Unquote(insn.Ops[0].Args[0]) == "SBC";
        string pair = Unquote(insn.Ops[0].Args[1]);
        string sMask = $"0x{(byte)(1 << flags.BitOf("S")):X2}";
        string zMask = $"0x{(byte)(1 << flags.BitOf("Z")):X2}";
        string yMask = $"0x{(byte)(1 << flags.BitOf("Y")):X2}";
        string hMask = $"0x{(byte)(1 << flags.BitOf("H")):X2}";
        string xMask = $"0x{(byte)(1 << flags.BitOf("X")):X2}";
        string pMask = $"0x{(byte)(1 << flags.BitOf("P")):X2}";
        string nMask = $"0x{(byte)(1 << flags.BitOf("N")):X2}";
        string cMask = $"0x{(byte)(1 << flags.BitOf("C")):X2}";

        sb.AppendLine("        WZ = unchecked((ushort)(HL + 1));");   // pre-op HL
        sb.AppendLine("        int hl = HL;");
        sb.AppendLine($"        int rr = {pair};");
        sb.AppendLine($"        int cin = (({f} & {cMask}) != 0 ? 1 : 0);");
        if (sub)
        {
            sb.AppendLine("        int full = hl - rr - cin;");
            sb.AppendLine("        int half = (hl & 0x0FFF) - (rr & 0x0FFF) - cin;");
            sb.AppendLine("        ushort res16 = unchecked((ushort)full);");
            sb.AppendLine("        int ov = ((hl ^ rr) & (hl ^ full) & 0x8000);");
            EmitZ80Ed16FlagWord(sb, f, sMask, zMask, yMask, hMask, xMask, pMask, nMask, cMask,
                subtract: true, halfBit: "((half & 0x1000) != 0)", carry: "(full < 0)", ov: "(ov != 0)");
        }
        else
        {
            sb.AppendLine("        int full = hl + rr + cin;");
            sb.AppendLine("        int half = (hl & 0x0FFF) + (rr & 0x0FFF) + cin;");
            sb.AppendLine("        ushort res16 = unchecked((ushort)full);");
            sb.AppendLine("        int ov = (~(hl ^ rr) & (hl ^ full) & 0x8000);");
            EmitZ80Ed16FlagWord(sb, f, sMask, zMask, yMask, hMask, xMask, pMask, nMask, cMask,
                subtract: false, halfBit: "((half & 0x1000) != 0)", carry: "(full > 0xFFFF)", ov: "(ov != 0)");
        }
        sb.AppendLine("        HL = res16;");
        sb.AppendLine($"        _cycles += {15 - 2};   // ADC/SBC HL,rp = 15 T-states");
    }

    /// <summary>The 16-bit ED ADC/SBC flag word: S=bit15, Z=(res==0), Y/X from the high byte, H from
    /// bit 11 carry, P/V overflow, N per op, C from bit 16.</summary>
    private static void EmitZ80Ed16FlagWord(
        StringBuilder sb, string f, string sMask, string zMask, string yMask, string hMask, string xMask,
        string pMask, string nMask, string cMask, bool subtract, string halfBit, string carry, string ov)
    {
        sb.AppendLine($"        {f} = unchecked((byte)(");
        sb.AppendLine($"              ((res16 & 0x8000) != 0 ? {sMask} : 0x00)");
        sb.AppendLine($"            | (res16 == 0 ? {zMask} : 0x00)");
        sb.AppendLine($"            | (((res16 >> 8) & 0x20) != 0 ? {yMask} : 0x00)");
        sb.AppendLine($"            | ({halfBit} ? {hMask} : 0x00)");
        sb.AppendLine($"            | (((res16 >> 8) & 0x08) != 0 ? {xMask} : 0x00)");
        sb.AppendLine($"            | ({ov} ? {pMask} : 0x00)");
        sb.AppendLine($"            | {(subtract ? nMask : "0x00")}");
        sb.AppendLine($"            | ({carry} ? {cMask} : 0x00)));");
    }

    private static void EmitZ80EdLdNnRp(
        StringBuilder sb, InstructionModel insn, string pc, string pcType, FlagBitMap flags)
    {
        bool store = Unquote(insn.Ops[0].Args[0]) == "STORE";
        string pair = Unquote(insn.Ops[0].Args[1]);
        sb.AppendLine($"        byte al = ReadBus({pc});");
        sb.AppendLine($"        {pc} = unchecked(({pcType})({pc} + 1));");
        sb.AppendLine($"        byte ah = ReadBus({pc});");
        sb.AppendLine($"        {pc} = unchecked(({pcType})({pc} + 1));");
        sb.AppendLine("        uint ea = (uint)(al | (ah << 8));");
        EmitWz(sb, "ea + 1");
        if (store)
        {
            sb.AppendLine($"        WriteBus(ea, unchecked((byte){pair}));");
            sb.AppendLine($"        WriteBus((ea + 1) & 0xFFFF, unchecked((byte)({pair} >> 8)));");
            sb.AppendLine($"        _cycles += {20 - 2 - 2 - 2};   // LD (nn),rp = 20 T (2 key + 2 addr reads + 2 writes)");
        }
        else
        {
            sb.AppendLine("        byte vlo = ReadBus(ea);");
            sb.AppendLine("        byte vhi = ReadBus((ea + 1) & 0xFFFF);");
            sb.AppendLine($"        {pair} = unchecked((ushort)(vlo | (vhi << 8)));");
            sb.AppendLine($"        _cycles += {20 - 2 - 2 - 2};   // LD rp,(nn) = 20 T (2 key + 2 addr + 2 data reads)");
        }
    }

    /// <summary>ED NEG: A = 0 − A. Flags as SUB(0,A): S/Z/X/Y from result, H = borrow from bit 4,
    /// P/V = (A==0x80), N=1, C = (A!=0). No WZ write. Cycles 8.</summary>
    private static void EmitZ80EdNeg(StringBuilder sb, string f, FlagBitMap flags)
    {
        string sMask = $"0x{(byte)(1 << flags.BitOf("S")):X2}";
        string zMask = $"0x{(byte)(1 << flags.BitOf("Z")):X2}";
        string yMask = $"0x{(byte)(1 << flags.BitOf("Y")):X2}";
        string hMask = $"0x{(byte)(1 << flags.BitOf("H")):X2}";
        string xMask = $"0x{(byte)(1 << flags.BitOf("X")):X2}";
        string pMask = $"0x{(byte)(1 << flags.BitOf("P")):X2}";
        string nMask = $"0x{(byte)(1 << flags.BitOf("N")):X2}";
        string cMask = $"0x{(byte)(1 << flags.BitOf("C")):X2}";
        sb.AppendLine("        int a0 = A;");
        sb.AppendLine("        int diff = 0 - a0;");
        sb.AppendLine("        int half = 0 - (a0 & 0x0F);");
        sb.AppendLine("        byte res = unchecked((byte)diff);");
        sb.AppendLine($"        {f} = unchecked((byte)(");
        sb.AppendLine($"              ((res & 0x80) != 0 ? {sMask} : 0x00)");
        sb.AppendLine($"            | (res == 0 ? {zMask} : 0x00)");
        sb.AppendLine($"            | ((res & 0x20) != 0 ? {yMask} : 0x00)");
        sb.AppendLine($"            | ((half & 0x10) != 0 ? {hMask} : 0x00)");
        sb.AppendLine($"            | ((res & 0x08) != 0 ? {xMask} : 0x00)");
        sb.AppendLine($"            | (a0 == 0x80 ? {pMask} : 0x00)");
        sb.AppendLine($"            | {nMask}");
        sb.AppendLine($"            | (a0 != 0 ? {cMask} : 0x00)));");
        sb.AppendLine("        A = res;");
        sb.AppendLine($"        _cycles += {8 - 2};   // NEG = 8 T-states");
    }

    /// <summary>ED RETN/RETI: pop PC, IFF1 = IFF2, WZ = popped PC. No flags. Cycles 14. (RETI vs RETN
    /// differ only in disassembly/the device daisy-chain ack, which is out of scope here — both restore
    /// IFF1 from IFF2; CONFIRMED against ed 45/ed 4d.)</summary>
    private static void EmitZ80EdRetn(
        StringBuilder sb, InstructionModel insn, string pc, string pcType, string? spReg)
    {
        string sp = spReg ?? "SP";
        sb.AppendLine($"        byte rl = ReadBus({sp});");
        sb.AppendLine($"        {sp} = unchecked((ushort)({sp} + 1));");
        sb.AppendLine($"        byte rh = ReadBus({sp});");
        sb.AppendLine($"        {sp} = unchecked((ushort)({sp} + 1));");
        sb.AppendLine($"        {pc} = unchecked(({pcType})(rl | (rh << 8)));");
        sb.AppendLine($"        WZ = unchecked((ushort)({pc}));");   // WZ = popped PC
        sb.AppendLine("        _iff1 = _iff2;");                      // IFF1 = IFF2
        sb.AppendLine($"        _cycles += {14 - 2 - 2};   // RETN/RETI = 14 T (2 key + 2 pop reads)");
    }

    /// <summary>ED IM n: set the interrupt mode. No flags, no WZ. Cycles 8.</summary>
    private static void EmitZ80EdIm(StringBuilder sb, InstructionModel insn)
    {
        int mode = int.Parse(insn.Ops[0].Args[0], System.Globalization.CultureInfo.InvariantCulture);
        sb.AppendLine($"        Im = {mode};");
        sb.AppendLine($"        _cycles += {8 - 2};   // IM n = 8 T-states");
    }

    /// <summary>ED LD I,A / R,A / A,I / A,R. I,A/R,A: copy A→I/R, no flags. A,I/A,R: copy I/R→A, S/Z
    /// from value, H=0, N=0, P/V = IFF2, X/Y from value, C preserved. Cycles 9. No WZ write.</summary>
    private static void EmitZ80EdLdIaRa(StringBuilder sb, InstructionModel insn, string f, FlagBitMap flags)
    {
        string op = Unquote(insn.Ops[0].Args[0]);   // "I_A"/"R_A"/"A_I"/"A_R"
        switch (op)
        {
            case "I_A": sb.AppendLine("        I = A;"); break;
            case "R_A": sb.AppendLine("        R = A;"); break;
            case "A_I":
            case "A_R":
            {
                string src = op == "A_I" ? "I" : "R";
                string sMask = $"0x{(byte)(1 << flags.BitOf("S")):X2}";
                string zMask = $"0x{(byte)(1 << flags.BitOf("Z")):X2}";
                string yMask = $"0x{(byte)(1 << flags.BitOf("Y")):X2}";
                string xMask = $"0x{(byte)(1 << flags.BitOf("X")):X2}";
                string pMask = $"0x{(byte)(1 << flags.BitOf("P")):X2}";
                string cMask = $"0x{(byte)(1 << flags.BitOf("C")):X2}";
                sb.AppendLine($"        byte v = {src};");
                sb.AppendLine("        A = v;");
                sb.AppendLine($"        {f} = unchecked((byte)(({f} & {cMask})");   // C preserved
                sb.AppendLine($"            | ((v & 0x80) != 0 ? {sMask} : 0x00)");
                sb.AppendLine($"            | (v == 0 ? {zMask} : 0x00)");
                sb.AppendLine($"            | ((v & 0x20) != 0 ? {yMask} : 0x00)");
                sb.AppendLine($"            | ((v & 0x08) != 0 ? {xMask} : 0x00)");
                sb.AppendLine($"            | (_iff2 ? {pMask} : 0x00)));");          // P/V = IFF2
                break;
            }
            default:
                throw new System.InvalidOperationException($"EdLdIaRa: unknown op '{op}'");
        }
        sb.AppendLine($"        _cycles += {9 - 2};   // LD I,A/R,A/A,I/A,R = 9 T-states");
    }

    /// <summary>ED RRD/RLD: nibble rotate between A's low nibble and (HL). S/Z/P from A, H=0, N=0,
    /// C preserved, X/Y from A. WZ = HL+1. Cycles 18.</summary>
    private static void EmitZ80EdRrdRld(StringBuilder sb, InstructionModel insn, string f, FlagBitMap flags)
    {
        bool rld = insn.Ops[0].Args[0] == "true";   // EdRrdRld(IsRld) -- Bool args stored raw "true"/"false"
        string sMask = $"0x{(byte)(1 << flags.BitOf("S")):X2}";
        string zMask = $"0x{(byte)(1 << flags.BitOf("Z")):X2}";
        string yMask = $"0x{(byte)(1 << flags.BitOf("Y")):X2}";
        string xMask = $"0x{(byte)(1 << flags.BitOf("X")):X2}";
        string pMask = $"0x{(byte)(1 << flags.BitOf("P")):X2}";
        string cMask = $"0x{(byte)(1 << flags.BitOf("C")):X2}";
        sb.AppendLine("        byte m = ReadBus(HL);");
        sb.AppendLine("        int alo = A & 0x0F;");
        if (rld)
        {
            sb.AppendLine("        byte newM = unchecked((byte)((m << 4) | alo));");
            sb.AppendLine("        A = unchecked((byte)((A & 0xF0) | (m >> 4)));");
        }
        else
        {
            sb.AppendLine("        byte newM = unchecked((byte)((alo << 4) | (m >> 4)));");
            sb.AppendLine("        A = unchecked((byte)((A & 0xF0) | (m & 0x0F)));");
        }
        sb.AppendLine("        WriteBus(HL, newM);");
        sb.AppendLine("        WZ = unchecked((ushort)(HL + 1));");
        sb.AppendLine($"        {f} = unchecked((byte)(({f} & {cMask})");
        sb.AppendLine($"            | ((A & 0x80) != 0 ? {sMask} : 0x00)");
        sb.AppendLine($"            | (A == 0 ? {zMask} : 0x00)");
        sb.AppendLine($"            | ((A & 0x20) != 0 ? {yMask} : 0x00)");
        sb.AppendLine($"            | ((A & 0x08) != 0 ? {xMask} : 0x00)");
        sb.AppendLine($"            | ((System.Numerics.BitOperations.PopCount((uint)A) & 1) == 0 ? {pMask} : 0x00)));");
        sb.AppendLine($"        _cycles += {18 - 2 - 1 - 1};   // RRD/RLD = 18 T (2 key + 1 read + 1 write)");
    }

    // ---- Monitor support (IMonitorSupport implementation) ----

    /// <summary>Mode → instruction length in bytes (1–3). Implied/Accumulator = 1;
    /// Immediate/ZeroPage*/Indirect*/Relative = 2; Absolute*/Indirect = 3.
    /// Unknown modes throw (same drift-surfacing posture as the disassembler) — the
    /// generated runtime switch's <c>_ =&gt; 1</c> default covers undefined OPCODES only.</summary>
    private static int ModeLength(string mode) => mode switch
    {
        "Implied" or "Accumulator" or "IoPortIndirect" => 1,   // (C): opcode only (M3.2)
        "Register" or "RegisterIndirect" => 1,                  // M3.4a: LD r,r' ; (HL) — opcode only
        "Immediate" or "ZeroPage" or "ZeroPageX" or "ZeroPageY"
            or "IndirectX" or "IndirectY" or "Relative"
            or "IoPortImmediate" => 2,                          // (n): opcode + port byte (M3.2)
        "RelativeJump" or "Bit" => 2,                           // M3.4a/b: opcode + (displacement | CB op byte)
        "Absolute" or "AbsoluteX" or "AbsoluteY" or "Indirect" => 3,
        "ImmediateExtended" or "ExtendedAddress" => 3,          // M3.4a: opcode + 16-bit operand
        "Indexed" => 3,                                         // M3.4e-1a: prefix + opcode + displacement
        _ => throw new System.InvalidOperationException(
            $"emitter has no instruction length for mode '{mode}'"),
    };

    private static void EmitMonitorSupport(StringBuilder sb, SpecModel model)
    {
        // ── InstructionLength ──────────────────────────────────────────────────
        // Routes through the one decode model (Ground truth E note): the signature is UNCHANGED
        // (IMonitorSupport stable), and the body resolves the opcode's descriptor via DescriptorFor
        // and returns its FixedLength. For the 6502 every opcode is LengthRule.Fixed, so this is the
        // exact value the old ModeLength(mode) switch produced — byte-identical behavior.
        sb.AppendLine();
        sb.AppendLine("    /// <summary>Total instruction length in bytes (1–3). Undefined opcodes return 1.");
        sb.AppendLine("    /// Routes through the decode walk's DescriptorFor(key)/FixedLength — the one length");
        sb.AppendLine("    /// source (Ground truth E).</summary>");
        sb.AppendLine("    public static int InstructionLength(byte opcode)");
        sb.AppendLine("        => DescriptorFor(opcode).FixedLength;");

        // ── TryAssemble — the single-instruction assembler (generated artifact ⑤) ──
        sb.AppendLine();
        sb.AppendLine("    /// <summary>Assemble one instruction from mnemonic + canonical operand text — the");
        sb.AppendLine("    /// inverse of Disassemble. The operand's shape selects the mode; its hex-digit width");
        sb.AppendLine("    /// selects zero-page (2 digits) vs absolute (4) — never promoted.</summary>");
        sb.AppendLine("    public static bool TryAssemble(string mnemonic, string operandText, out byte[] bytes, out string? error)");
        sb.AppendLine("    {");
        sb.AppendLine("        bytes = System.Array.Empty<byte>();");
        sb.AppendLine("        if (!TryParseOperand(operandText, out string mode, out byte lo, out byte hi, out error))");
        sb.AppendLine("            return false;");
        sb.AppendLine("        string m = mnemonic.Trim().ToUpperInvariant();");
        sb.AppendLine("        int opcode = AssembleOpcode(m, mode);");
        sb.AppendLine("        if (opcode < 0 && mode == \"Implied\")");
        sb.AppendLine("            opcode = AssembleOpcode(m, \"Accumulator\"); // bare 'ASL' means the accumulator form");
        sb.AppendLine("        if (opcode < 0)");
        sb.AppendLine("        {");
        sb.AppendLine("            error = KnownMnemonic(m)");
        sb.AppendLine("                ? $\"no {m} + {mode} form in the instruction table\"");
        sb.AppendLine("                : $\"unknown mnemonic '{m}'\";");
        sb.AppendLine("            return false;");
        sb.AppendLine("        }");
        sb.AppendLine("        bytes = mode switch");
        sb.AppendLine("        {");
        sb.AppendLine("            \"Implied\" or \"Accumulator\" => new byte[] { (byte)opcode },");
        sb.AppendLine("            \"Absolute\" or \"AbsoluteX\" or \"AbsoluteY\" or \"Indirect\" => new byte[] { (byte)opcode, lo, hi },");
        sb.AppendLine("            _ => new byte[] { (byte)opcode, lo },");
        sb.AppendLine("        };");
        sb.AppendLine("        error = null;");
        sb.AppendLine("        return true;");
        sb.AppendLine("    }");

        // ── AssembleOpcode: (mnemonic, mode) → opcode or -1 ──
        sb.AppendLine();
        sb.AppendLine("    /// <summary>(mnemonic, mode) → opcode, or -1. Generated from the instruction table —");
        sb.AppendLine("    /// the spec table arbitrates every mnemonic+mode ambiguity.</summary>");
        sb.AppendLine("    private static int AssembleOpcode(string mnemonic, string mode) => (mnemonic, mode) switch");
        sb.AppendLine("    {");
        // De-dup by (mnemonic, mode): the Z80 has MANY rows sharing a (mnemonic, mode) pair (the
        // register/pair selector distinguishes them but is opcode-encoded, not in the operand text),
        // so the assembler maps each pair to the FIRST matching opcode. The 6502's pairs are unique,
        // so its emission is byte-identical (the first — and only — row per pair). The assembler is
        // monitor support, NOT on the TomHarte gate; Z80 register-granular assembly is out of scope.
        var seenAsm = new System.Collections.Generic.HashSet<string>(System.StringComparer.Ordinal);
        foreach (var instruction in model.Instructions)
            if (seenAsm.Add($"{instruction.Mnemonic} {instruction.Mode}"))
                sb.AppendLine($"        (\"{instruction.Mnemonic}\", \"{instruction.Mode}\") => 0x{instruction.Opcode:X2},");
        sb.AppendLine("        _ => -1,");
        sb.AppendLine("    };");

        // ── KnownMnemonic ──
        var mnemonics = model.Instructions.Select(i => i.Mnemonic).Distinct().OrderBy(m => m).ToArray();
        sb.AppendLine();
        sb.AppendLine("    private static bool KnownMnemonic(string mnemonic) => mnemonic switch");
        sb.AppendLine("    {");
        // M4.1: a register-only CPU (the 68000 in M4.1) has zero instruction rows, so there are no
        // mnemonics — emit only the `_ => false` arm. A spec with mnemonics (6502/Z80) is unchanged
        // (the joined-name arm is emitted exactly as before), so their .g.cs is byte-identical.
        if (mnemonics.Length > 0)
            sb.AppendLine($"        {string.Join(" or ", mnemonics.Select(m => $"\"{m}\""))} => true,");
        sb.AppendLine("        _ => false,");
        sb.AppendLine("    };");

        // ── TryParseOperand ──
        sb.AppendLine();
        sb.AppendLine("    /// <summary>Parse canonical operand text into (mode, lo, hi). Whitespace is stripped,");
        sb.AppendLine("    /// hex is case-insensitive. Exactly 2 hex digits = zero-page family; exactly 4 =");
        sb.AppendLine("    /// absolute family; 1/3 digits are errors — the disassembler always writes 2 or 4,");
        sb.AppendLine("    /// which is what makes assemble∘disassemble an identity.</summary>");
        sb.AppendLine("    private static bool TryParseOperand(string text, out string mode, out byte lo, out byte hi, out string? error)");
        sb.AppendLine("    {");
        sb.AppendLine("        mode = \"Implied\"; lo = 0; hi = 0; error = null;");
        sb.AppendLine("        string t = text.Replace(\" \", string.Empty).Replace(\"\\t\", string.Empty).ToUpperInvariant();");
        sb.AppendLine("        if (t.Length == 0)");
        sb.AppendLine("            return true; // Implied (TryAssemble falls back to Accumulator)");
        sb.AppendLine("        if (t == \"A\")");
        sb.AppendLine("        {");
        sb.AppendLine("            mode = \"Accumulator\";");
        sb.AppendLine("            return true;");
        sb.AppendLine("        }");
        sb.AppendLine("        if (t[0] == '*')");
        sb.AppendLine("        {");
        sb.AppendLine("            if (t.Length >= 3 && (t[1] == '+' || t[1] == '-')");
        sb.AppendLine("                && int.TryParse(t.Substring(1), System.Globalization.NumberStyles.AllowLeadingSign,");
        sb.AppendLine("                       System.Globalization.CultureInfo.InvariantCulture, out int rel)");
        sb.AppendLine("                && rel >= -128 && rel <= 127)");
        sb.AppendLine("            {");
        sb.AppendLine("                mode = \"Relative\";");
        sb.AppendLine("                lo = unchecked((byte)rel);");
        sb.AppendLine("                return true;");
        sb.AppendLine("            }");
        sb.AppendLine("            error = $\"malformed relative operand '{text}' (expected *+d or *-d, decimal, -128..+127)\";");
        sb.AppendLine("            return false;");
        sb.AppendLine("        }");
        sb.AppendLine("        if (t[0] == '#')");
        sb.AppendLine("        {");
        sb.AppendLine("            if (t.Length == 4 && t[1] == '$' && TryHexByte(t.Substring(2), out lo))");
        sb.AppendLine("            {");
        sb.AppendLine("                mode = \"Immediate\";");
        sb.AppendLine("                return true;");
        sb.AppendLine("            }");
        sb.AppendLine("            error = $\"malformed immediate operand '{text}' (expected #$hh — immediates are one byte)\";");
        sb.AppendLine("            return false;");
        sb.AppendLine("        }");
        sb.AppendLine("        if (t[0] == '(')");
        sb.AppendLine("        {");
        sb.AppendLine("            // All three indirect forms after whitespace strip (all length 7):");
        sb.AppendLine("            //   ($hh,X)  → IndirectX  — t[4]=',' t[5]='X' t[6]=')'");
        sb.AppendLine("            //   ($hh),Y  → IndirectY  — t[4]=')' t[5]=',' t[6]='Y'");
        sb.AppendLine("            //   ($hhhh)  → Indirect   — t[6]=')'");
        sb.AppendLine("            // Disambiguated by suffix, checked in that order.");
        sb.AppendLine("            if (t.Length == 7 && t[1] == '$')");
        sb.AppendLine("            {");
        sb.AppendLine("                // ($hh,X) : indices 2-3 = byte, 4=',', 5='X', 6=')'");
        sb.AppendLine("                if (t[4] == ',' && t[5] == 'X' && t[6] == ')' && TryHexByte(t.Substring(2, 2), out lo))");
        sb.AppendLine("                {");
        sb.AppendLine("                    mode = \"IndirectX\";");
        sb.AppendLine("                    return true;");
        sb.AppendLine("                }");
        sb.AppendLine("                // ($hh),Y : indices 2-3 = byte, 4=')', 5=',', 6='Y'");
        sb.AppendLine("                if (t[4] == ')' && t[5] == ',' && t[6] == 'Y' && TryHexByte(t.Substring(2, 2), out lo))");
        sb.AppendLine("                {");
        sb.AppendLine("                    mode = \"IndirectY\";");
        sb.AppendLine("                    return true;");
        sb.AppendLine("                }");
        sb.AppendLine("                // ($hhhh) : indices 2-5 = word, 6=')'");
        sb.AppendLine("                if (t[6] == ')' && TryHexWord(t.Substring(2, 4), out lo, out hi))");
        sb.AppendLine("                {");
        sb.AppendLine("                    mode = \"Indirect\";");
        sb.AppendLine("                    return true;");
        sb.AppendLine("                }");
        sb.AppendLine("            }");
        sb.AppendLine("            error = $\"malformed indirect operand '{text}' (expected ($hh,X), ($hh),Y or ($hhhh))\";");
        sb.AppendLine("            return false;");
        sb.AppendLine("        }");
        sb.AppendLine("        if (t[0] == '$')");
        sb.AppendLine("        {");
        sb.AppendLine("            string digits = t.Substring(1);");
        sb.AppendLine("            string suffix = string.Empty;");
        sb.AppendLine("            int comma = digits.IndexOf(',');");
        sb.AppendLine("            if (comma >= 0)");
        sb.AppendLine("            {");
        sb.AppendLine("                suffix = digits.Substring(comma);");
        sb.AppendLine("                digits = digits.Substring(0, comma);");
        sb.AppendLine("            }");
        sb.AppendLine("            if (suffix != string.Empty && suffix != \",X\" && suffix != \",Y\")");
        sb.AppendLine("            {");
        sb.AppendLine("                error = $\"malformed index suffix in '{text}' (expected ,X or ,Y)\";");
        sb.AppendLine("                return false;");
        sb.AppendLine("            }");
        sb.AppendLine("            if (digits.Length == 2 && TryHexByte(digits, out lo))");
        sb.AppendLine("            {");
        sb.AppendLine("                mode = suffix == string.Empty ? \"ZeroPage\" : suffix == \",X\" ? \"ZeroPageX\" : \"ZeroPageY\";");
        sb.AppendLine("                return true;");
        sb.AppendLine("            }");
        sb.AppendLine("            if (digits.Length == 4 && TryHexWord(digits, out lo, out hi))");
        sb.AppendLine("            {");
        sb.AppendLine("                mode = suffix == string.Empty ? \"Absolute\" : suffix == \",X\" ? \"AbsoluteX\" : \"AbsoluteY\";");
        sb.AppendLine("                return true;");
        sb.AppendLine("            }");
        sb.AppendLine("            error = $\"'{text}': write exactly 2 hex digits ($hh, zero page) or exactly 4 ($hhhh, absolute) — no promotion\";");
        sb.AppendLine("            return false;");
        sb.AppendLine("        }");
        sb.AppendLine("        error = $\"unrecognised operand '{text}'\";");
        sb.AppendLine("        return false;");
        sb.AppendLine("    }");

        // ── TryHexByte / TryHexWord helpers ──
        sb.AppendLine();
        sb.AppendLine("    private static bool TryHexByte(string s, out byte value)");
        sb.AppendLine("    {");
        sb.AppendLine("        value = 0;");
        sb.AppendLine("        return s.Length == 2 && byte.TryParse(s, System.Globalization.NumberStyles.HexNumber,");
        sb.AppendLine("            System.Globalization.CultureInfo.InvariantCulture, out value);");
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine("    private static bool TryHexWord(string s, out byte lo, out byte hi)");
        sb.AppendLine("    {");
        sb.AppendLine("        lo = 0; hi = 0;");
        sb.AppendLine("        if (s.Length != 4 || !ushort.TryParse(s, System.Globalization.NumberStyles.HexNumber,");
        sb.AppendLine("                System.Globalization.CultureInfo.InvariantCulture, out ushort v))");
        sb.AppendLine("            return false;");
        sb.AppendLine("        lo = unchecked((byte)v);");
        sb.AppendLine("        hi = unchecked((byte)(v >> 8));");
        sb.AppendLine("        return true;");
        sb.AppendLine("    }");

        // ── InterruptPending partial-property declaration ──
        sb.AppendLine();
        sb.AppendLine("    /// <summary>True exactly when the next Step will service an interrupt — the");
        sb.AppendLine("    /// IMonitorSupport contract: monitor displays say so rather than naming the");
        sb.AppendLine("    /// instruction at PC that will not run. The hand-written partial implements this");
        sb.AppendLine("    /// with the same predicate TryServiceInterrupt gates on.</summary>");
        sb.AppendLine("    public partial bool InterruptPending { get; }");

        // ── Explicit interface implementations ──
        sb.AppendLine();
        sb.AppendLine("    string CpuEmulator.Core.IMonitorSupport.Disassemble(byte opcode, byte operandLo, byte operandHi)");
        sb.AppendLine("        => Disassemble(opcode, operandLo, operandHi);");
        sb.AppendLine("    int CpuEmulator.Core.IMonitorSupport.InstructionLength(byte opcode)");
        sb.AppendLine("        => InstructionLength(opcode);");
        sb.AppendLine("    bool CpuEmulator.Core.IMonitorSupport.TryAssemble(string mnemonic, string operandText, out byte[] bytes, out string? error)");
        sb.AppendLine("        => TryAssemble(mnemonic, operandText, out bytes, out error);");
        var pcRegister = model.Registers.First(r => r.Role == "ProgramCounter");
        sb.AppendLine($"    string CpuEmulator.Core.IMonitorSupport.ProgramCounterName => \"{pcRegister.Name}\";");
        sb.AppendLine("    int CpuEmulator.Core.IMonitorSupport.RegisterBits(string name) => name switch");
        sb.AppendLine("    {");
        foreach (var reg in model.Registers)
            sb.AppendLine($"        \"{reg.Name}\" => {reg.Bits},");
        sb.AppendLine("        _ => throw new System.ArgumentException($\"Unknown register '{name}'.\", nameof(name)),");
        sb.AppendLine("    };");
    }

    // ---- Disassembler ----

    /// <summary>
    /// Emits a static <c>Disassemble</c> method that formats a decoded opcode as a human-readable
    /// string. The mnemonic whitelist (CPUGEN004: 1-8 uppercase letters/digits) guarantees every
    /// mnemonic in the table is safe for direct string interpolation — no escaping is needed.
    /// Format rules per addressing mode:
    ///   Implied   → mnemonic only        (e.g. "TAX")
    ///   Immediate → mnemonic + " #$xx"   (e.g. "LDA #$42")
    ///   ZeroPage  → mnemonic + " $xx"    (e.g. "LDA $10")
    ///   Absolute  → mnemonic + " $xxyy"  (e.g. "LDA $1234", hi then lo in address)
    ///   Relative  → mnemonic + " *±dd"   (e.g. "BNE *+5", "BNE *-4")
    ///   unknown   → "???"
    /// Relative caveat: the rendered offset is the RAW operand byte (relative to the
    /// post-operand PC), not conventional assembler <c>*</c> semantics (relative to the
    /// instruction's own address) — the two differ by the 2-byte instruction length, so
    /// bytes D0 FC render here as "BNE *-4" where a reference disassembler says "BNE *-2".
    /// Keep in mind when diffing against reference disassemblies (3b).
    /// </summary>
    private static void EmitDisassembler(StringBuilder sb, SpecModel model)
    {
        // The disassembler switches on the operation-key. For the 6502 (degenerate) the key IS the
        // opcode byte (≤ 0xFF), so the parameter stays `byte opcode` and the arms are textually
        // identical (Ground truth E: "MINIMAL (body)"). A structured CPU's key is a uint, so the
        // parameter widens to express keys > 0xFF; the IMonitorSupport.Disassemble(byte,...) contract
        // stays stable (its explicit impl widens the byte to the key).
        string opParam = (model.Decode is not null || model.FieldGrammar is not null) ? "uint opcode" : "byte opcode";
        sb.AppendLine();
        sb.AppendLine("    /// <summary>Disassemble one instruction. Returns a human-readable string.</summary>");
        sb.AppendLine($"    public static string Disassemble({opParam}, byte operandLo, byte operandHi)");
        sb.AppendLine("    {");
        sb.AppendLine("        return opcode switch");
        sb.AppendLine("        {");
        foreach (var instruction in model.Instructions)
        {
            string m = instruction.Mnemonic;
            string arm = instruction.Mode switch
            {
                "Implied" =>
                    $"            0x{instruction.OperationKey:X2} => \"{m}\",",
                "Accumulator" =>
                    $"            0x{instruction.OperationKey:X2} => \"{m} A\",",
                "Immediate" =>
                    $"            0x{instruction.OperationKey:X2} => $\"{m} #${{operandLo:X2}}\",",
                "ZeroPage" =>
                    $"            0x{instruction.OperationKey:X2} => $\"{m} ${{operandLo:X2}}\",",
                "ZeroPageX" =>
                    $"            0x{instruction.OperationKey:X2} => $\"{m} ${{operandLo:X2}},X\",",
                "ZeroPageY" =>
                    $"            0x{instruction.OperationKey:X2} => $\"{m} ${{operandLo:X2}},Y\",",
                "Absolute" =>
                    $"            0x{instruction.OperationKey:X2} => $\"{m} ${{operandHi:X2}}{{operandLo:X2}}\",",
                "AbsoluteX" =>
                    $"            0x{instruction.OperationKey:X2} => $\"{m} ${{operandHi:X2}}{{operandLo:X2}},X\",",
                "AbsoluteY" =>
                    $"            0x{instruction.OperationKey:X2} => $\"{m} ${{operandHi:X2}}{{operandLo:X2}},Y\",",
                "IndirectX" =>
                    $"            0x{instruction.OperationKey:X2} => $\"{m} (${{operandLo:X2}},X)\",",
                "IndirectY" =>
                    $"            0x{instruction.OperationKey:X2} => $\"{m} (${{operandLo:X2}}),Y\",",
                "Indirect" =>
                    $"            0x{instruction.OperationKey:X2} => $\"{m} (${{operandHi:X2}}{{operandLo:X2}})\",",
                "Relative" =>
                    $"            0x{instruction.OperationKey:X2} => $\"{m} *{{(sbyte)operandLo:+0;-0}}\",",
                // Port (M3.2): IoPortImmediate renders the (n) port byte; IoPortIndirect the (C) form.
                "IoPortImmediate" =>
                    $"            0x{instruction.OperationKey:X2} => $\"{m} (${{operandLo:X2}})\",",
                "IoPortIndirect" =>
                    $"            0x{instruction.OperationKey:X2} => \"{m} (C)\",",
                // M3.4a Z80 register-shape modes. The operand-register/pair detail is opcode-encoded
                // (not in operandLo/Hi), so the disassembly shows the mnemonic + the operand bytes that
                // ARE carried (the immediate/address); the register selectors are implicit in the row.
                "Register" =>
                    $"            0x{instruction.OperationKey:X2} => \"{m}\",",
                "RegisterIndirect" =>
                    $"            0x{instruction.OperationKey:X2} => \"{m}\",",
                "ImmediateExtended" =>
                    $"            0x{instruction.OperationKey:X2} => $\"{m} ${{operandHi:X2}}{{operandLo:X2}}\",",
                "ExtendedAddress" =>
                    $"            0x{instruction.OperationKey:X2} => $\"{m} (${{operandHi:X2}}{{operandLo:X2}})\",",
                "RelativeJump" =>
                    $"            0x{instruction.OperationKey:X2} => $\"{m} ${{operandLo:X2}}\",",
                // M3.4b (CB plane): the bit index + target register are opcode-encoded (not in
                // operandLo/Hi), so the disassembly shows the mnemonic only.
                "Bit" =>
                    $"            0x{instruction.OperationKey:X2} => \"{m}\",",
                // M3.4e-2 (IX+d)/(IY+d): the index register is the prefix byte in the OperationKey
                // (0xDD -> IX, else IY); the displacement is the first operand byte (operandLo). For a
                // plain prefixed key (0xDD7E) the prefix is >> 8; for a 24-bit COMPOUND key (0xDDCB46,
                // M3.4e-3) it is >> 16 — using >> 8 there would yield 0xDDCB and mis-render IX as IY (H1/
                // D11). The disassembly string is NOT vector-gated — it need only be well-formed + not throw.
                "Indexed" =>
                    $"            0x{instruction.OperationKey:X} => $\"{m} ({((instruction.OperationKey > 0xFFFF ? instruction.OperationKey >> 16 : instruction.OperationKey >> 8) == 0xDD ? "IX" : "IY")}+${{operandLo:X2}})\",",
                _ => throw new System.InvalidOperationException(
                    $"emitter has no disassembler format for mode '{instruction.Mode}' (opcode 0x{instruction.Opcode:X2})"),
            };
            sb.AppendLine(arm);
        }
        sb.AppendLine("            _ => \"???\",");
        sb.AppendLine("        };");
        sb.AppendLine("    }");
    }

    // ---- JIT descriptor table (generated artifact ③, data form) ----

    /// <summary>Emit <c>public static readonly OpcodeDescriptor[] JitDescriptors</c> — a
    /// 256-slot, opcode-indexed table the CpuEmulator.Jit block compiler walks. Absent opcodes
    /// get the Undefined sentinel. Length/BaseCycles/page-cross reuse the SAME ModeLength,
    /// ComputeCycles, and isPageCross logic the interpreter body emission uses, so the table
    /// can never drift from the interpreter on length or cycle template. Pure data — no
    /// Reflection.Emit here; the JIT assembly is the only place that emits IL.</summary>
    private static void EmitJitDescriptors(StringBuilder sb, SpecModel model, FlagBitMap flags)
    {
        // A declared DecodeStructure OR a word-granular FieldGrammar (M4.3a) keys descriptors on the
        // opaque OperationKey via a dictionary (the field-decode DescriptorFor resolves through it). A
        // FieldGrammar CPU has no instruction rows yet, so the dictionary is empty — but it must EXIST.
        if (model.Decode is not null || model.FieldGrammar is not null)
        {
            EmitKeyedDescriptorTable(sb, model, flags);
            return;
        }

        // Degenerate (6502): a 256-slot lookup so absent opcodes get the Undefined sentinel.
        var byOpcode = model.Instructions.ToDictionary(i => i.Opcode);

        sb.AppendLine();
        sb.AppendLine("    /// <summary>Per-opcode JIT descriptor table (generated artifact ③, data form).");
        sb.AppendLine("    /// Indexed by opcode; absent opcodes are the Undefined sentinel. Consumed by");
        sb.AppendLine("    /// CpuEmulator.Jit's CPU-agnostic block compiler. AOT-clean data — no Reflection.Emit");
        sb.AppendLine("    /// here; the JIT assembly is the only place that emits IL.</summary>");
        sb.AppendLine("    public static readonly CpuEmulator.Core.Jit.OpcodeDescriptor[] JitDescriptors =");
        sb.AppendLine("    [");
        for (int op = 0; op <= 0xFF; op++)
        {
            if (byOpcode.TryGetValue((byte)op, out var insn))
                sb.AppendLine($"        {DescriptorLiteral(insn, flags)},");
            else
                sb.AppendLine($"        CpuEmulator.Core.Jit.OpcodeDescriptor.Undefined(0x{op:X2}),");
        }
        sb.AppendLine("    ];");
    }

    /// <summary>Emit the key→descriptor dictionary for a CPU that declared a DecodeStructure
    /// (the multi-byte key path — Ground truth C/E). A dense [256] array cannot hold prefixed/bare/
    /// opcode-group rows that share an opcode byte, so the structured CPU keys its descriptors on the
    /// opaque OperationKey instead. ModR/M rows carry LengthRule.ModRmDetermined; every other row is
    /// LengthRule.Fixed. The 6502 (no DecodeStructure) keeps the dense array path above.</summary>
    private static void EmitKeyedDescriptorTable(StringBuilder sb, SpecModel model, FlagBitMap flags)
    {
        // A FieldGrammar-only CPU (M4.3a) declares no DecodeStructure, hence no ModRm opcodes; the field-
        // decode path computes length itself, so the keyed table is just the (empty, for M4.3a) row map.
        var modRm = model.Decode?.ModRmOpcodes.Values ?? System.Collections.Immutable.ImmutableArray<byte>.Empty;
        sb.AppendLine();
        sb.AppendLine("    /// <summary>Key→descriptor table for a declared DecodeStructure (Ground truth C). Keyed on");
        sb.AppendLine("    /// the opaque OperationKey the walk computes; DescriptorFor consults this, never a raw");
        sb.AppendLine("    /// byte index, so the key packing is fully encapsulated.</summary>");
        sb.AppendLine("    public static readonly System.Collections.Generic.Dictionary<uint, CpuEmulator.Core.Jit.OpcodeDescriptor> JitDescriptorsByKey = new()");
        sb.AppendLine("    {");
        foreach (var insn in model.Instructions)
        {
            bool isModRm = modRm.Contains(insn.Opcode) && insn.KeyShape == KeyShape.OpcodeByte;
            sb.AppendLine($"        [0x{insn.OperationKey:X}u] = {KeyedDescriptorLiteral(insn, isModRm, flags)},");
        }
        sb.AppendLine("    };");
    }

    /// <summary>One descriptor row as a C# object-creation expression. Reuses ModeLength,
    /// ComputeCycles, and the isPageCross predicate — the SAME functions the interpreter
    /// body emission uses, so the table cannot drift from the interpreter.</summary>
    private static string DescriptorLiteral(InstructionModel insn, FlagBitMap flags)
    {
        InstructionClass cls = insn.Class;
        int length = ModeLength(insn.Mode);
        int baseCycles = JitBaseCycles(insn, cls);
        bool pageCross = insn.Mode is "AbsoluteX" or "AbsoluteY" or "IndirectY"
            && cls is InstructionClass.Load or InstructionClass.Alu;
        (string jitClass, bool endsBlock, bool fallback) = ClassifyForJit(insn, cls);
        string ops = string.Join(", ", insn.Ops.Select(o => JitOpLiteral(o, flags)));
        return $"new(0x{insn.Opcode:X2}, \"{insn.Mnemonic}\", "
             + $"CpuEmulator.Core.Jit.JitMode.{insn.Mode}, "
             + $"CpuEmulator.Core.Jit.JitOpClass.{jitClass}, "
             + $"CpuEmulator.Core.Jit.LengthRule.Fixed, {length}, {baseCycles}, "
             + $"{(pageCross ? "true" : "false")}, "
             + $"{(fallback ? "true" : "false")}, {(endsBlock ? "true" : "false")}, "
             + $"[{ops}])";
    }

    /// <summary>One descriptor row for a CPU that declared a DecodeStructure (the synthetic CPU). The
    /// FixedLength is the count of bytes the walk consumes BEFORE any operand bytes the mode adds:
    /// OpcodeByte → 1; PrefixedOpcode → 2 (prefix + opcode); OpcodeGroup → 2 (opcode + the sub-field
    /// byte); ModRm → 2 base (opcode + the length-determining byte) with LengthRule.ModRmDetermined,
    /// the walk reading the variable tail. (The synthetic ops are Implied with no operand bytes —
    /// the proof is the DECODE SHAPE, not operand carriage; Ground truth F scope honesty.)</summary>
    private static string KeyedDescriptorLiteral(InstructionModel insn, bool isModRm, FlagBitMap flags)
    {
        InstructionClass cls = insn.Class;
        int baseCycles = JitBaseCycles(insn, cls);
        (string jitClass, bool endsBlock, bool fallback) = ClassifyForJit(insn, cls);

        // M3.5-3a (J1/J3): a STRUCTURED CPU (one with a DecodeStructure — the Z80, and the synthetic
        // decode fixtures) emits its keyed descriptors with NeedsFallback FORCED true. The generic JIT
        // cannot yet emit correct IL for a structured CPU's ops (the Z80's flag model + M-cycle/T-state
        // timing differ from the 6502 arms the JIT has), so EVERY structured-CPU op defers to the
        // interpreter Step in 5-3a — the all-fallback bring-up the tier-parity gate proves. WITHOUT
        // this, a Z80 op the importer mapped to a GENERIC class (e.g. NOP→Register, LD A,n→Load — not a
        // Z80* class, so ClassifyForJit's z80 guard misses it) would be wrongly emitted via the 6502 arm
        // with the 6502 cycle model (NOP=2T vs the Z80's 4T) — breaking tier parity. 5-3b flips the hot
        // Z80 ops back to emitted IL one family at a time, each with its own correct cycle + flag model.
        // A fallback op ENDS the block (one interpreter Step per block), matching ClassifyForJit's rule.
        fallback = true;
        endsBlock = true;

        string ops = string.Join(", ", insn.Ops.Select(o => JitOpLiteral(o, flags)));

        int fixedLength = insn.KeyShape switch
        {
            KeyShape.PrefixedOpcode => 2,   // prefix + opcode
            KeyShape.OpcodeGroup => 2,       // opcode + the sub-field byte
            KeyShape.Compound => 4,          // M3.4e-1b: prefix + CB + displacement + opcode
            _ => isModRm ? 2 : 1,            // ModRm base (opcode + modrm) | plain single byte
        };
        string rule = isModRm
            ? "CpuEmulator.Core.Jit.LengthRule.ModRmDetermined"
            : "CpuEmulator.Core.Jit.LengthRule.Fixed";

        return $"new(0x{insn.Opcode:X2}, \"{insn.Mnemonic}\", "
             + $"CpuEmulator.Core.Jit.JitMode.{insn.Mode}, "
             + $"CpuEmulator.Core.Jit.JitOpClass.{jitClass}, "
             + $"{rule}, {fixedLength}, {baseCycles}, false, "
             + $"{(fallback ? "true" : "false")}, {(endsBlock ? "true" : "false")}, "
             + $"[{ops}])";
    }

    /// <summary>The descriptor's BaseCycles — the fixed cycle template the block compiler
    /// charges. For the per-op-kind variable classes (Branch, Stack, Flow) the raw
    /// <see cref="ComputeCycles"/> base is not the real count, so this mirrors the SAME per-op
    /// cycle logic the interpreter's <see cref="ComputeStackCycleStr"/>/<see cref="ComputeFlowCycleStr"/>
    /// doc strings encode (and the emitted bodies realize byte-for-byte): Branch → 2 (the +1/+1
    /// for taken/page-cross are emitted at run time); Push → 3, Pull → 4; JSR/RTS/RTI → 6,
    /// BRK → 7. Every other (mode, class) uses ComputeCycles directly. Keeps the descriptor's
    /// BaseCycles equal to the interpreter's notion so the JIT charges identical cycles.</summary>
    private static int JitBaseCycles(InstructionModel insn, InstructionClass cls)
    {
        if (cls == InstructionClass.Branch)
            return 2;

        string firstKind = insn.Ops.Length > 0 ? insn.Ops[0].Kind : string.Empty;
        // M3.4a: Z80 classes get their base T-state count from the Z80 cycle table (the not-taken
        // base for conditional flow; the body adds the taken penalty — parallel to the 6502 branch).
        if (cls is InstructionClass.Z80Alu or InstructionClass.Z80Ld or InstructionClass.Z80Stack
            or InstructionClass.Z80Exchange or InstructionClass.Z80Flow or InstructionClass.Z80Misc
            or InstructionClass.Z80Rot or InstructionClass.Z80Bit
            or InstructionClass.Z80EdIo or InstructionClass.Z80EdOp
            or InstructionClass.Z80EdBlock or InstructionClass.Z80Indexed
            or InstructionClass.Z80DdCb)
            return Z80Cycles(insn.Mode, cls, firstKind);

        if (cls == InstructionClass.Stack)
            return firstKind switch
            {
                "Push" or "PushP" => 3,   // opcode + dummy read + write
                "Pull" or "PullP" => 4,   // opcode + dummy read + dummy stack read + real read
                _ => 2,
            };
        if (cls == InstructionClass.Flow)
            return firstKind switch
            {
                "Jsr" => 6,
                "Rts" => 6,
                "Brk" => 7,
                "Rti" => 6,
                _ => ComputeCycles(insn.Mode, cls),
            };

        return ComputeCycles(insn.Mode, cls);
    }

    /// <summary>Map the interpreter's <see cref="InstructionClass"/> to the JIT
    /// <c>JitOpClass</c>, returning the (class, endsBlock, needsFallback) triple. The
    /// interpreter's coarse <c>Flow</c> class is split by op-kind: JSR → Jsr, RTS → Rts,
    /// BRK/RTI → Flow (+fallback). The interpreter's <c>Jump</c> stays Jump. ADC/SBC are EMITTED
    /// (M2-ii Task 5) — straight-line Alu-class, no fallback. EndsBlock = a control-flow JIT class
    /// OR fallback.
    /// The interpreter's <c>Stack</c> class (PHA/PLA/PHP/PLP) maps to the JIT <c>Register</c>
    /// class: both are Implied, straight-line, block-continuing — the block compiler dispatches
    /// the stack ops by op-kind within the Register arm (the JIT enum has no Stack member; the
    /// schema-only <c>Transfer</c> value is reserved for CPU-agnostic future use).</summary>
    private static (string JitClass, bool EndsBlock, bool Fallback) ClassifyForJit(
        InstructionModel insn, InstructionClass cls)
    {
        string firstKind = insn.Ops.Length > 0 ? insn.Ops[0].Kind : string.Empty;
        // M2-ii Task 5 (the ambition decision's planned flip): ADC/SBC are now EMITTED in both the
        // binary and decimal arms (Ground truth E), so they leave the fallback set — they become
        // straight-line Alu-class (NeedsFallback false, EndsBlock false). BRK/RTI stay fallbacks
        // (recorded decision: they touch the interrupt/vector machinery the interpreter owns).
        // Halt (M3.2): a HALT/STOP row rides the Register class but is a JIT FALLBACK — the halted
        // idle is delegated to _inner.Step by the dispatcher's halted fast path (Ground truth B.3),
        // so the JIT never needs a Halt emit arm. The 6502 has no HaltOp, so this never fires for it.
        // M3.4a: ALL Z80 base-plane classes are JIT FALLBACKS — the Z80 runs interpreter-only (M3.5
        // JITs it). The descriptor is emitted (the table must be well-formed) with NeedsFallback so a
        // Z80 block defers to the interpreter; the JIT never emits IL for a Z80 op. The 6502 (which
        // names none of these classes) is unchanged. Z80 control-flow classes also end the block.
        bool z80 = cls is InstructionClass.Z80Alu or InstructionClass.Z80Ld or InstructionClass.Z80Stack
            or InstructionClass.Z80Exchange or InstructionClass.Z80Flow or InstructionClass.Z80Misc
            or InstructionClass.Z80Rot or InstructionClass.Z80Bit
            or InstructionClass.Z80EdIo or InstructionClass.Z80EdOp
            or InstructionClass.Z80EdBlock or InstructionClass.Z80Indexed
            or InstructionClass.Z80DdCb;
        bool fallback = firstKind is "Brk" or "Rti" or "Halt" || z80;

        string jitClass = cls switch
        {
            InstructionClass.Load => "Load",
            InstructionClass.Store => "Store",
            InstructionClass.Register => "Register",
            InstructionClass.Stack => "Register",
            InstructionClass.Alu => "Alu",
            InstructionClass.Rmw => "Rmw",
            InstructionClass.Branch => "Branch",
            InstructionClass.Jump => "Jump",
            InstructionClass.Port => "Port",   // M3.2: the Io-bus callout arm (never fastmem)
            InstructionClass.Flow => firstKind switch
            {
                "Jsr" => "Jsr",
                "Rts" => "Rts",
                _ => "Flow",          // Brk/Rti
            },
            // M3.4a: Z80 classes ride the Flow/Undefined-style fallback — they never emit IL.
            InstructionClass.Z80Flow => "Flow",
            InstructionClass.Z80Alu or InstructionClass.Z80Ld or InstructionClass.Z80Stack
                or InstructionClass.Z80Exchange or InstructionClass.Z80Misc
                or InstructionClass.Z80Rot or InstructionClass.Z80Bit
                or InstructionClass.Z80EdIo or InstructionClass.Z80EdOp
                or InstructionClass.Z80EdBlock or InstructionClass.Z80Indexed
                or InstructionClass.Z80DdCb => "Register",
            _ => throw new System.InvalidOperationException(
                $"ClassifyForJit has no mapping for class '{cls}' (opcode 0x{insn.Opcode:X2})"),
        };

        bool endsBlock = jitClass is "Branch" or "Jump" or "Jsr" or "Rts" or "Flow" || fallback;
        return (jitClass, endsBlock, fallback);
    }

    /// <summary>Render one <see cref="OpModel"/> as a <c>JitOp</c> object-creation expression:
    /// <c>new JitOp("Kind", "regA", "regB", flagBit, boolArg)</c>. Register args carry their
    /// declared NAME (J2 — the register file is data, not a fixed A=0/X=1/… index); flag args map
    /// to their hardware bit via <see cref="FlagBit"/>; a trailing bool literal becomes BoolArg.
    /// Unused register slots are the empty string "" (the unambiguous "no register operand"
    /// marker — no register is ever named "").</summary>
    private static string JitOpLiteral(OpModel op, FlagBitMap flags)
    {
        string regA = "\"\"", regB = "\"\"";
        byte flagBit = 0;
        bool boolArg = false;

        switch (op.Kind)
        {
            case "Transfer":   // (reg source, reg target)
                regA = Quote(op.Args[0]);
                regB = Quote(op.Args[1]);
                break;
            case "Load":       // (reg target)
            case "Store":      // (reg source)
            case "Increment":  // (reg target)
            case "Decrement":  // (reg target)
            case "SetNZ":      // (reg source)
            case "Compare":    // (reg source)
            case "Push":       // (reg source)
            case "Pull":       // (reg target)
            case "PortIn":     // (reg target) — M3.2
            case "PortOut":    // (reg source) — M3.2
            case "SetSZ":      // (reg source) — M3.4a
            case "SetParity":  // (reg source) — M3.4a
            case "SetXY":      // (reg source) — M3.4a
                regA = Quote(op.Args[0]);
                break;
            case "SetAddSub":  // (bool subtract) — M3.4a
                boolArg = op.Args[0] == "true";
                break;
            case "IncReg":     // (reg) — M3.4a
            case "DecReg":
            case "Inc16":
            case "Dec16":
            case "Load16":
            case "Store16":
            case "LoadMem16":
            case "Push16":
            case "Pop16":
            case "Djnz":
                regA = Quote(op.Args[0]);
                break;
            case "Add16":      // (target, source) — M3.4a
                regA = Quote(op.Args[0]);
                regB = Quote(op.Args[1]);
                break;
            case "BranchIf":   // (Flag, bool when)
            case "SetFlag":    // (Flag, bool value)
            case "JumpIf":     // (Flag cc, bool sense) — M3.4a
            case "CallIf":
            case "RetCc":
            case "RelJumpIf":
                flagBit = (byte)flags.BitOf(op.Args[0]);
                boolArg = op.Args[1] == "true";
                break;
            case "CbRotate":   // (string op, string target) — JIT fallback; slots unused
            case "CbBit":      // (string op, int bit, string target) — JIT fallback; slots unused
            // M3.4c ED-core ops — JIT fallback; slots unused (same treatment as CbRotate/CbBit).
            case "EdIn":
            case "EdOut":
            case "EdAdcSbc16":
            case "EdLdNnRp":
            case "EdNeg":
            case "EdRetn":
            case "EdIm":
            case "EdLdIaRa":
            case "EdRrdRld":
            case "EdNop":
            case "EdBlock":   // M3.4d ED block op — JIT fallback; slots unused
            // M3.4e-2 DD/FD indexed ops — JIT fallback (D4: DD/FD JIT-IL deferred to M3.5); slots unused.
            case "DdFdLdIndexed":
            case "DdFdStoreImmIndexed":
            case "DdFdAluIndexed":
            case "DdFdIncDecIndexed":
            case "DdCb":      // M3.4e-3 DDCB/FDCB compound op — JIT fallback (D4); slots unused
                break;         // leave regA/regB empty; the Z80 op never emits IL
            // Zero-arg op kinds (Jump, Adc, Sbc, And, Ora, Eor, Bit, ShiftLeft, ShiftRight,
            // RotateLeft, RotateRight, IncrementMem, DecrementMem, PushP, PullP, Jsr, Rts,
            // Brk, Rti; M3.4a Add8..Cp8, IncMem8/DecMem8, StoreImm8, ExDeHl/ExAfAf/Exx/ExSpHl,
            // RelJump/Rst/JumpIndirect/JumpAbs/CallAbs/Ret, Daa/Cpl/Scf/Ccf/Di/Ei;
            // M3.4b Rlca/Rrca/Rla/Rra) carry no register/flag operands — register slots stay "".
            default:
                break;
        }

        return $"new CpuEmulator.Core.Jit.JitOp(\"{op.Kind}\", {regA}, {regB}, {flagBit}, "
             + $"{(boolArg ? "true" : "false")})";
    }

    /// <summary>Quote a register name for direct interpolation into a JitOp literal. Register
    /// names passed the identifier + reserved-name guards at declaration (SpecParser CPUGEN002/
    /// the identifier-validity check), so direct interpolation is injection-safe — same posture as
    /// the mnemonic whitelist used elsewhere in this emitter.</summary>
    private static string Quote(string s) => $"\"{s}\"";

    // ---- The decode walk (Ground truths A/C/E) ----

    /// <summary>Emit the single generated decode walk — <c>Decode(IFetchStream)</c> + the key→
    /// descriptor resolver <c>DescriptorFor(uint)</c> — that replaces the four switch(opcode) decode
    /// sites with ONE model (Ground truth A). For a spec with NO DecodeStructure (the 6502 — the
    /// default), this is the degenerate byte-key / fixed-length walk: consume the opcode unit, look
    /// up its descriptor, consume the operand units its FixedLength implies, and return
    /// (key == opcode, COMPUTED Length, operands). A spec that declares a DecodeStructure (the
    /// synthetic CPU — Task 7) emits the non-degenerate walk (prefix / ModR/M-length / sub-field key)
    /// + a dictionary resolver. Length == stream.UnitsConsumed × stream.UnitBytes — a COMPUTED
    /// output, never a field read (Ground truth B).</summary>
    private static void EmitDecodeWalk(StringBuilder sb, SpecModel model)
    {
        if (model.Decode is not null || model.FieldGrammar is not null)
        {
            EmitStructuredDecodeWalk(sb, model);
            return;
        }

        // Degenerate (6502) walk: single byte opcode, key == opcode, fixed length per mode.
        sb.AppendLine();
        sb.AppendLine("    /// <summary>The generated decode walk (Ground truth A): consume the opcode unit, look up");
        sb.AppendLine("    /// its descriptor, consume the operand units its FixedLength implies, and return");
        sb.AppendLine("    /// (OperationKey, COMPUTED Length, Operands). For this CPU every row is LengthRule.Fixed");
        sb.AppendLine("    /// and the key is the opcode byte — the degenerate walk the 6502 always takes.");
        sb.AppendLine("    /// Length == stream.UnitsConsumed × stream.UnitBytes (a COMPUTED output, not a field).</summary>");
        sb.AppendLine("    public static CpuEmulator.Core.Jit.DecodeResult Decode(CpuEmulator.Core.Jit.IFetchStream stream)");
        sb.AppendLine("    {");
        sb.AppendLine("        uint opcode = stream.NextUnit();                       // consume the opcode unit");
        sb.AppendLine("        uint key = opcode;                                     // KeyShape.OpcodeByte — key == opcode");
        sb.AppendLine("        CpuEmulator.Core.Jit.OpcodeDescriptor d = DescriptorFor(key);");
        sb.AppendLine("        byte lo = 0, hi = 0, count = 0;");
        sb.AppendLine("        // Fixed rule: consume (FixedLength - 1) operand units (the mode's operand bytes).");
        sb.AppendLine("        for (int i = 1; i < d.FixedLength; i++)");
        sb.AppendLine("        {");
        sb.AppendLine("            byte b = (byte)stream.NextUnit();");
        sb.AppendLine("            if (count == 0) { lo = b; count = 1; }");
        sb.AppendLine("            else { hi = b; count = 2; }");
        sb.AppendLine("        }");
        sb.AppendLine("        int length = stream.UnitsConsumed * stream.UnitBytes;  // COMPUTED — not a field read");
        sb.AppendLine("        return new CpuEmulator.Core.Jit.DecodeResult(key, length, new(lo, hi, count));");
        sb.AppendLine("    }");

        sb.AppendLine();
        sb.AppendLine("    /// <summary>Resolve an operation-key to its descriptor (Ground truth C). The dense [256]");
        sb.AppendLine("    /// array index — key fits a byte, so zero hot-path regression. A prefixed CPU emits a");
        sb.AppendLine("    /// dictionary here; the consumers call this, never the raw table, so the key packing is");
        sb.AppendLine("    /// fully encapsulated.</summary>");
        sb.AppendLine("    public static CpuEmulator.Core.Jit.OpcodeDescriptor DescriptorFor(uint operationKey)");
        sb.AppendLine("        => JitDescriptors[(byte)operationKey];");
    }

    /// <summary>Emit the NON-degenerate decode walk for a declared DecodeStructure (Ground truths
    /// C/E — the synthetic CPU's proof that the model generalizes to Z80 prefixes AND 8086 ModR/M).
    /// The walk: read the first unit; if it is a PREFIX byte, read the opcode and pack
    /// key = (prefix &lt;&lt; 8) | opcode; if it is a SUB-FIELD opcode, read the next byte and pack
    /// key = (opcode &lt;&lt; 3) | ((next &gt;&gt; 3) &amp; 7); if it is a MODR/M opcode, read the
    /// length-determining byte and consume (byte &amp; 3) tail bytes — a COMPUTED length; otherwise the
    /// degenerate key == opcode. A declared COMPOUND prefix (the Z80 DD CB d op form) routes via
    /// s_compoundWith / s_dispBeforeOpcode: when the next byte is the prefix's CompoundWith byte the
    /// walk consumes the displacement (DisplacementBeforeOpcode) then the final opcode, packing a
    /// 24-bit key (prefix &lt;&lt; 16) | (CompoundWith &lt;&lt; 8) | opcode. DescriptorFor resolves
    /// through the keyed dictionary. Length == stream.UnitsConsumed × stream.UnitBytes throughout —
    /// never a field read.</summary>
    private static void EmitStructuredDecodeWalk(StringBuilder sb, SpecModel model)
    {
        // M4.3a (ADR 0004 Decision 1): a declared word-granular FieldGrammar selects the field-decode arm
        // (non-contiguous bit-field extraction over a 16-bit big-endian operword). A byte-fetch CPU
        // (6502/Z80/8086) has no FieldGrammar, so it falls through to the existing prefix/ModRm/sub-field
        // walk below — byte-identical.
        if (model.FieldGrammar is { } grammar && grammar.FetchUnit == FetchUnit.Word)
        {
            EmitFieldDecodeWalk(sb, model, grammar);
            return;
        }

        var decode = model.Decode!;
        string prefixSet = string.Join(", ", decode.Prefixes.Values.Select(p => $"0x{p:X2}"));
        string modRmSet = string.Join(", ", decode.ModRmOpcodes.Values.Select(p => $"0x{p:X2}"));
        string subFieldSet = string.Join(", ", decode.SubFieldOpcodes.Values.Select(p => $"0x{p:X2}"));

        sb.AppendLine();
        sb.AppendLine($"    private static readonly System.Collections.Generic.HashSet<uint> s_prefixBytes = new() {{ {prefixSet} }};");
        sb.AppendLine($"    private static readonly System.Collections.Generic.HashSet<uint> s_modRmOpcodes = new() {{ {modRmSet} }};");
        sb.AppendLine($"    private static readonly System.Collections.Generic.HashSet<uint> s_subFieldOpcodes = new() {{ {subFieldSet} }};");

        // M3.4e-1b: the per-prefix COMPOUND metadata. s_compoundWith maps a compound prefix byte
        // (DD/FD) → its CompoundWith byte (CB); s_dispBeforeOpcode is the set of compound prefixes
        // whose displacement precedes the final opcode (the DD CB d op shape). A plain prefix
        // (CB/ED — no CompoundWith) appears in NEITHER, so its decode is byte-identical.
        var compoundPrefixes = decode.PrefixDetails.Values.Where(p => p.CompoundWith >= 0).ToList();
        string compoundWithPairs = string.Join(", ", compoundPrefixes.Select(p => $"{{ 0x{p.Value:X2}, 0x{p.CompoundWith:X2} }}"));
        string dispBeforeSet = string.Join(", ", compoundPrefixes.Where(p => p.DisplacementBeforeOpcode).Select(p => $"0x{p.Value:X2}"));
        sb.AppendLine($"    private static readonly System.Collections.Generic.Dictionary<uint, uint> s_compoundWith = new() {{ {compoundWithPairs} }};");
        sb.AppendLine($"    private static readonly System.Collections.Generic.HashSet<uint> s_dispBeforeOpcode = new() {{ {dispBeforeSet} }};");

        sb.AppendLine();
        sb.AppendLine("    /// <summary>The generated decode walk for a declared DecodeStructure (Ground truth A/C):");
        sb.AppendLine("    /// prefix / mid-stream-length (ModR/M) / sub-field-key, with Length COMPUTED by consumption");
        sb.AppendLine("    /// (UnitsConsumed × UnitBytes), never a field read. The synthetic CPU's three-property proof.</summary>");
        sb.AppendLine("    public static CpuEmulator.Core.Jit.DecodeResult Decode(CpuEmulator.Core.Jit.IFetchStream stream)");
        sb.AppendLine("    {");
        sb.AppendLine("        uint first = stream.NextUnit();                        // consume the first unit");
        sb.AppendLine("        uint key;");
        sb.AppendLine("        byte lo = 0, hi = 0, count = 0;");
        sb.AppendLine("        if (s_prefixBytes.Contains(first))");
        sb.AppendLine("        {");
        sb.AppendLine("            uint op = stream.NextUnit();                       // the byte after the prefix");
        sb.AppendLine("            if (s_compoundWith.TryGetValue(first, out uint second) && op == second)");
        sb.AppendLine("            {");
        sb.AppendLine("                // M3.4e-1b COMPOUND prefix (Z80 DD CB / FD CB). When the displacement");
        sb.AppendLine("                // precedes the opcode (DD CB d op), consume it BEFORE the final opcode.");
        sb.AppendLine("                uint finalOp;");
        sb.AppendLine("                if (s_dispBeforeOpcode.Contains(first))");
        sb.AppendLine("                {");
        sb.AppendLine("                    lo = (byte)stream.NextUnit(); count = 1;       // the displacement byte d");
        sb.AppendLine("                    finalOp = stream.NextUnit();                   // then the final opcode");
        sb.AppendLine("                }");
        sb.AppendLine("                else");
        sb.AppendLine("                {");
        sb.AppendLine("                    finalOp = stream.NextUnit();");
        sb.AppendLine("                }");
        sb.AppendLine("                key = (first << 16) | (second << 8) | finalOp;     // KeyShape.Compound (24-bit)");
        sb.AppendLine("            }");
        sb.AppendLine("            else");
        sb.AppendLine("            {");
        sb.AppendLine("                key = (first << 8) | op;                           // KeyShape.PrefixedOpcode (plain / DD-core)");
        sb.AppendLine("            }");
        sb.AppendLine("        }");
        sb.AppendLine("        else if (s_subFieldOpcodes.Contains(first))");
        sb.AppendLine("        {");
        sb.AppendLine("            uint next = stream.NextUnit();                     // opcode group → read the sub-field byte");
        sb.AppendLine("            key = (first << 3) | ((next >> 3) & 7);            // KeyShape.OpcodeGroup — bits 5-3");
        sb.AppendLine("        }");
        sb.AppendLine("        else if (s_modRmOpcodes.Contains(first))");
        sb.AppendLine("        {");
        sb.AppendLine("            key = first;                                       // LengthRule.ModRmDetermined");
        sb.AppendLine("            byte modrm = (byte)stream.NextUnit();              // the length-determining mid-stream byte");
        sb.AppendLine("            lo = modrm; count = 1;");
        sb.AppendLine("            int tail = modrm & 0x03;                           // its low 2 bits set how many MORE bytes follow");
        sb.AppendLine("            for (int i = 0; i < tail; i++) stream.NextUnit();  // COMPUTED tail");
        sb.AppendLine("        }");
        sb.AppendLine("        else");
        sb.AppendLine("        {");
        sb.AppendLine("            key = first;                                       // KeyShape.OpcodeByte — the degenerate case");
        sb.AppendLine("            CpuEmulator.Core.Jit.OpcodeDescriptor d = DescriptorFor(key);");
        sb.AppendLine("            for (int i = 1; i < d.FixedLength; i++)");
        sb.AppendLine("            {");
        sb.AppendLine("                byte b = (byte)stream.NextUnit();");
        sb.AppendLine("                if (count == 0) { lo = b; count = 1; }");
        sb.AppendLine("                else { hi = b; count = 2; }");
        sb.AppendLine("            }");
        sb.AppendLine("        }");
        sb.AppendLine("        int length = stream.UnitsConsumed * stream.UnitBytes;  // COMPUTED — not a field read");
        sb.AppendLine("        return new CpuEmulator.Core.Jit.DecodeResult(key, length, new(lo, hi, count));");
        sb.AppendLine("    }");

        sb.AppendLine();
        sb.AppendLine("    /// <summary>Resolve an operation-key to its descriptor (Ground truth C). A declared");
        sb.AppendLine("    /// DecodeStructure keys descriptors on the opaque OperationKey via a dictionary — a dense");
        sb.AppendLine("    /// [256] array cannot hold prefixed/bare/group rows that share an opcode byte. An unknown");
        sb.AppendLine("    /// key gets the Undefined sentinel.</summary>");
        sb.AppendLine("    public static CpuEmulator.Core.Jit.OpcodeDescriptor DescriptorFor(uint operationKey)");
        sb.AppendLine("        => JitDescriptorsByKey.TryGetValue(operationKey, out var d)");
        sb.AppendLine("            ? d : CpuEmulator.Core.Jit.OpcodeDescriptor.Undefined((byte)operationKey);");
    }

    /// <summary>M4.3a (ADR 0004 Decision 1): the word-granular, field-decomposed decode walk. Fetches a
    /// 16-bit big-endian operword, matches it against the emitted (mask, match) field-op table, extracts
    /// (operation, size, ea-mode, ea-register) by non-contiguous bit-field extraction, packs the opaque
    /// (operation, size) key, and (Task 4) consumes the extension words the (ea-mode × size) implies so
    /// the COMPUTED length is right. No match ⇒ the Undefined sentinel (the illegal-instruction path; the
    /// vector is M4.5). Length == UnitsConsumed × UnitBytes (= words × 2) throughout — never a field read.</summary>
    private static void EmitFieldDecodeWalk(StringBuilder sb, SpecModel model, FieldGrammarModel grammar)
    {
        // Emit the field-op table: each entry (mask, match, opIndex, sizeShift, sizeWidth, sizeEnc, eaShift).
        // opIndex is the op's position in the grammar (the (operation, size) key's high part).
        sb.AppendLine();
        sb.AppendLine("    // M4.3a: the word-granular field-op table (mask, match, opIndex, size/EA field positions).");
        sb.AppendLine("    private static readonly (uint Mask, uint Match, uint OpIndex, int SizeShift, int SizeWidth, int SizeEnc, int EaShift)[] s_fieldOps =");
        sb.AppendLine("    [");
        for (int i = 0; i < grammar.Ops.Length; i++)
        {
            var op = grammar.Ops[i];
            int sizeEnc = (int)op.SizeEncoding;   // 0 = Standard, 1 = Move (C4)
            sb.AppendLine($"        (0x{op.Mask:X4}u, 0x{op.Match:X4}u, {i}u, {op.SizeShift}, {op.SizeWidth}, {sizeEnc}, {op.EaShift}),");
        }
        sb.AppendLine("    ];");

        sb.AppendLine();
        sb.AppendLine("    /// <summary>The generated word-granular field-decode walk (M4.3a, ADR 0004 Decision 1).</summary>");
        sb.AppendLine("    public static CpuEmulator.Core.Jit.DecodeResult Decode(CpuEmulator.Core.Jit.IFetchStream stream)");
        sb.AppendLine("    {");
        sb.AppendLine("        uint operword = stream.NextUnit();                    // the 16-bit big-endian operword (one word)");
        sb.AppendLine("        for (int i = 0; i < s_fieldOps.Length; i++)");
        sb.AppendLine("        {");
        sb.AppendLine("            var f = s_fieldOps[i];");
        sb.AppendLine("            if ((operword & f.Mask) != f.Match) continue;     // non-matching op");
        sb.AppendLine("            // Extract the size bits and map via the size encoding (Standard vs Move — C4).");
        sb.AppendLine("            uint sizeBits = (operword >> f.SizeShift) & (uint)((1 << f.SizeWidth) - 1);");
        sb.AppendLine("            uint size = MapSize(sizeBits, f.SizeEnc);          // 0=b, 1=w, 2=l (an OperandSize index)");
        sb.AppendLine("            // M4.5b: the address-reg variants (ADDA/SUBA/CMPA) have a 1-bit size field (opmode bit 8:");
        sb.AppendLine("            // 0=.w, 1=.l) that the Standard MapSize yields as index 0/1 — but the operand is .w/.l, NOT");
        sb.AppendLine("            // .b/.w. Remap to the REAL operand size index (1=.w, 2=.l) so the extension-word count, the EA");
        sb.AppendLine("            // (An)+/-(An) magnitude, and the (operation,size) key all reflect .w/.l (the body relies on it).");
        sb.AppendLine("            if (IsAddressRegVariant(f.OpIndex)) size += 1u;");
        sb.AppendLine("            // Extract the 6-bit EA field: mode = bits 5-3, register = bits 2-0 (M4.3b consumes these).");
        sb.AppendLine("            uint ea = (operword >> f.EaShift) & 0x3F;");
        sb.AppendLine("            uint eaMode = (ea >> 3) & 7;");
        sb.AppendLine("            uint eaReg  = ea & 7;");
        sb.AppendLine("            // The opaque (operation, size) descriptor key (Ground truth C — opaque to consumers).");
        sb.AppendLine("            uint key = (1u << 24) | (f.OpIndex << 8) | size;   // high tag keeps it distinct from byte/prefix keys");
        sb.AppendLine("            ushort e0 = 0, e1 = 0, e2 = 0, e3 = 0;                     // M4.3b: capture the extension-word VALUES (D2)");
        sb.AppendLine("            int extWords = 0;");
        sb.AppendLine("            // M4.5b: the immediate forms (ADDI/SUBI/ANDI/ORI/EORI/CMPI) carry a LEADING #imm");
        sb.AppendLine("            // extension word(s) BEFORE the EA's own words: .b/.w = 1 word, .l = 2 words. The");
        sb.AppendLine("            // walk fetches them FIRST (stream order), so ext[0..immCount-1] = imm, then the EA's.");
        sb.AppendLine("            if (IsImmediateForm(f.OpIndex))");
        sb.AppendLine("            {");
        sb.AppendLine("                int immWords = size == 2u ? 2 : 1;");
        sb.AppendLine("                for (int w = 0; w < immWords; w++)");
        sb.AppendLine("                {");
        sb.AppendLine("                    ushort iw = (ushort)stream.NextUnit();");
        sb.AppendLine("                    switch (w) { case 0: e0 = iw; break; default: e1 = iw; break; }");
        sb.AppendLine("                }");
        sb.AppendLine("                extWords = immWords;");
        sb.AppendLine("            }");
        sb.AppendLine("            int eaExt = ExtensionWordCount(eaMode, eaReg, size);      // M4.3a Task 4: operand-computed");
        sb.AppendLine("            for (int w = 0; w < eaExt; w++)");
        sb.AppendLine("            {");
        sb.AppendLine("                ushort ew = (ushort)stream.NextUnit();   // big-endian word (the stream composes BE)");
        sb.AppendLine("                switch (extWords + w) { case 0: e0 = ew; break; case 1: e1 = ew; break; case 2: e2 = ew; break; default: e3 = ew; break; }");
        sb.AppendLine("            }");
        sb.AppendLine("            extWords += eaExt;");
        sb.AppendLine("            // M4.5a (deferred D5): MOVE/MOVEA have a SECOND EA (dest, bits 11-6, mode/reg swapped).");
        sb.AppendLine("            if (IsMoveFamily(f.OpIndex))");
        sb.AppendLine("            {");
        sb.AppendLine("                uint dstReg  = (operword >> 9) & 7u;   // bits 11-9");
        sb.AppendLine("                uint dstMode = (operword >> 6) & 7u;   // bits 8-6");
        sb.AppendLine("                int dstExt = ExtensionWordCount(dstMode, dstReg, size);");
        sb.AppendLine("                for (int w = 0; w < dstExt; w++)");
        sb.AppendLine("                {");
        sb.AppendLine("                    ushort ew = (ushort)stream.NextUnit();");
        sb.AppendLine("                    switch (extWords + w) { case 0: e0 = ew; break; case 1: e1 = ew; break; case 2: e2 = ew; break; default: e3 = ew; break; }");
        sb.AppendLine("                }");
        sb.AppendLine("                extWords += dstExt;");
        sb.AppendLine("            }");
        sb.AppendLine("            int len = stream.UnitsConsumed * stream.UnitBytes;        // COMPUTED — words × 2");
        sb.AppendLine("            var ext = new CpuEmulator.Core.Jit.ExtensionWords(e0, e1, e2, e3, extWords);");
        sb.AppendLine("            return new CpuEmulator.Core.Jit.DecodeResult(key, len, CpuEmulator.Core.Jit.DecodedOperands.None, ext, (ushort)operword);");
        sb.AppendLine("        }");
        sb.AppendLine("        // No field op matched ⇒ the illegal-instruction path (the Undefined sentinel; M4.5 vectors it).");
        sb.AppendLine("        int illegalLen = stream.UnitsConsumed * stream.UnitBytes;     // 2 (the operword) — the illegal op is one word");
        sb.AppendLine("        return new CpuEmulator.Core.Jit.DecodeResult(0xFFFFFFFFu, illegalLen, CpuEmulator.Core.Jit.DecodedOperands.None, default, (ushort)operword);");
        sb.AppendLine("    }");

        EmitSizeMapHelper(sb);            // MapSize(sizeBits, enc) — Standard vs Move (C4)
        EmitExtensionWordCount(sb);       // ExtensionWordCount(mode, reg, size) — Task 4 (C5)
        EmitIsMoveFamily(sb, grammar);    // M4.5a: the two-EA MOVE/MOVEA length predicate (deferred D5)
        EmitIsImmediateForm(sb, grammar); // M4.5b: the leading-#imm-word ALU immediate-form predicate
        EmitIsAddressRegVariant(sb, grammar); // M4.5b: the ADDA/SUBA/CMPA .w/.l size remap predicate
        EmitM68kEa(sb);                   // M4.3b: the EA-compute helper + the address-register accessors

        // DescriptorFor reuses the keyed dictionary (emitted by EmitKeyedDescriptorTable); 0xFFFFFFFF →
        // Undefined sentinel. (For M4.3a the grammar CPU has no descriptor rows yet — every matched key
        // resolves to Undefined too; the proof asserts the KEY shape + the computed length, not a live op.)
        sb.AppendLine();
        sb.AppendLine("    public static CpuEmulator.Core.Jit.OpcodeDescriptor DescriptorFor(uint operationKey)");
        sb.AppendLine("        => JitDescriptorsByKey.TryGetValue(operationKey, out var d)");
        sb.AppendLine("            ? d : CpuEmulator.Core.Jit.OpcodeDescriptor.Undefined((byte)operationKey);");
    }

    /// <summary>Emit MapSize(sizeBits, enc): a field op's size bits → an OperandSize index (0=b,1=w,2=l).</summary>
    private static void EmitSizeMapHelper(StringBuilder sb)
    {
        sb.AppendLine();
        sb.AppendLine("    /// <summary>Map a field op's size bits to an OperandSize index (0=b,1=w,2=l). Standard");
        sb.AppendLine("    /// (enc 0): 00=b,01=w,10=l. Move (enc 1, the MOVE outlier): 01=b,11=w,10=l (C4).</summary>");
        sb.AppendLine("    private static uint MapSize(uint bits, int enc) => enc == 1");
        sb.AppendLine("        ? bits switch { 1u => 0u, 3u => 1u, 2u => 2u, _ => 0u }   // Move: 01=b,11=w,10=l");
        sb.AppendLine("        : bits switch { 0u => 0u, 1u => 1u, 2u => 2u, _ => 0u };  // Standard: 00=b,01=w,10=l");
    }

