            : string.Join(" || ", immIndices.Select(i => $"opIndex == {i}u")) + ";");
    }

    /// <summary>M4.5b: the address-reg variants (ADDA/SUBA/CMPA) whose 1-bit opmode size field (bit 8: 0=.w,
    /// 1=.l) the Standard MapSize yields as index 0/1; the decode walk remaps it to the real .w/.l index (1/2)
    /// so the extension-word count + EA magnitude + (operation,size) key reflect the true operand size.</summary>
    private static void EmitIsAddressRegVariant(StringBuilder sb, FieldGrammarModel grammar)
    {
        var idx = new System.Collections.Generic.List<int>();
        for (int i = 0; i < grammar.Ops.Length; i++)
            if (grammar.Ops[i].Operation is "ADDA" or "SUBA" or "CMPA") idx.Add(i);
        sb.AppendLine();
        sb.Append("    private static bool IsAddressRegVariant(uint opIndex) => ");
        sb.AppendLine(idx.Count == 0
            ? "false;"
            : string.Join(" || ", idx.Select(i => $"opIndex == {i}u")) + ";");
    }

    /// <summary>M4.3a Task 4 (C5): emit ExtensionWordCount(eaMode, eaReg, size) — the (ea-mode, size)
    /// extension-word count (the operand-computed-length core).</summary>
    private static void EmitExtensionWordCount(StringBuilder sb)
    {
        sb.AppendLine();
        sb.AppendLine("    /// <summary>M4.3a (ADR 0004 Decision 1 / C5): the extension-word count an EA mode consumes,");
        sb.AppendLine("    /// mode-AND-size dependent (the operand-computed length core). mode = EA bits 5-3, reg = 2-0,");
        sb.AppendLine("    /// size = 0/1/2 (b/w/l). mode 7 (reg-selected): 0=abs.w(1), 1=abs.l(2), 2=d16(PC)(1),");
        sb.AppendLine("    /// 3=d8(PC,Xn)(1), 4=#imm(1 for b/w, 2 for l). This table is shared with M4.3b (which READS");
        sb.AppendLine("    /// the same extension words to compute the EA address).</summary>");
        sb.AppendLine("    private static int ExtensionWordCount(uint eaMode, uint eaReg, uint size) => eaMode switch");
        sb.AppendLine("    {");
        sb.AppendLine("        0u or 1u or 2u or 3u or 4u => 0,   // Dn / An / (An) / (An)+ / -(An): no extension word");
        sb.AppendLine("        5u or 6u => 1,                     // d16(An) / d8(An,Xn): one extension word");
        sb.AppendLine("        7u => eaReg switch                 // mode 7: the register sub-field selects the form");
        sb.AppendLine("        {");
        sb.AppendLine("            0u => 1,                       // abs.w");
        sb.AppendLine("            1u => 2,                       // abs.l");
        sb.AppendLine("            2u => 1,                       // d16(PC)");
        sb.AppendLine("            3u => 1,                       // d8(PC,Xn)");
        sb.AppendLine("            4u => size == 2u ? 2 : 1,      // #imm: .l = 2 words, .b/.w = 1 (the size-dependence)");
        sb.AppendLine("            _  => 0,                       // illegal mode-7 register (M4.5 vectors)");
        sb.AppendLine("        },");
        sb.AppendLine("        _ => 0,");
        sb.AppendLine("    };");
    }

    /// <summary>M4.3b (ADR 0004 Decision 2): emit the 68000 EA-compute. Given eaMode (bits 5-3), eaReg
    /// (2-0), the size index (0/1/2 = b/w/l), the extension words, and a pureEa flag (LEA/PEA — compute the
    /// address, do NOT perform the (An)+/-(An) write-back), compute the 32-bit EA into __ea. For (An)+
    /// (mode 3) and -(An) (mode 4) mutate the address register by the size magnitude (.b→1/.w→2/.l→4) with
    /// the A7 ±2 special case (register 7 moves by 2 even for .b — D4), in the correct order: PostInc reads
    /// An THEN adds; PreDec subtracts THEN reads (D3). Reuses the EmitZ80IndexedEa displacement shape for
    /// d16(An)/d8(An,Xn)/d16(PC)/d8(PC,Xn). Address registers are read/written via Areg(reg)/SetAreg(reg,v)
    /// (the An fields by name — A7 is a plain register on the synthetic spec; the real banking is M4.5).
    /// Emitted ONLY on the field-grammar path (called from EmitFieldDecodeWalk), so 6502/Z80 never get it
    /// (byte-identity, D5). Marked internal so the test assembly could unit-test it (mirrors
    /// EmitZ80IndexedEa; InternalsVisibleTo("CpuEmulator.Tests")).</summary>
    internal static void EmitM68kEa(StringBuilder sb)
    {
        sb.AppendLine();
        sb.AppendLine("    /// <summary>Compute the 68000 effective address (M4.3b, ADR 0004 Decision 2).</summary>");
        sb.AppendLine("    private uint ComputeEa(uint eaMode, uint eaReg, uint size, CpuEmulator.Core.Jit.ExtensionWords ext, bool pureEa)");
        sb.AppendLine("    {");
        sb.AppendLine("        uint mag = size == 0u ? 1u : size == 1u ? 2u : 4u;            // .b/.w/.l magnitude");
        sb.AppendLine("        if (eaReg == 7u && eaMode is 3u or 4u && mag == 1u) mag = 2u; // A7 ±2 (stack word-align — D4)");
        sb.AppendLine("        switch (eaMode)");
        sb.AppendLine("        {");
        sb.AppendLine("            case 0u: return 0u;                                        // Dn — register direct (no memory EA)");
        sb.AppendLine("            case 1u: return Areg(eaReg);                               // An — register direct");
        sb.AppendLine("            case 2u: return Areg(eaReg);                               // (An)");
        sb.AppendLine("            case 3u:                                                   // (An)+ : read An, THEN An += mag (D3)");
        sb.AppendLine("            {");
        sb.AppendLine("                uint ea = Areg(eaReg);");
        sb.AppendLine("                if (!pureEa) SetAreg(eaReg, ea + mag);");
        sb.AppendLine("                return ea;");
        sb.AppendLine("            }");
        sb.AppendLine("            case 4u:                                                   // -(An) : An -= mag FIRST, THEN read (D3)");
        sb.AppendLine("            {");
        sb.AppendLine("                uint ea = Areg(eaReg) - mag;");
        sb.AppendLine("                if (!pureEa) SetAreg(eaReg, ea);");
        sb.AppendLine("                return ea;");
        sb.AppendLine("            }");
        sb.AppendLine("            case 5u: return unchecked(Areg(eaReg) + (uint)(short)ext[0]);   // d16(An) — signed 16-bit disp");
        sb.AppendLine("            case 6u: return ComputeBriefIndex(Areg(eaReg), ext[0]);    // d8(An,Xn) — brief extension word");
        sb.AppendLine("            case 7u: return eaReg switch                               // mode 7 — register selects the form");
        sb.AppendLine("            {");
        sb.AppendLine("                0u => (uint)(short)ext[0],                             // abs.w — sign-extended 16-bit");
        sb.AppendLine("                1u => ((uint)ext[0] << 16) | ext[1],                   // abs.l — two words, high first");
        sb.AppendLine("                2u => unchecked(PcForEa + (uint)(short)ext[0]),        // d16(PC)");
        sb.AppendLine("                3u => ComputeBriefIndex(PcForEa, ext[0]),             // d8(PC,Xn)");
        sb.AppendLine("                4u => 0u,                                              // #imm — no address (the value is the ext words)");
        sb.AppendLine("                _ => 0u,                                               // illegal mode-7 reg (M4.5 vectors)");
        sb.AppendLine("            };");
        sb.AppendLine("            default: return 0u;");
        sb.AppendLine("        }");
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine("    /// <summary>Read address register An by index (0-7 → A0..A7). A7 is a plain register on the");
        sb.AppendLine("    /// synthetic spec; the real SR-S-bit banking over USP/SSP is M68000Cpu's (M4.5).</summary>");
        sb.AppendLine("    private uint Areg(uint reg) => reg switch { 0u=>A0,1u=>A1,2u=>A2,3u=>A3,4u=>A4,5u=>A5,6u=>A6,_=>A7 };");
        sb.AppendLine();
        sb.AppendLine("    /// <summary>Write address register An by index (0-7 → A0..A7) — the (An)+/-(An) write-back (D3/D4).</summary>");
        sb.AppendLine("    private void SetAreg(uint reg, uint v) { switch(reg){ case 0u: A0=v; break; case 1u: A1=v; break; case 2u: A2=v; break; case 3u: A3=v; break; case 4u: A4=v; break; case 5u: A5=v; break; case 6u: A6=v; break; default: A7=v; break; } }");
        sb.AppendLine();
        sb.AppendLine("    /// <summary>The PC a PC-relative EA (d16(PC)/d8(PC,Xn)) is computed from: the address of the EA's");
        sb.AppendLine("    /// first extension word = the operword address + 2 (M4.5a). Step captures it before advancing the");
        sb.AppendLine("    /// live PC past the whole instruction; defaults to the live PC for the synthetic EA-compute probe");
        sb.AppendLine("    /// (which sets PC to the operword address directly and reads back PcForEa without a Step).</summary>");
        sb.AppendLine("    private uint _eaPcBase;");
        sb.AppendLine("    private uint PcForEa => _eaPcBase != 0u ? _eaPcBase : PC;");
        sb.AppendLine();
        sb.AppendLine("    /// <summary>Decode the brief extension word (d8(An,Xn)/d8(PC,Xn)) — M4.5a wires the full index");
        sb.AppendLine("    /// (D5, pulled forward from M4.3b's displacement-only stub). The brief format: bit 15 = D/A (0=Dn,");
        sb.AppendLine("    /// 1=An), bits 14-12 = index register, bit 11 = W/L (0=sign-extended low word, 1=full long), bits");
        sb.AppendLine("    /// 10-9 = scale (0 on the 68000), bits 7-0 = signed 8-bit displacement. EA = base + disp + index.</summary>");
        sb.AppendLine("    private uint ComputeBriefIndex(uint baseAddr, ushort ext)");
        sb.AppendLine("    {");
        sb.AppendLine("        int disp = (sbyte)(byte)ext;                       // signed 8-bit displacement (low byte)");
        sb.AppendLine("        uint idxReg = (uint)((ext >> 12) & 7);            // bits 14-12: index register number");
        sb.AppendLine("        uint idxVal = (ext & 0x8000) != 0 ? Areg(idxReg) : Dreg(idxReg);   // bit 15: An vs Dn");
        sb.AppendLine("        if ((ext & 0x0800) == 0) idxVal = unchecked((uint)(int)(short)(ushort)idxVal);  // bit 11: .w sign-extends");
        sb.AppendLine("        return unchecked(baseAddr + (uint)disp + idxVal);");
        sb.AppendLine("    }");
